"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 행렬의 덧셈
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12950
    풀이일자   : 2026-06-25
===================================================================================
[문제 요약]
    행과 열의 크기가 같은 두 행렬 arr1, arr2의 같은 위치 원소끼리 더한 결과 반환

    제약 조건
        - arr1, arr2의 행/열 길이: 500 이하
        - 두 행렬의 크기 동일 보장
        - 최대 원소 수: 500 × 500 = 250,000개
===================================================================================
[입출력 예시]
    arr1          | arr2          | return
    --------------|---------------|--------
    [[1,2],[2,3]] | [[3,4],[5,6]] | [[4,6],[7,9]]
    [[1],[2]]     | [[3],[4]]     | [[4],[6]]
===================================================================================
[내 초기 풀이]
    solution_mine_one: 이중 for 루프 + zip + temp 리스트 누적
        zip(arr1, arr2)로 행 추출, zip(x, y)로 원소 추출
        temp 임시 리스트에 원소합 누적 후 answer에 추가

    solution_mine_two: 중첩 리스트 컴프리헨션으로 원라인 반환
        [i+j for i,j in zip(x,y)] → 각 행의 원소합 리스트
        [[...] for x,y in zip(arr1,arr2)] → 전체 행렬 결과

[개선 포인트]
    solution_mine_one: 개선 필요 없음 - Sub
        각 단계가 명시적으로 분리되어 가독성 우위
        temp, answer 변수로 중간 상태 확인 가능
    solution_mine_two: 개선 필요 없음 - Best
        중첩 리스트 컴프리헨션으로 간결하게 표현
        temp, answer 변수 없이 바로 결과 생성 후 반환
===================================================================================
[zip 활용 근거]
    같은 인덱스 원소끼리 연산이 필요한 상황에서 zip이 가장 적합:
        zip(arr1, arr2): 두 행렬에서 같은 행 인덱스의 리스트 쌍 추출
        zip(x, y)      : 같은 행에서 같은 열 인덱스의 원소 쌍 추출

    손 추적 ([[1,2],[2,3]], [[3,4],[5,6]]):
        zip(arr1, arr2) → ([1,2],[3,4]), ([2,3],[5,6])
        x=[1,2], y=[3,4]: zip(x,y) → (1,3),(2,4) → [1+3, 2+4] = [4,6]
        x=[2,3], y=[5,6]: zip(x,y) → (2,5),(3,6) → [2+5, 3+6] = [7,9]
        → [[4,6],[7,9]] ✓

[중첩 리스트 컴프리헨션 읽는 방향]
    [[i+j for i,j in zip(x,y)] for x,y in zip(arr1,arr2)]

    읽는 순서: 바깥 for문 먼저 → 안쪽 for문 나중
        1. for x,y in zip(arr1,arr2): 행 단위로 순회
        2. [i+j for i,j in zip(x,y)]: 각 행의 원소합 리스트 생성
        3. 전체: 각 행의 원소합 리스트를 모은 2차원 배열
===================================================================================
[복잡도 분석]
    R = 행 수 (최대 500)
    C = 열 수 (최대 500)

    Mine_one - 시간: O(R×C) | 공간: O(R×C) - 결과 행렬 저장
    Mine_two - 시간: O(R×C) | 공간: O(R×C) - 결과 행렬 저장
    Best     - 시간: O(R×C) | 공간: O(R×C) - Mine_two와 동일, 주석 보강
    Sub      - 시간: O(R×C) | 공간: O(R×C) - Mine_one과 동일, 주석 보강

    모든 풀이 동일한 복잡도 O(R×C)
    최대 250,000번 연산 → 충분히 통과
    알고리즘 최적화 여지 없음: 모든 원소를 반드시 1회씩 접근해야 함
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution one - 이중 for 루프 + zip + temp 리스트
# =================================================================================
def solution_mine_one(arr1: List[List[int]], arr2: List[List[int]]) -> List[List[int]]:
    """
    이중 for 루프와 zip으로 같은 위치 원소끼리 더하는 초기 풀이

    핵심:
        zip(arr1, arr2): 두 행렬의 같은 행 인덱스 리스트 쌍 동시 추출
        zip(x, y): 같은 행에서 같은 열 인덱스 원소 쌍 동시 추출
        temp: 각 행의 덧셈 결과를 담는 임시 리스트
        answer: 전체 행렬 결과를 담는 리스트

    개선 가능:
        temp, answer 변수 → 중첩 리스트 컴프리헨션으로 제거 가능
    """
    answer = []

    for x, y in zip(arr1, arr2):       # 같은 행 인덱스의 리스트 쌍 추출
        temp = []
        for i, j in zip(x, y):         # 같은 열 인덱스의 원소 쌍 추출
            temp.append(i + j)
        answer.append(temp)

    return answer


# =================================================================================
# Mine solution two - 중첩 리스트 컴프리헨션
# =================================================================================
def solution_mine_two(arr1: List[List[int]], arr2: List[List[int]]) -> List[List[int]]:
    """
    중첩 리스트 컴프리헨션으로 mine_one을 원라인으로 압축한 풀이

    mine_one 대비:
        temp, answer 변수 제거
        외부 컴프리헨션: for x,y in zip(arr1,arr2) → 행 단위 순회
        내부 컴프리헨션: i+j for i,j in zip(x,y)  → 열 단위 원소합

    읽는 순서: 바깥 for문(행) 먼저 → 안쪽 for문(열) 나중
    """
    return [[i + j for i, j in zip(x, y)] for x, y in zip(arr1, arr2)]


# =================================================================================
# Best solution - 중첩 리스트 컴프리헨션 (mine_two 주석 보강)
# =================================================================================
def solution_best(arr1: List[List[int]], arr2: List[List[int]]) -> List[List[int]]:
    """
    중첩 리스트 컴프리헨션으로 행렬 덧셈을 표현하는 최적 풀이

    mine_two와 동일한 로직, 근거 주석 보강:
        zip의 역할: 두 이터러블에서 같은 인덱스 원소를 쌍으로 추출
        이중 zip 구조: 행렬의 2차원 구조를 자연스럽게 표현
        중첩 컴프리헨션: temp, answer 변수 없이 결과를 직접 생성

    알고리즘 최적화 여지 없음:
        모든 원소를 반드시 1회씩 접근 → O(R×C)가 하한
    """
    return [[i + j for i, j in zip(x, y)] for x, y in zip(arr1, arr2)]


# =================================================================================
# Sub solution - 이중 for 루프 (mine_one 주석 보강)
# =================================================================================
def solution_sub(arr1: List[List[int]], arr2: List[List[int]]) -> List[List[int]]:
    """
    이중 for 루프로 각 단계를 명시적으로 표현하는 서브 풀이

    Best 대비 특징:
        각 단계(행 추출 → 열 추출 → 덧셈 → 누적)가 변수로 분리
        행렬 덧셈의 수학적 정의(같은 행, 같은 열 원소끼리 합산)가
        코드 구조에 직접적으로 드러남
        중간 상태(temp) 확인 가능 → 디버깅 용이
    """
    answer = []

    for x, y in zip(arr1, arr2):       # 같은 행 추출
        temp = []
        for i, j in zip(x, y):         # 같은 열 원소 추출
            temp.append(i + j)         # 원소합 누적
        answer.append(temp)            # 행 결과 누적

    return answer


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[List[int]], List[List[int]], List[List[int]]]] = [
        # (arr1, arr2, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # [[1,2],[2,3]] + [[3,4],[5,6]]:
        #   행0: [1+3, 2+4] = [4,6]
        #   행1: [2+5, 3+6] = [7,9]
        #   → [[4,6],[7,9]]
        ([[1,2],[2,3]], [[3,4],[5,6]], [[4,6],[7,9]]),
        # [[1],[2]] + [[3],[4]]:
        #   행0: [1+3] = [4]
        #   행1: [2+4] = [6]
        #   → [[4],[6]]
        ([[1],[2]],    [[3],[4]],    [[4],[6]]),
        # 추가 케이스:
        # 1×1 행렬: [[5]] + [[3]] → [[8]]
        ([[5]],        [[3]],        [[8]]),
        # 음수 포함: [[-1,2]] + [[1,-2]] → [[0,0]]
        ([[-1,2]],     [[1,-2]],     [[0,0]]),
    ]

    solutions = [
        ("Mine_one (이중for+zip)", solution_mine_one),
        ("Mine_two (중첩컴프리) ", solution_mine_two),
        ("Best     (중첩컴프리) ", solution_best),
        ("Sub      (이중for+zip)", solution_sub),
    ]

    # ----------------------------------------------------------------------------------
    # 워밍업 (Warm-up) — 워밍업 B 방식
    # ----------------------------------------------------------------------------------
    # [왜 워밍업이 필요한가]
    #   time.perf_counter()는 단 1회 측정이라 아래 오버헤드가 결과에 그대로 반영됨:
    #     주 오버헤드: Python VM(인터프리터) 첫 진입 시 메모리 할당자(obmalloc) 초기화
    #                 CPU 파이프라인 채움, 인터프리터 내부 상태 활성화
    #     부 오버헤드: 각 함수 첫 호출 시 PyFrameObject 생성
    #                 난이도가 높은 문제일수록 내부 중첩 함수가 많아져 부 오버헤드 증가
    #   → 워밍업 없이는 특정 TC에서 수십~수백 배 느린 값이 튀어나와 비교를 왜곡
    #
    # [timeit을 쓰지 않는 이유]
    #   timeit은 다회 반복 평균으로 오버헤드를 희석하는 방식이나 이 구조에 맞지 않음:
    #     lambda 방식: lambda 호출 + 클로저 변수 조회 오버헤드가 N번 누적
    #                  → 측정값에 알고리즘 외 비용 포함
    #     globals 방식: timeit.timeit("func(a,b)", globals=globals())
    #                   → test_cases, arr1, arr2가 지역 변수라 globals()에 미포함
    #                   → NameError 발생, env 병합 시 코드 복잡도 급증
    #   → test_cases 구조를 유지하면서 워밍업으로 오버헤드를 직접 제거하는 방식 채택
    #
    # [워밍업 A/B/C 비교 및 B 선택 이유]
    #   워밍업 A (모든 함수 × 모든 케이스): 불필요하게 많은 실행, 과도한 워밍업
    #   워밍업 B (모든 함수 × 첫 케이스):   주/부 오버헤드 모두 해소, 결과 A와 동일
    #   워밍업 C (첫 함수만 × 첫 케이스):   VM 활성화(주)는 해소되나
    #                                        각 함수별 PyFrameObject(부) 미해소
    #                                        현재 함수 규모가 작아 C도 동작하지만
    #                                        향후 중첩 함수 증가 시 측정값 왜곡 가능
    #   → B 선택: 모든 풀이 함수를 1회씩 실행해 주/부 오버헤드 완전 해소
    #             향후 복잡한 문제에서 중첩 함수 규모가 커져도 동일하게 대비 가능
    _arr1, _arr2, _ = test_cases[0]    # 워밍업 전용 변수 (측정용 변수와 혼동 방지)
    for _, func in solutions:
        func(_arr1, _arr2)              # 각 함수 1회 실행 → 주/부 오버헤드 해소
    # ----------------------------------------------------------------------------------

    print("=" * 64)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (arr1, arr2, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(arr1, arr2)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
