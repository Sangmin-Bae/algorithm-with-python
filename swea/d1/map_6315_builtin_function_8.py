import time


# ================================================================================
# Mine solution one - map + 람다식 (제곱 연산자)
# ================================================================================
def solution_mine_one(numbers: list[int]) -> list[int]:
    """
    map 함수와 람다식으로 각 원소의 제곱 값을 리스트로 반환하는 직접 작성한 풀이

    핵심:
        lambda x: x ** 2 : 원소 x를 제곱한 값 반환
        map은 각 원소에 람다를 적용한 map 객체(이터레이터)를 반환
        list()로 변환해 리스트로 반환
    """
    return list(map(lambda x: x ** 2, numbers))


# ================================================================================
# Best solution - map + 람다식 (곱셈)
# ================================================================================
def solution_best(numbers: list[int]) -> list[int]:
    """
    제곱을 곱셈 x * x로 표현한 최적 풀이

    핵심:
        lambda x: x * x : 정수 입력에서 x ** 2와 결과 동일
        실측에서 x ** 2, pow(x, 2)보다 일관되게 빠름
    """
    return list(map(lambda x: x * x, numbers))


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (numbers, 기댓값) - 전부 손 계산
        (list(range(1, 11)), [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]),  # 공식 예시
        ([], []),                                                      # 빈 리스트 경계
        ([0], [0]),                                                    # 0 경계
        ([-3, -1, 0, 2], [9, 1, 0, 4]),                                # 음수 포함
        ([1_000_000], [1_000_000_000_000]),                            # 큰 값
        ([7] * 1_000_000, [49] * 1_000_000),                           # 대용량: 7의 제곱은 전부 49
    ]

    solutions = [
        ("Mine (x ** 2)", solution_mine_one),
        ("Best (x * x)",  solution_best),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
