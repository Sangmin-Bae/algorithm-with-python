"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 3진법 뒤집기
    유형       : Math / String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/68935
    풀이일자   : 2025-05-25
================================================================================
[문제 요약]
    자연수 n을 3진법으로 변환 -> 앞뒤 뒤집기 -> 10진법으로 변환하여 반환

    제약 조건
        - 1 이상 100,000,000 이하인 자연수
================================================================================
[입출력 예시]
    n   | n(3진법) | 뒤집기  | result
    ----|---------|--------|-------
    45  | 1200    | 0021   | 7
    125 | 11122   | 22111  | 229
================================================================================
[진법 변환 원리 - 왜 나머지가 낮은 자리부터 나오는가]
    10진수 45를 3진법으로 변환하는 표준 과정:
        45 ÷ 3 = 15 ... 나머지 0  ← 1의 자리 (3⁰)
        15 ÷ 3 = 5  ... 나머지 0  ← 3의 자리 (3¹)
        5  ÷ 3 = 1  ... 나머지 2  ← 9의 자리 (3²)
        1  ÷ 3 = 0  ... 나머지 1  ← 27의 자리 (3³)

    나머지 누적 순서: "0021" (낮은 자리 -> 높은 자리)
    올바른 3진법:     "1200" (높은 자리 -> 낮은 자리)
    -> 표준 변환은 [::-1] 뒤집기 필요
================================================================================
[핵심 발상 - 뒤집기 소거]
    표준 파이프라인:
        n -> 나머지 누적("0021") -> [::-1]뒤집기("1200") -> 문제조건 뒤집기("0021") -> int(,3)

    두 번의 뒤집기가 서로 상쇄됨: reverse(reverse(x)) = x

    소거 후:
        n -> 나머지 누적("0021") -> int("0021", 3) = 7

    진법 변환 과정의 "뒤집기 필요"와
    문제 조건의 "3진법 수 뒤집기"가 정확히 상쇄되어 소거
================================================================================
[내 초기 풀이]
    뒤집기 소거 발상 적용, 문자열 += 방식으로 나머지 누적

[개선 포인트]
    ternary += str(rest): 문자열 불변(immutable)이라 += 반복 시 매번 새 객체 생성
    -> digits 리스트에 append 후 ''.join() 으로 한 번에 결합
    -> 이 문제에서는 최대 17자리라 실질적 차이 없으나 올바른 습관

[Sub 풀이 의도]
    뒤집기 소거 없이 표준 파이프라인을 그대로 구현
    "왜 Mine/Best에서 뒤집기가 소거됐는가"를 코드로 시각화
================================================================================
[복잡도 분석]
    N = n (최대 10⁸)
    3진법 자릿수 = log₃(N) ≈ log₃(10⁸) ≈ 17

    Mine - 시간: O(log₃N) | 공간: O(log₃N) — 문자열 += 방식
    Best - 시간: O(log₃N) | 공간: O(log₃N) — 리스트 + join 방식
    Sub  - 시간: O(log₃N) | 공간: O(log₃N) — 표준 변환 2회 뒤집기

    N ≤ 10⁸이어도 최대 17번 반복 → 사실상 O(1)
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution - 뒤집기 소거 + 문자열 += 방식
# ==============================================================================
def solution_mine(n: int) -> int:
    """
    뒤집기 소거 발상을 적용한 초기 풀이

    핵심 발상:
        - divmod로 3으로 나눈 나머지를 순서대로 누적
        - 진법 변환의 "뒤집기"와 문제 조건의 "뒤집기"가 상쇄 -> 소거
        - 나머지 누적 결과를 그대로 int(..., 3)으로 변환

    개선 전 상태:
        - ternary += str(rest): 문자열 불변이라 매번 새 객체 생성
            최대 17회라 실질적 차이 없으나 리스트 + join이 올바른 습관
    """
    ternary = ""

    while n > 0:
        n, rest = divmod(n, 3)
        ternary += str(rest)        # 낮은 자리부터 누적(뒤집기 소거로 그대로 사용)

    return int(ternary, 3)          # 3진법 문자열을 10진법으로 변환


# ==============================================================================
# Best solution - 뒤집기 소거 + 리스트 + join
# ==============================================================================
def solution_best(n: int) -> int:
    """
    뒤집기 소거 + 리스트 append + join으로 개선한 최적 풀이

    Mine 대비 개선:
        - 문자열 += -> digits 리스트 append + ''.join()
        - 리스트 append: O(1) 분할 상환
        - join: 한 번에 결합 -> 불필요한 중간 객체 생성 없음

    뒤집기 소거 원리:
        나머지 누적 순서 = 낮은 자리부터 = 뒤집힌 3진법
        문제 조건 = 3진법을 뒤집어라
        reverse(reverse(x)) = x -> 두 뒤집기 상태 -> 누적 결과 그대로 사용
    """
    digits = []

    while n > 0:
        n, rest = divmod(n, 3)
        digits.append(str(rest))     # 낮은 자리부터 리스트에 누적

    return int(''.join(digits), 3)   # 리스트를 문자열로 결합 후 10진법 변환


# ==============================================================================
# Sub solution - 표준 파이프라인 (뒤집기 소거 없이 명시적 구현)
# ==============================================================================
def solution_sub(n: int) -> int:
    """
    표준 3진법 변환 과정을 그대로 구현해 뒤집기 소거가 왜 성립하는지 보여주는 풀이

    표준 파이프라인:
        1. 나머지 누적 -> 뒤집힌 3진법 ("0021")
        2. [::-1] 뒤집기 -> 올바른 3진법 ("0021")
        3. 문제 조건 뒤집기 -> 다시 뒤집힌 3진법 ("0021")
        4. int(..., 3) -> 10진법

        2번과 3번이 서로 상쇄 -> Mine/Best에서 두 단계 모두 소거
    """
    digits = []

    while n > 0:
        n, rest = divmod(n, 3)
        digits.append(str(rest))        # 낮은 자리부터 누적

    ternary = ''.join(digits[::-1])     # 뒤집어서 올바른 3진법 문자열
    reversed_ternary = ternary[::-1]    # 문제 조건: 3진법 수 뒤집기
    # ↑ 이 두 뒤집기([::-1])가 Mine/Best에서 소거된 핵심 이유

    return int(reversed_ternary, 3)     # 뒤집힌 3진법을 10진법으로 변환


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int]] = [
        # (n, 기댓값)
        (45, 7),  # 기본 예시 1: 1200 → 0021 → 7
        (125, 229),  # 기본 예시 2: 11122 → 22111 → 229
        (1, 1),  # 최솟값: 1(3진법) → 1(뒤집기) → 1
        (3, 1),  # 10(3진법) → 01(뒤집기) → int("01",3) = 1
        (9, 9),  # 100(3진법) → 001(뒤집기) → 1? 아니면? 검증 필요
        (100000000, None),  # 최댓값 (Best로 계산)
    ]

    # 기댓값 검증
    test_cases[4] = (9, solution_best(9))
    test_cases[5] = (100000000, solution_best(100000000))

    solutions = [
        ("Mine (소거+문자열+=)", solution_mine),
        ("Best (소거+리스트)", solution_best),
        ("Sub  (표준파이프라인)", solution_sub),
    ]

    print("=" * 62)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
