import time


# ================================================================================
# Mine solution one - filter + 람다식
# ================================================================================
def solution_mine_one(nums: list[int]) -> list[int]:
    """
    filter 함수와 람다식으로 짝수만 선택해 리스트로 반환하는 직접 작성한 풀이

    핵심:
        lambda x: x % 2 == 0 : 짝수이면 True
        filter는 True인 원소만 통과시키는 이터레이터(filter 객체)를 반환
        list()로 변환해 리스트로 반환
    """
    return list(filter(lambda x: x % 2 == 0, nums))


# ================================================================================
# Best solution - filter + 람다식 (mine_one과 동일 로직)
# ================================================================================
def solution_best(nums: list[int]) -> list[int]:
    """
    mine_one과 동일한 로직의 최적 풀이

    선정 근거:
        조건식 변형(not x % 2, x & 1 == 0, not x & 1) 실측 차이가 최대 약 8%
        가독성과 자료형 일반성(x % 2는 실수도 처리) 기준으로 x % 2 == 0 유지
    """
    return list(filter(lambda x: x % 2 == 0, nums))


# ================================================================================
# 풀이 결과 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (nums, 기댓값) - 전부 손 계산
        (list(range(1, 11)), [2, 4, 6, 8, 10]),                 # 공식 예시
        ([], []),                                               # 빈 리스트 경계
        ([1, 3, 5], []),                                        # 짝수 없음
        ([2, 4, 6], [2, 4, 6]),                                 # 전부 짝수
        ([0, -1, -2, 3], [0, -2]),                              # 0과 음수 경계
        (list(range(1, 1_000_001)), list(range(2, 1_000_001, 2))),  # 대용량
    ]

    solutions = [
        ("Mine (filter+lambda)", solution_mine_one),
        ("Best (filter+lambda)", solution_best),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
