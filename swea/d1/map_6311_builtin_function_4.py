"""
================================================================================
[문제 정보]
    사이트     : SWEA (SW Expert Academy)
    레벨       : D1
    문제명     : 6311. [파이썬 프로그래밍 기초(1) 파이썬의 기본 구조와 기초 문법] 9. 내장함수 4
    유형       : Map (map 함수 + 람다식), Dictionary
    링크       : https://swexpertacademy.com/main/code/problem/problemDetail.do?contestProbId=AWcWDP9a5UYDFAU4&categoryId=AWcWDP9a5UYDFAU4&categoryType=CODE&problemTitle=&orderBy=PASS_RATE&selectCodeLang=ALL&select-1=&pageSize=10&pageIndex=4
    풀이일자   : 2026-10-24
================================================================================
[문제 요약]
    A, B, C, D로 이루어진 문자열에서 A는 4점, B는 3점, C는 2점, D는 1점일 때
    문자열에 사용된 알파벳 점수의 총합을 구함

    입력 방식 : 입력 없음 (문자열이 지문에 고정)
    적용 방식 : 고정된 문자열 → 매개변수 s, output → 반환값
    지문 조건 : map 함수와 람다식 사용
================================================================================
[입출력 예시]
    공식 예시
    s (70자)                                                              | return
    ----------------------------------------------------------------------|-------
    "ADCBBBBCABBCBDACBDCAACDDDCAABABDBCBCBDBDBDDABBAAAAAAADADBDBCBDABADCADC" | 184

    문자별 개수: A 20개, B 21개, C 12개, D 17개
    → 20 * 4 + 21 * 3 + 12 * 2 + 17 * 1 = 80 + 63 + 24 + 17 = 184

    자체 검증 케이스 (전부 손 계산)
    s                | return
    -----------------|----------------------
    ""               | 0
    "A"              | 4
    "ABCD"           | 10                 (4 + 3 + 2 + 1)
    "DDDD"           | 4                  (1 * 4)
    "AAAA"           | 16                 (4 * 4)
    "ABCDABCD"       | 20                 (10 * 2)
    "ABCD" * 250000  | 2500000            (10 * 250000, 닫힌 식으로 기댓값 계산)
================================================================================
[풀이 전략]
    핵심: 문자 → 점수 변환 후 합산
        map(함수, s) : 문자열 s의 문자를 하나씩 함수에 넣어 점수로 변환 (이터레이터)
        sum(...) : 변환된 점수를 모두 더함
        문자열은 문자 단위로 순회되므로 각 원소가 문자 한 개

    풀이 구성:
        mine_one : 점수표 딕셔너리 + map + 람다식 (직접 작성한 풀이)
                   lambda x: score[x] : 문자 x의 점수를 딕셔너리에서 조회
        best     : mine_one과 동일 (지문 조건을 만족하는 더 나은 변형이 없음)
        sub      : 딕셔너리 대신 아스키 코드로 점수 계산
                   lambda x: ord('E') - ord(x) : 'A'(65)는 69 - 65 = 4, 'D'(68)는 69 - 68 = 1
                   문자 순서(A→D)와 점수(4→1)가 1씩 어긋나 있는 구조를 이용
                   점수표가 이 규칙을 벗어나면 사용할 수 없음

    손 추적 (문자열 "ABCD"):
        map: 'A' → 4, 'B' → 3, 'C' → 2, 'D' → 1
        sum: 4 + 3 + 2 + 1 = 10 ✓
================================================================================
[개선 포인트]
    solution_mine_one : 개선 여지 작음 - 지문 조건(map + 람다식)을 그대로 구현, 호출마다 점수표를 새로 생성
    solution_best     : mine_one과 동일 로직 - Best
    solution_sub      : 딕셔너리 없이 아스키 코드 차이로 점수 계산 - 점수표가 규칙적일 때 사용 가능
================================================================================
[복잡도 분석]
    n = len(s)

    Mine_one - 시간: O(n) | 공간: O(1) - 문자마다 딕셔너리 조회 1번, 딕셔너리는 4개로 고정
    Best     - 시간: O(n) | 공간: O(1) - mine_one과 동일
    Sub      - 시간: O(n) | 공간: O(1) - 문자마다 ord 호출 2번과 뺄셈 1번
"""

import time


# ================================================================================
# Mine solution one - 점수표 딕셔너리 + map + 람다식
# ================================================================================
def solution_mine_one(s: str) -> int:
    """
    점수표 딕셔너리를 만들고 map과 람다식으로 문자를 점수로 바꿔 합산하는 직접 작성한 풀이

    핵심:
        lambda x: score[x] : 문자 하나를 점수로 변환
        map이 s의 문자를 하나씩 람다식에 전달
        sum으로 변환된 점수를 합산
    """
    score = {'A': 4, 'B': 3, 'C': 2, 'D': 1}

    return sum(map(lambda x: score[x], s))


# ================================================================================
# Best solution - mine_one과 동일 로직
# ================================================================================
def solution_best(s: str) -> int:
    """
    mine_one과 동일한 로직의 최적 풀이

    선정 근거:
        지문 조건(map + 람다식)을 만족하는 변형 중 점수표가 가장 명시적이라 읽기 쉬움
    """
    score = {'A': 4, 'B': 3, 'C': 2, 'D': 1}

    return sum(map(lambda x: score[x], s))


# ================================================================================
# Sub solution - 아스키 코드 차이
# ================================================================================
def solution_sub(s: str) -> int:
    """
    딕셔너리 없이 아스키 코드 차이로 점수를 계산하는 풀이

    핵심:
        ord('E') - ord(x) : 'A'→4, 'B'→3, 'C'→2, 'D'→1
        문자 순서와 점수가 1씩 어긋나는 규칙을 이용
    """
    return sum(map(lambda x: ord('E') - ord(x), s))


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (s, 기댓값) - 전부 손 계산
        ("ADCBBBBCABBCBDACBDCAACDDDCAABABDBCBCBDBDBDDABBAAAAAAADADBDBCBDABADCADC", 184),  # 공식 예시
        ("", 0),                                            # 빈 문자열 경계
        ("A", 4),                                           # 문자 1개
        ("ABCD", 10),                                       # 4 + 3 + 2 + 1
        ("DDDD", 4),                                        # 최저 점수만
        ("AAAA", 16),                                       # 최고 점수만
        ("ABCDABCD", 20),                                   # 10 * 2
        ("ABCD" * 250000, 2500000),                         # 대용량: 10 * 250000
    ]

    solutions = [
        ("Mine (딕셔너리)", solution_mine_one),
        ("Best (딕셔너리)", solution_best),
        ("Sub (ord)", solution_sub),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
