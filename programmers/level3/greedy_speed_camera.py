"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 3
    문제명     : 단속카메라
    유형       : Greedy
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/42884
    풀이일자   : 2026-10-01
===================================================================================
[문제 요약]
    각 차량의 고속도로 진입/진출 지점 routes가 주어질 때
    모든 차량이 단속카메라를 한 번은 만나도록 하는 최소 카메라 수 반환
    진입/진출 지점에 카메라가 있어도 만난 것으로 간주 (경계 포함)

    제약 조건
        - routes 길이(차량 수): 1 이상 10,000 이하
        - 진입/진출 지점: -30,000 이상 30,000 이하
        - 진입 <= 진출 가정 (지문에 명시적 보장 문구는 없으나 예시와 통상 풀이의 전제)
===================================================================================
[입출력 예시]
    routes                                  | return
    ----------------------------------------|-------
    [[-20,-15],[-14,-5],[-18,-13],[-5,-3]]  | 2
    (-15 지점: 1,3번 차량 / -5 지점: 2,4번 차량)
===================================================================================
[핵심 — 진출 시점 정렬이 최선인 이유 (교환 논증)]
    진출 시점 오름차순 정렬 후 첫 차량: [s1, e1] (e1 = 가장 작은 진출 시점)
    어떤 해든 이 차량을 잡으려면 [s1, e1] 안 어딘가(위치 p)에 카메라 필요

    그 카메라를 p -> e1로 옮겨도 잃는 차량 없음:
        p가 잡던 차량 [s, e]는 s <= p <= e
        정렬 때문에 e >= e1, 그리고 p <= e1
        -> s <= p <= e1 <= e  -> e1도 [s, e] 안에 있음

    따라서 "e1에 카메라 설치" 선택은 항상 최선 중 하나
    그 카메라가 잡는 차량을 제거한 나머지 문제에 같은 논리 반복
    (확률적인 "가능성"이 아니라 증명되는 선택)

[코드와 경계 조건의 대응]
    if entry > camera:
        마지막 카메라가 이 차량의 진입보다 앞 -> 못 잡음 -> 진출 시점에 새 카메라
    entry == camera 는 "경계 포함" 조건이라 잡힌 것 -> 등호 없는 > 가 정확
    camera 초기값 -30001: 최소 좌표(-30000)보다 작아 첫 차량이 항상 새 카메라 생성

[풀이2 — 풀이1의 거울상]
    좌표 x를 -x로 뒤집으면 풀이2 = 풀이1
    진입 시점 오름차순 정렬 후 뒤에서부터 순회, 못 잡는 차량의 진입 시점에 설치
    조건 exit < camera 도 경계 포함 처리 (같으면 잡힘)
    camera 초기값 30001: 최대 좌표(30000)보다 큰 값

[구조적 통찰 — 카메라 수 = 서로 겹치지 않는 차량의 수]
    새 카메라가 설치되는 순간의 차량들은 서로 구간이 겹치지 않음 (entry > camera)
    닫힌 구간에서 "모든 구간을 찌르는 최소 점 수 = 서로 겹치지 않는 구간의 최대 개수"

[검증]
    공식 예시 통과 + 무작위 3,000케이스(차량 1~7대, 좌표 -8~8)를
    무차별 대입(모든 카메라 배치 탐색)과 대조 -> 불일치 0건

[실측 결과 — N=10,000, 좌표 -30,000~30,000, 반복 측정 최솟값]
    one (lambda key)            2.157ms
    two (lambda key, 역슬라이스) 2.153ms  <- one과 동률 (정렬 방향은 성능과 무관)
    one (itemgetter key)        1.910ms  <- 약 11% 단축
    two (itemgetter, reversed)  1.936ms

    차이는 key 함수에서 발생: lambda는 원소마다 파이썬 함수 호출,
    itemgetter는 C 레벨 처리 (cmp_to_key 때와 같은 원리)
    절대 차이 약 0.2ms -> 통과 여부와는 무관, 원리 확인 수준

    제3 방향 탐색: 좌표 범위(60,001칸)를 이용한 카운팅 배열 방식
        exit 좌표별 최대 entry를 기록한 뒤 좌표 순으로 스윕
        정렬 방식과 동률 수준, itemgetter 버전은 넘지 못함 -> 채택하지 않음
===================================================================================
[내 초기 풀이]
    solution_mine_one: 진출 시점 오름차순 정렬 + 순방향 스캔
    solution_mine_two: 진입 시점 오름차순 정렬 + 역방향 스캔 (거울상)

[개선 포인트]
    solution_mine_one: 로직 개선 필요 없음 - Best의 기반
                       key를 lambda -> itemgetter로 교체, 내장 함수 exit를 가리는
                       변수명을 end로 변경
    solution_mine_two: 로직 개선 필요 없음 - Sub
                       거울상 발상이 명시적, 성능은 mine_one과 동률
    공통: routes.sort()는 입력 리스트를 제자리에서 변경 (호출자 데이터 부작용)
===================================================================================
[복잡도 분석]
    N = len(routes) (최대 10,000)

    Mine_one - 시간: O(N log N) | 공간: O(1)  - 제자리 정렬 + 단일 스캔
    Mine_two - 시간: O(N log N) | 공간: O(N)  - 역순 슬라이싱 복사
    Best     - 시간: O(N log N) | 공간: O(1)  - Mine_one과 동일
    Sub      - 시간: O(N log N) | 공간: O(N)  - Mine_two와 동일

    정렬이 지배적, 이후 스캔은 O(N)
"""

import time
from operator import itemgetter


# =================================================================================
# Mine solution one - 진출 시점 정렬 + 순방향 스캔
# =================================================================================
def solution_mine_one(routes: list[list[int]]) -> int:
    """
    진출 시점 오름차순 정렬 후 못 잡은 차량의 진출 시점에 카메라를 놓는 초기 풀이

    교환 논증:
        가장 빨리 나가는 차량을 잡으려면 [진입, 진출] 안에 카메라 필요
        그 카메라를 진출 시점으로 옮겨도 잃는 차량 없음 -> 진출 시점이 최선

    entry > camera:
        마지막 카메라가 진입보다 앞 -> 못 잡음 -> 새 카메라
        entry == camera 는 경계 포함이라 잡힘
    """
    answer = 0
    camera = -30001

    routes.sort(key=lambda x: x[1])
    for entry, exit in routes:
        if entry > camera:
            camera = exit
            answer += 1

    return answer


# =================================================================================
# Mine solution two - 진입 시점 정렬 + 역방향 스캔
# =================================================================================
def solution_mine_two(routes: list[list[int]]) -> int:
    """
    진입 시점 오름차순 정렬 후 뒤에서부터 못 잡은 차량의 진입 시점에 카메라를 놓는 풀이

    mine_one의 거울상 (좌표 x -> -x):
        가장 늦게 들어오는 차량의 진입 시점에 카메라를 두는 것이 최선
        exit < camera:
            카메라가 이 차량의 진출보다 뒤 -> 못 잡음 -> 새 카메라
            exit == camera 는 경계 포함이라 잡힘

    routes[::-1] 은 역순 복사본을 만들어 공간 O(N)
    """
    answer = 0
    camera = 30001

    routes.sort(key=lambda x: x[0])
    for entry, exit in routes[::-1]:
        if exit < camera:
            camera = entry
            answer += 1

    return answer


# =================================================================================
# Best solution - 진출 시점 정렬 + itemgetter key
# =================================================================================
def solution_best(routes: list[list[int]]) -> int:
    """
    mine_one의 로직에서 key를 itemgetter로 교체한 최적 풀이

    mine_one 대비 변경점:
        key=lambda x: x[1] -> key=itemgetter(1)
            lambda는 원소마다 파이썬 함수를 호출, itemgetter는 C 레벨 처리
            실측 약 11% 단축 (2.157ms -> 1.910ms, N=10,000)
        변수명 exit -> end : 내장 함수 exit를 가리지 않도록 변경

    정렬 방향(진출/진입)은 성능과 무관하므로 순방향 스캔인 mine_one 계열을 선택
    (역슬라이스 복사 없음, 공간 O(1))
    """
    answer = 0
    camera = -30001

    routes.sort(key=itemgetter(1))
    for entry, end in routes:
        if entry > camera:
            camera = end
            answer += 1

    return answer


# =================================================================================
# Sub solution - 진입 시점 정렬 + 역방향 스캔 (mine_two 주석 보강)
# =================================================================================
def solution_sub(routes: list[list[int]]) -> int:
    """
    mine_two와 동일한 로직, 선정 근거 주석 보강:
        같은 문제를 거울상으로 바라보는 발상이 코드에 명시적
        "가장 늦게 진입하는 차량의 진입 시점에 카메라" = mine_one의 좌우 반전
        실측은 mine_one과 동률 (2.153ms vs 2.157ms)
        Best 대비 역슬라이스 복사로 공간 O(N)
    """
    answer = 0
    camera = 30001

    routes.sort(key=lambda x: x[0])
    for entry, exit in routes[::-1]:
        if exit < camera:
            camera = entry
            answer += 1

    return answer


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[list[list[int]], int]] = [
        # (routes, 기댓값)
        # 공식 예시
        # 손 추적(진출 정렬): [-20,-15],[-18,-13],[-14,-5],[-5,-3]
        #   [-20,-15]: -20 > -30001 -> camera=-15, 1대
        #   [-18,-13]: -18 > -15 ? 아님 -> 잡힘
        #   [-14,-5] : -14 > -15 -> camera=-5, 2대
        #   [-5,-3]  : -5 > -5 ? 아님(경계 포함) -> 잡힘  => 2
        ([[-20, -15], [-14, -5], [-18, -13], [-5, -3]], 2),
        # 추가 케이스:
        # 좌표 최댓값 경계: 한 대가 전 구간 이동 -> 1
        ([[-30000, 30000]], 1),
        # 접점: [1,3]과 [3,5]는 3에서 만남(경계 포함) -> 1
        ([[1, 3], [3, 5]], 1),
        # 완전히 분리된 구간 3개 -> 3
        ([[1, 2], [3, 4], [5, 6]], 3),
        # 포함 관계: [3,8]이 나머지를 모두 포함 -> 1
        ([[1, 10], [2, 9], [3, 8]], 1),
        # 큰 구간 하나 + 짧은 구간 둘: 2에 놓으면 [0,10],[1,2] 처리, [3,4]는 별도 -> 2
        ([[0, 10], [1, 2], [3, 4]], 2),
    ]

    solutions = [
        ("Mine_one (exit정렬)   ", solution_mine_one),
        ("Mine_two (entry역순)  ", solution_mine_two),
        ("Best     (itemgetter) ", solution_best),
        ("Sub      (entry역순)  ", solution_sub),
    ]

    # 워밍업 스텝
    _routes, _ = test_cases[0]
    for _, func in solutions:
        func([r[:] for r in _routes])

    print("=" * 66)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 66)

    for name, func in solutions:
        for idx, (routes, expected) in enumerate(test_cases, 1):
            case = [r[:] for r in routes]
            start = time.perf_counter()
            output = func(case)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 66)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
