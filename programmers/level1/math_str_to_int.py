"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 문자열을 정수로 바꾸기
    유형       : Math / String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12925
    풀이일자   : 2026-07-26
===================================================================================
[문제 요약]
    부호(+/-)와 숫자로 이루어진 문자열 s를 정수로 변환해 반환

    제약 조건
        - s 길이: 1 이상 5 이하
        - 맨 앞에 부호(+, -)가 올 수 있음
        - "0"으로 시작하지 않음
===================================================================================
[입출력 예시]
    s       | result
    --------|-------
    "1234"  | 1234
    "-1234" | -1234
===================================================================================
[핵심 원리 - 자릿수 누적]
    answer * 10 + digit 패턴:
        각 자리 문자를 왼쪽부터 읽으며 자릿수를 밀어 올리는 방식

    손 추적 (s="-1234"):
        sign=-1, start=1
        i=1: digit=1, answer = 0*10+1 = 1
        i=2: digit=2, answer = 1*10+2 = 12
        i=3: digit=3, answer = 12*10+3 = 123
        i=4: digit=4, answer = 123*10+4 = 1234
        return -1 * 1234 = -1234

[ord() 활용 원리]
    ord('0') = 48, ord('1') = 49, ..., ord('9') = 57
    ord(c) - ord('0'): 문자 숫자를 정수로 변환
        ord('5') - ord('0') = 53 - 48 = 5

[CPython int() 내부 동작]
    단순 루프(answer*10+digit)와 방향은 동일하나 C 레벨 구현
    Python 3.11+: 큰 정수는 O(N^1.585)에 가까운 알고리즘 사용
    s 길이 최대 5(소규모)에서는 단순 루프와 동일하게 동작
===================================================================================
[내 초기 풀이]
    solution_mine_one: int() 내장 함수 활용
    solution_mine_two: ord()로 직접 구현 (int() 미사용)

[개선 포인트]
    solution_mine_one: 개선 필요 없음 - Best
                       int()가 부호, 변환 모두 처리, 가장 간결하고 신뢰성 높음
    solution_mine_two: 개선 필요 없음 - Sub
                       int() 없이 직접 구현, 내부 동작 원리 이해 목적
                       ord() 없이도 구현 가능하나 ord()가 가장 효율적인 방법
===================================================================================
[복잡도 분석]
    N = len(s) (최대 5, 사실상 상수)

    Mine_one - 시간: O(N) | 공간: O(1) - int() C 레벨 파싱
    Mine_two - 시간: O(N) | 공간: O(1) - ord() 변환 + 자릿수 누적
    Best     - 시간: O(N) | 공간: O(1) - Mine_one과 동일
    Sub      - 시간: O(N) | 공간: O(1) - Mine_two와 동일

    N<=5 고정 -> 모두 실질적으로 O(1)
"""

import time


# =================================================================================
# Mine solution one - int() 내장 함수 활용
# =================================================================================
def solution_mine_one(s: str) -> int:
    """
    int() 형변환 내장 함수로 문자열을 정수로 변환하는 풀이

    핵심:
        int(s): 부호(+/-) 포함 문자열을 정수로 변환
        "+1234" -> 1234, "-1234" -> -1234, "1234" -> 1234
        부호 처리, 자릿수 계산을 C 레벨에서 자동 처리
    """
    return int(s)


# =================================================================================
# Mine solution two - ord()로 직접 구현
# =================================================================================
def solution_mine_two(s: str) -> int:
    """
    ord()를 이용해 int() 없이 문자열을 정수로 변환하는 풀이

    부호 처리:
        s[0] == '+': start=1, sign=1
        s[0] == '-': start=1, sign=-1
        숫자로 시작: start=0, sign=1

    자릿수 누적 (answer * 10 + digit):
        왼쪽부터 한 자리씩 읽으며 이전 값을 10배 밀어 올리고 현재 자리 추가
        "1234": 1 -> 12 -> 123 -> 1234

    ord() 활용:
        ord(c) - ord('0'): 문자 숫자를 정수로 변환
        ord('5') - ord('0') = 53 - 48 = 5
        아스키 코드 테이블에서 숫자 문자들이 연속 배치되어 있음을 이용
    """
    answer = 0
    start = 0
    sign = 1

    if s[0] == '+':
        start = 1
    elif s[0] == '-':
        start = 1
        sign = -1

    for i in range(start, len(s)):
        digit = ord(s[i]) - ord('0')
        answer = (answer * 10) + digit

    return sign * answer


# =================================================================================
# Best solution - int() 활용 (mine_one 주석 보강)
# =================================================================================
def solution_best(s: str) -> int:
    """
    int()로 문자열을 정수로 변환하는 최적 풀이

    mine_one과 동일한 로직, 선정 근거 주석 보강:
        int(s): 부호, 자릿수, 변환 모두 C 레벨에서 처리
        가장 간결하고 신뢰성 높음
        Mine_two 대비 부호/자릿수 처리 오류 가능성 없음
    """
    return int(s)


# =================================================================================
# Sub solution - ord() 직접 구현 (mine_two 주석 보강)
# =================================================================================
def solution_sub(s: str) -> int:
    """
    ord()로 int() 없이 구현하는 서브 풀이

    Best 대비 특징:
        int() 미사용 → 문자열-정수 변환 원리 직접 표현
        answer*10+digit 패턴: 10진수 자릿수 누적의 기본 원리
        sign 변수: 부호를 마지막에 한 번만 적용
        CPython int()도 내부적으로 동일한 방향으로 동작하나
        C 레벨 구현으로 더 빠름
    """
    answer = 0
    start = 0
    sign = 1

    if s[0] == '+':
        start = 1
    elif s[0] == '-':
        start = 1
        sign = -1

    for i in range(start, len(s)):
        digit = ord(s[i]) - ord('0')
        answer = (answer * 10) + digit

    return sign * answer


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[str, int]] = [
        # (s, 기댓값)
        # 공식 예시
        ("1234",  1234),
        ("-1234", -1234),
        # 추가 케이스:
        ("+1234", 1234),   # 양수 부호 명시
        ("0",     0),      # 단일 0
        ("-1",    -1),     # 최소 음수
        ("99999", 99999),  # 최대 길이
    ]

    solutions = [
        ("Mine_one (int())  ", solution_mine_one),
        ("Mine_two (ord())  ", solution_mine_two),
        ("Best     (int())  ", solution_best),
        ("Sub      (ord())  ", solution_sub),
    ]

    # 워밍업 스텝
    _s, _ = test_cases[0]
    for _, func in solutions:
        func(_s)

    print("=" * 60)
    print(f"{'풀이':<20} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 60)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<20} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 60)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
