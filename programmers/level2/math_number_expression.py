"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 숫자의 표현
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12924
    풀이일자   : 2026-08-06
================================================================================
[문제 요약]
    자연수 n을 연속된 자연수들의 합으로 표현하는 방법의 수 반환

    제약 조건
        - n: 1 이상 10,000 이하 자연수
================================================================================
[입출력 예시]
    n  | result
    ---|-------
    15 | 4      (15, 7+8, 4+5+6, 1+2+3+4+5)
================================================================================
[등차수열 합 공식 유도]
    시작값 a, 항 수 k인 연속 자연수 합:
        S = k/2 × (2a + (k-1)) = n
        2n = k × (2a + k - 1)

    m = 2a + k - 1로 치환하면:
        2n = k × m

    k + m = k + (2a + k - 1) = 2k + 2a - 1
        2k, 2a는 짝수이므로 -1을 하면 k+m은 항상 홀수
        → k와 m 중 하나는 반드시 홀수, 나머지는 짝수

[ref_one — 등차수열 합 공식 직접 적용]
    2n = k × m에서 k가 약수인지 확인:
        조건 1: (2n) % k == 0         → k가 2n의 약수
        조건 2: (m - k + 1) % 2 == 0  → a = (m-k+1)/2가 정수(자연수)

    while 조건 k*(k+1)//2 <= n 유도:
        a=1일 때 k개 연속 자연수 최솟값: 1+2+...+k = k(k+1)/2
        a가 클수록 합이 단조증가 → a=1이 하한선
        k(k+1)/2 > n이면 어떤 a를 써도 합이 n을 초과
        → a=1을 고정하고 k만 변수로 본 것
        → k(k+1)/2 <= n인 동안만 유효한 k가 존재할 수 있음

[ref_two — 홀수 약수 개수 정리]
    2n = k × m, k+m = 홀수 → 하나는 홀수, 하나는 짝수
    홀수인 쪽(d라 하면): 2n = d × (짝수)
        짝수 = 2n/d → n = d × (n/d) → d는 n의 약수

    d가 n의 홀수 약수이면 k=d 또는 k=2n/d로 a≥1인 표현 항상 존재
    → n의 홀수 약수 하나 ↔ 유효한 표현 하나 (1:1 대응)
    → n의 홀수 약수 개수 = 표현 방법 수

    손 추적 (n=15):
        홀수 약수: 1, 3, 5, 15
        d=1:  k=1,  a=15 → 15
        d=3:  k=3,  a=4  → 4+5+6
        d=5:  k=5,  a=1  → 1+2+3+4+5
        d=15: k=2,  a=7  → 7+8 (k=15는 a가 음수라 k=2n/d=2로 대체)
        → 4가지 ✓
================================================================================
[내 초기 풀이]
    solution_mine_one: 단일 포인터 완전 탐색 O(N²)
    solution_mine_two: 투 포인터 O(N)

[개선 포인트]
    solution_mine_one: O(N²) → 투 포인터/등차수열/홀수약수로 개선 가능
                       break 없이 조건에 의한 탈출 (while total <= n으로 종료)
                       지문 로직과 1:1 대응, 학습 목적
    solution_mine_two: 개선 필요 없음 - Sub
                       투 포인터로 O(N), total 재초기화 없이 포인터 이동으로 조절
    solution_ref_one:  등차수열 합 공식 적용 O(sqrt(N))
                       while 조건: a=1 고정, k만 변수로 최솟값 기준 범위 제한
    solution_ref_two:  홀수 약수 개수 정리 O(N)
                       range(1,n+1,2)로 홀수만 순회, n의 홀수 약수 개수 반환
                       Best: 수학적 정리로 가장 간결
================================================================================
[복잡도 분석]
    N = n (최대 10,000)

    Mine_one  - 시간: O(N²)     | 공간: O(1) - 이중 while 완전 탐색
    Mine_two  - 시간: O(N)      | 공간: O(1) - 투 포인터, start+end 각 최대 N
    Ref_one   - 시간: O(sqrt(N))| 공간: O(1) - k 최대 sqrt(2N)까지 순회
    Ref_two   - 시간: O(N)      | 공간: O(1) - range(1,n+1,2): N/2번 순회
    Best      - 시간: O(N)      | 공간: O(1) - Ref_two와 동일
    Sub       - 시간: O(N)      | 공간: O(1) - Mine_two와 동일
"""

import time


# ================================================================================
# Mine solution one - 단일 포인터 완전 탐색
# ================================================================================
def solution_mine_one(n: int) -> int:
    """
    pointer를 시작값으로 내부 while에서 누적합을 구하는 완전 탐색 풀이

    핵심:
        pointer(=a): 1부터 n까지 각 시작값 시도
        내부 while: start부터 1씩 더하며 total이 n에 도달하는지 확인
        total == n: 유효한 표현 발견 → count += 1
        total > n:  while 조건(total <= n) 불충족 → 자연 탈출

    시간 O(N²):
        외부 while N회 × 내부 while 최악 N회
    """
    count = 0
    pointer = 1

    while pointer <= n:
        total = 0
        start = pointer
        while total <= n:
            total += start
            start += 1
            if total == n:
                count += 1
        pointer += 1

    return count


# ================================================================================
# Mine solution two - 투 포인터
# ================================================================================
def solution_mine_two(n: int) -> int:
    """
    start, end 두 포인터로 total을 조절하며 유효한 표현을 찾는 풀이

    핵심:
        total < n: end 포인터 추가 (자연수 순열 확장)
        total > n: start 포인터 제거 (최솟값 제거로 total 감소)
        total == n: 유효한 표현 발견 → start 이동으로 다음 탐색

    total 재초기화 없이 포인터 이동으로 조절:
        O(N²) → O(N) 개선
        start, end 각각 최대 n까지만 이동
    """
    count = 0
    start = 1
    end = 1
    total = 0

    while start <= n:
        if total < n:
            total += end
            end += 1
        elif total > n:
            total -= start
            start += 1
        else:
            count += 1
            total -= start
            start += 1

    return count


# ================================================================================
# Ref solution one - 등차수열 합 공식 (O(sqrt(N)))
# ================================================================================
def solution_ref_one(n: int) -> int:
    """
    2n = k × (2a + k - 1) 공식으로 유효한 k를 탐색하는 참고 풀이

    while 조건 k*(k+1)//2 <= n:
        a=1일 때 k개 연속 자연수 최솟값 = k(k+1)/2
        a가 클수록 합이 단조증가 → a=1이 하한선
        a=1 기준 최솟값이 n을 초과하면 어떤 a도 불가
        → k 최대 sqrt(2N) 수준, 전체 O(sqrt(N))

    조건 1: (2n) % k == 0
        k가 2n의 약수여야 함

    조건 2: ((2n) // k - k + 1) % 2 == 0
        m = 2n // k, a = (m - k + 1) / 2
        a가 자연수(정수)이려면 m - k + 1이 짝수여야 함
    """
    count = 0
    k = 1

    while k * (k + 1) // 2 <= n:
        if (2 * n) % k == 0 and ((2 * n) // k - k + 1) % 2 == 0:
            count += 1
        k += 1

    return count


# ================================================================================
# Ref solution two - 홀수 약수 개수 정리 (Best)
# ================================================================================
def solution_ref_two(n: int) -> int:
    """
    n의 홀수 약수 개수 = n을 연속 자연수 합으로 표현하는 방법 수

    수학적 근거:
        2n = k × m (k+m = 홀수)
        → 하나는 홀수, 하나는 짝수
        → 홀수인 쪽은 n의 약수
        → n의 홀수 약수 하나 ↔ 유효한 표현 하나 (1:1 대응)

    구현:
        range(1, n+1, 2): 1, 3, 5, ... 홀수만 순회 (N/2번)
        n % i == 0: n의 홀수 약수 여부 확인
    """
    return sum(1 for i in range(1, n + 1, 2) if n % i == 0)


# ================================================================================
# Best solution - 홀수 약수 개수 (ref_two 주석 보강)
# ================================================================================
def solution_best(n: int) -> int:
    """
    n의 홀수 약수 개수로 표현 방법 수를 구하는 최적 풀이

    ref_two와 동일한 로직, 선정 근거 주석 보강:
        수학적 정리(홀수 약수 = 연속 자연수 합 표현 수)를 직접 적용
        코드 한 줄로 표현, 가독성과 성능 모두 우위
        O(N/2) = O(N): 투 포인터와 복잡도 동일
        ref_one O(sqrt(N))보다 느리나 코드 간결성 압도적
    """
    return sum(1 for i in range(1, n + 1, 2) if n % i == 0)


# ================================================================================
# Sub solution - 투 포인터 (mine_two 주석 보강)
# ================================================================================
def solution_sub(n: int) -> int:
    """
    투 포인터로 O(N) 시간에 유효한 표현을 찾는 서브 풀이

    Best 대비 특징:
        수학적 정리 없이 알고리즘적 접근
        start, end 포인터로 연속 자연수 구간을 직접 조절
        total 재초기화 없이 포인터 이동으로 조절 → O(N) 보장
        투 포인터 패턴의 동작 원리가 코드에 직접 드러남
    """
    count = 0
    start = 1
    end = 1
    total = 0

    while start <= n:
        if total < n:
            total += end
            end += 1
        elif total > n:
            total -= start
            start += 1
        else:
            count += 1
            total -= start
            start += 1

    return count


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[int, int]] = [
        # (n, 기댓값)
        # 손 추적 n=15:
        #   15=15, 7+8, 4+5+6, 1+2+3+4+5 → 4
        (15, 4),
        # 추가 케이스:
        (1,  1),   # n=1: 1만
        (3,  2),   # 3, 1+2
        (5,  2),   # 5, 2+3
        (10, 2),   # 10, 1+2+3+4
    ]

    solutions = [
        ("Mine_one   (완전탐색)  ", solution_mine_one),
        ("Mine_two   (투포인터)  ", solution_mine_two),
        ("Ref_one    (등차수열)  ", solution_ref_one),
        ("Ref_two    (홀수약수)  ", solution_ref_two),
        ("Best       (홀수약수)  ", solution_best),
        ("Sub        (투포인터)  ", solution_sub),
    ]

    # 워밍업 스텝
    _n, _ = test_cases[0]
    for _, func in solutions:
        func(_n)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start_t = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start_t

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
