"""
================================================================================
[문제 정보]
    사이트     : SWEA (SW Expert Academy)
    레벨       : D1
    문제명     : 2058. 자릿수 더하기
    유형       : Math (자릿수 분해)
    링크       : https://swexpertacademy.com/main/code/problem/problemDetail.do?contestProbId=AV5QPRjqA10DFAUq&categoryId=AV5QPRjqA10DFAUq&categoryType=CODE&problemTitle=&orderBy=PASS_RATE&selectCodeLang=ALL&select-1=&pageSize=10&pageIndex=4
    풀이일자   : 2026-10-28
================================================================================
[문제 요약]
    자연수 N의 각 자릿수의 합을 계산

    입력 방식 : 자연수 N 한 개 (1 ≤ N ≤ 9999)
    적용 방식 : 입력 → 매개변수 n, output → 반환값
================================================================================
[입출력 예시]
    공식 예시
    n    | return
    -----|-------
    6789 | 30      (6 + 7 + 8 + 9)

    자체 검증 케이스 (전부 손 계산)
    n                  | return
    -------------------|--------
    1                  | 1
    9                  | 9
    10                 | 1
    100                | 1       (1 + 0 + 0)
    1000               | 1
    9000               | 9
    1234               | 10      (1 + 2 + 3 + 4)
    999                | 27      (9 * 3)
    9999               | 36      (9 * 4, 최대값)
    999999999          | 81      (9 * 9, 제약을 넘는 큰 값)
================================================================================
[풀이 전략]
    핵심: 한 자리씩 분리해서 더하기
        n % 10 : 마지막 자리 (6789 % 10 = 9)
        n // 10 : 마지막 자리를 제거한 수 (6789 // 10 = 678)
        n이 0이 될 때까지 반복

    풀이 구성:
        mine_one : while 반복으로 나머지(%)와 몫(//)을 이용 (직접 작성한 풀이)
        mine_two : 문자열 변환 + 제너레이터로 각 문자를 정수로 바꿔 sum (직접 작성한 풀이)
        best     : mine_one과 동일 (문자열 변환 없이 산술 연산만 사용)
        sub      : sum(map(int, str(n))), mine_two의 제너레이터 식을 map으로 대체해 간결
                   str(n)으로 각 자리를 문자로 얻고, map이 문자를 정수로 변환

    손 추적 (공식 예시) n = 6789:
        total = 0
        6789 % 10 = 9 → total = 9,  n = 678
        678 % 10 = 8  → total = 17, n = 67
        67 % 10 = 7   → total = 24, n = 6
        6 % 10 = 6    → total = 30, n = 0 → 종료
        → 30 ✓
================================================================================
[개선 포인트]
    solution_mine_one : 개선 여지 작음 - 산술 연산만 사용, 자릿수만큼 반복
    solution_mine_two : 개선 여지 있음 - 문자열 변환과 정수 변환이 모두 필요, map으로 더 간결
    solution_best     : mine_one과 동일 로직 - Best
    solution_sub      : 제너레이터 식을 map으로 대체 - 한 줄로 가독성 우수
================================================================================
[복잡도 분석]
    d = n의 자릿수 (d = log10(n) + 1)

    Mine_one - 시간: O(d) | 공간: O(1) - 자릿수만큼 나머지, 몫 연산
    Mine_two - 시간: O(d) | 공간: O(d) - 문자열 str(n)을 만들고 순회
    Best     - 시간: O(d) | 공간: O(1) - mine_one과 동일
    Sub      - 시간: O(d) | 공간: O(d) - 문자열 str(n)을 만들고 순회
"""

import time


# ================================================================================
# Mine solution one - while + 나머지/몫
# ================================================================================
def solution_mine_one(n: int) -> int:
    """
    나머지로 마지막 자리를 추출하고 몫으로 n을 줄여 가며 합산하는 직접 작성한 풀이

    핵심:
        n % 10 : 마지막 자리 추출
        n // 10 : 마지막 자리 제거
        n이 0이 되면 모든 자리를 더한 것
    """
    total = 0
    while n > 0:
        total += n % 10
        n = n // 10

    return total


# ================================================================================
# Mine solution two - 문자열 변환 + 제너레이터
# ================================================================================
def solution_mine_two(n: int) -> int:
    """
    정수를 문자열로 바꿔 각 문자를 정수로 되돌려 합산하는 직접 작성한 풀이

    핵심:
        str(n) : 각 자리를 문자로 접근 가능
        int(x) : 문자를 다시 정수로 변환
        sum : 변환된 값을 합산
    """
    return sum(int(x) for x in str(n))


# ================================================================================
# Best solution - mine_one과 동일 로직
# ================================================================================
def solution_best(n: int) -> int:
    """
    mine_one과 동일한 로직의 최적 풀이

    선정 근거:
        문자열 변환 없이 산술 연산만 사용하고 추가 메모리가 필요 없음
    """
    total = 0
    while n > 0:
        total += n % 10
        n = n // 10

    return total


# ================================================================================
# Sub solution - sum + map + str
# ================================================================================
def solution_sub(n: int) -> int:
    """
    mine_two의 제너레이터 식을 map으로 대체한 풀이

    핵심:
        sum(map(int, str(n))) : 문자열의 각 문자를 정수로 변환해 합산
        제너레이터 식 없이 한 줄로 표현
    """
    return sum(map(int, str(n)))


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (n, 기댓값) - 전부 손 계산
        (6789, 30),                                         # 공식 예시
        (1, 1),                                             # 최솟값
        (9, 9),                                             # 한 자리 최댓값
        (10, 1),                                            # 0이 포함된 두 자리
        (100, 1),                                           # 1 + 0 + 0
        (1000, 1),                                          # 0이 연속
        (9000, 9),                                          # 끝자리가 모두 0
        (1234, 10),                                         # 1 + 2 + 3 + 4
        (999, 27),                                          # 9 * 3
        (9999, 36),                                         # 최대값: 9 * 4
        (999999999, 81),                                    # 큰 값: 9 * 9
    ]

    solutions = [
        ("Mine1 (while)", solution_mine_one),
        ("Mine2 (str+gen)", solution_mine_two),
        ("Best (while)", solution_best),
        ("Sub (str+map)", solution_sub),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
