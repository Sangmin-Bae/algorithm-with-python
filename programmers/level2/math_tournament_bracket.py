"""
================================================================================
[문제 정보]
    사이트      : Programmers
    레벨        : Level 2
    문제명      : 예상 대진표
    유형        : Math / Simulation
    링크        : https://school.programmers.co.kr/learn/courses/30/lessons/12985
    풀이일자    : 2025-06-02
================================================================================
[문제 요약]
    N명 토너먼트. 1↔2, 3↔4, ... 순서로 대결
    이긴 사람은 다음 라운드에서 1번부터 재번호 부여
    A, B가 항상 이긴다고 가정할 때 몇 번째 라운드에서 만나는가

    제약 조건
        - N: 2¹ 이상 2²⁰ 이하 (2의 지수승, 부전승 없음)
        - A ≠ B
================================================================================
[입출력 예시]
    N | A | B | answer
    --|---|---|-------
    8 | 4 | 7 | 3
================================================================================
[핵심 아이디어 — 그룹 번호 변환]
    각 라운드에서 매치 그룹 번호 = ⌈번호/2⌉ = (번호+1)//2

    n=8, a=4, b=7 손 추적:
        1라운드: a=(4+1)//2=2, b=(7+1)//2=4  → 다름, round=1
        2라운드: a=(2+1)//2=1, b=(4+1)//2=2  → 다름, round=2
        3라운드: a=(1+1)//2=1, b=(2+1)//2=1  → 같음! return 3  ✓
================================================================================
[solution_two의 (a+1)//2 = solution_one 수학적 증명]
    두 풀이가 동일한 이유:

    a가 홀수(a=2k+1)일 때:
        solution_one: a//2 + 1 = k + 1
        solution_two: (a+1)//2 = (2k+2)//2 = k+1  → 동일

    a가 짝수(a=2k)일 때:
        solution_one: a//2 = k
        solution_two: (a+1)//2 = (2k+1)//2 = k  → 동일 (파이썬 //는 버림)

    ∴ (a+1)//2 = ⌈a/2⌉ (올림 나눗셈)
        홀수/짝수 조건문을 하나의 수식으로 통일한 것
================================================================================
[Ref 풀이 분석 — 이진 탐색 방식]
    이진 탐색으로 "어느 라운드에서 a,b가 갈라지는가"를 탐색

    핵심 아이디어:
        n//2를 중간점으로 설정
        a,b가 둘 다 중간점 초과 → 같은 오른쪽 절반 → 범위 좁혀 다음 라운드 확인
        a,b가 둘 다 중간점 이하 → 같은 왼쪽 절반 → 범위 좁혀 다음 라운드 확인
        a,b가 서로 다른 절반 → 이 라운드에서 만남 → return i

    최대 라운드에서 역으로 내려오는 이유:
        큰 라운드(최종)에서 시작해서 "이 라운드에서 만나는가"를 확인
        같은 절반이면 더 작은 라운드로 내려가며 탐색

    나의 풀이 대비:
        결과는 동일하나 코드가 복잡하고 직관적이지 않음
        c, n 변수 조작이 이진 탐색 구현을 위해 추가됨
        → 네 풀이(solution_two)가 더 간결하고 명확
================================================================================
[복잡도 분석]
    N = n (최대 2²⁰ = 약 백만)
    라운드 수 = log₂(N) ≤ 20

    Mine_one - 시간: O(log N) | 공간: O(1) — 조건문으로 홀짝 구분
    Mine_two - 시간: O(log N) | 공간: O(1) — (a+1)//2 수식으로 통일
    Best     - 시간: O(log N) | 공간: O(1) — Mine_two와 동일
    Ref      - 시간: O(log N) | 공간: O(1) — 이진 탐색 방식
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one — 홀짝 조건문으로 그룹 번호 계산
# ==============================================================================
def solution_mine_one(n: int, a: int, b: int) -> int:
    """
    홀수/짝수 조건문으로 다음 라운드 그룹 번호를 계산하는 초기 풀이

    핵심 발상:
        각 번호의 그룹 번호 = ⌈번호/2⌉
        홀수: 그룹의 첫 번째 자리 → a//2 + 1
        짝수: 그룹의 두 번째 자리 → a//2
        두 번호가 같은 그룹이 되면 그 라운드에서 만남

    개선 가능:
        홀짝 조건문 → (a+1)//2 단일 수식으로 통일 가능
    """
    round = 0

    while True:
        if a == b:
            break

        if a % 2:
            a = a // 2 + 1  # 홀수: 올림 나눗셈
        else:
            a = a // 2  # 짝수: 내림 나눗셈

        if b % 2:
            b = b // 2 + 1
        else:
            b = b // 2

        round += 1

    return round


# ==============================================================================
# Mine solution two — (a+1)//2 수식으로 홀짝 조건 통일
# ==============================================================================
def solution_mine_two(n: int, a: int, b: int) -> int:
    """
    (a+1)//2 올림 나눗셈으로 홀짝 조건을 통일한 개선 풀이

    Mine_one 대비 개선:
        홀수: a//2 + 1 = (a+1)//2  (a=2k+1일 때 k+1로 동일)
        짝수: a//2 = (a+1)//2     (a=2k일 때 k로 동일)
        → 조건문 제거, 단일 수식으로 통일

    직관:
        (a+1)//2 = ⌈a/2⌉ = 올림 나눗셈
        홀수든 짝수든 "내가 속한 그룹 번호"를 정확히 계산
    """
    round = 0

    while a != b:
        a = (a + 1) // 2
        b = (b + 1) // 2
        round += 1

    return round


# ==============================================================================
# Best solution — Mine_two (변경 없음, 주석 보강)
# ==============================================================================
def solution_best(n: int, a: int, b: int) -> int:
    """
    올림 나눗셈으로 매 라운드 그룹 번호를 변환하는 최적 풀이

    (a+1)//2 수학적 근거:
        홀수 a=2k+1: (2k+2)//2 = k+1 = a//2 + 1 (올림)
        짝수 a=2k:   (2k+1)//2 = k   = a//2     (버림)
        → 두 경우를 하나의 수식으로 통일

    시간복잡도 O(log N):
        매 라운드 a,b가 절반으로 줄어듦
        N=2²⁰이어도 최대 20번 반복
    """
    round = 0

    while a != b:
        a = (a + 1) // 2  # 다음 라운드에서 a의 그룹 번호 (올림 나눗셈)
        b = (b + 1) // 2  # 다음 라운드에서 b의 그룹 번호
        round += 1

    return round


# ==============================================================================
# Ref solution — 다른 사용자 풀이 (이진 탐색 방식)
# ==============================================================================
def solution_ref(n: int, a: int, b: int) -> int:
    """
    최대 라운드에서 역방향으로 탐색하는 다른 사용자 풀이

    핵심 아이디어:
        n//2를 중간점으로 설정해 a,b가 같은 절반인지 다른 절반인지 확인
        같은 절반 → 범위 좁혀서 더 작은 라운드 확인
        다른 절반 → 이 라운드에서 만남 → return i

    분석:
        Best 대비 복잡하고 직관적이지 않음
        c, n 변수 조작으로 이진 탐색 구현
        결과는 동일
    """
    c = 0
    maxn = bin(n).count('0') - 1  # 전체 라운드 수: bin(8)='0b1000' → '0'4개 -1=3

    if a > b:
        a, b = b, a  # a ≤ b 보장

    n = n // 2  # 초기 중간점
    c = n

    for i in range(maxn, 0, -1):  # 최대 라운드부터 역으로
        if i == 1:
            return 1

        if a > n and b > n:  # 둘 다 오른쪽 절반 → 같은 절반
            c = c // 2
            n += c  # 중간점을 오른쪽으로 이동
            continue

        elif a <= n and b <= n:  # 둘 다 왼쪽 절반 → 같은 절반
            c = c // 2
            n -= c  # 중간점을 왼쪽으로 이동
            continue

        return i  # 서로 다른 절반 → 이 라운드에서 만남


# ==============================================================================
# Ref solution two — 가장 좋아요 많은 풀이 (XOR + bit_length)
# ==============================================================================
def solution_ref_two(n: int, a: int, b: int) -> int:
    """
    XOR 비트 연산과 bit_length()로 한 줄에 해결하는 풀이

    핵심 아이디어:
        1-indexed → 0-indexed 변환 (-1)
        XOR: 두 번호의 다른 비트만 1로 표시
        bit_length(): 최상위 1비트의 위치 = 몇 번째 라운드에서 처음 갈라지는가

    수학적 근거:
        토너먼트 구조 = 이진 트리
        k번째 라운드에서 만남 = 두 번호(0-indexed)의 이진수가 상위 비트는 같고 k번째 비트부터 다름
        XOR의 최상위 1비트 위치 = 처음 달라지는 비트 = 라운드 수

    검증 (n=8):
        a=4, b=7 → a-1=3=011, b-1=6=110
        XOR = 101 = 5
        bit_length() = 3 → return 3  ✓

    시간복잡도: O(1) — 연산 2번 (Mine_two의 O(log N) 대비)
    """
    return ((a - 1) ^ (b - 1)).bit_length()


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int, int, int]] = [
        # (n, a, b, 기댓값)
        # 기댓값 손 추적:
        # (8,4,7): a=(4+1)//2=2→1, b=(7+1)//2=4→2→1, round=3
        (8, 4, 7, 3),
        # (8,1,2): a=(1+1)//2=1, b=(2+1)//2=1, round=1 (1라운드에서 바로 만남)
        (8, 1, 2, 1),
        # (8,1,8): a=1→1→1, b=8→4→2→1, round=3
        (8, 1, 8, 3),
        # (4,1,4): a=1→1, b=4→2→1, round=2
        (4, 1, 4, 2),
        # (16,1,16): a=1→1→1→1, b=16→8→4→2→1, round=4
        (16, 1, 16, 4),
        # (2,1,2): a=1, b=1 → 즉시 같음? 아니면 round=1?
        # 손 추적: a=1, b=2 → (1+1)//2=1, (2+1)//2=1 → round=1
        (2, 1, 2, 1),
    ]

    solutions = [
        ("Mine_one (홀짝조건)", solution_mine_one),
        ("Mine_two (올림나눗셈)", solution_mine_two),
        ("Best     (올림나눗셈)", solution_best),
        ("Ref      (이진탐색)", solution_ref),
        ("Ref_two  (XOR+bit_length)", solution_ref_two),
    ]

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (n, a, b, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n, a, b)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
