"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 짝수와 홀수
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12937
    풀이일자   : 2026-07-30
===================================================================================
[문제 요약]
    정수 num이 짝수이면 "Even", 홀수이면 "Odd" 반환

    제약 조건
        - num: int 범위 정수 (음수 포함)
        - 0은 짝수
===================================================================================
[입출력 예시]
    num | return
    ----|-------
    3   | "Odd"
    4   | "Even"
===================================================================================
[짝수/홀수 판별 방법 비교]
    나눗셈 방식 (num % 2):
        2로 나눈 나머지가 0이면 짝수, 1이면 홀수
        Python 음수 나머지: -3 % 2 = 1 (양수 나머지 보장)

    비트 연산 방식 (num & 1):
        2^0 자리 비트만 추출 → 0이면 짝수, 1이면 홀수
        음수도 올바르게 동작: -3 & 1 = 1 (홀수 ✓)

[실측 결과 — 성능 비교 (timeit 1,000,000회)]
    케이스   | %(삼항)  | &(리스트) | &(삼항)
    ---------|----------|-----------|--------
    짝수 4   | 0.152μs  | 0.139μs   | 0.072μs
    홀수 3   | 0.083μs  | 0.103μs   | 0.070μs
    음수 -3  | 0.078μs  | 0.102μs   | 0.074μs
    0        | 0.073μs  | 0.100μs   | 0.069μs

    &(삼항) 방식이 일관되게 가장 빠름
    &(리스트) 방식이 느린 이유:
        ['Even','Odd'] 리스트 객체 생성 + 인덱싱 오버헤드
    %(삼항)이 &(삼항)보다 느린 이유:
        짝수 케이스에서 else 분기 예측 미스 가능성
        &(삼항)은 0 또는 1로 분기 패턴이 더 단순

    C/Java에서는 & 방식이 % 방식보다 빠름 (CPU DIV vs AND 명령)
    Python에서는 리스트 인덱싱 방식(mine_two)이 오히려 느리고
    삼항 연산자 조합(mine_three)이 최적
===================================================================================
[내 초기 풀이]
    solution_mine_one  : num % 2 == 0 나눗셈 + 삼항 연산자
    solution_mine_two  : num & 1 비트 연산 + 리스트 인덱싱
    solution_mine_three: num & 1 비트 연산 + 삼항 연산자 (개선)

[개선 포인트]
    solution_mine_one  : 개선 필요 없음 - Sub
                         가독성 우위, 음수/0 자연스럽게 처리
    solution_mine_two  : 리스트 객체 생성 오버헤드 존재
                         → 삼항 연산자 조합(mine_three)으로 개선
    solution_mine_three: 개선 필요 없음 - Best
                         비트 AND + 삼항 연산자로 리스트 오버헤드 제거
                         실측 전 케이스에서 가장 빠름

    선정 기준:
        1순위: 효율성과 성능 → & 삼항 방식이 실측 우위
        2순위: 가독성 → % 방식이 더 직관적 → Sub
===================================================================================
[복잡도 분석]
    Mine_one   - 시간: O(1) | 공간: O(1) - 나눗셈 + 삼항 연산
    Mine_two   - 시간: O(1) | 공간: O(1) - 비트 AND + 리스트 인덱싱
    Mine_three - 시간: O(1) | 공간: O(1) - 비트 AND + 삼항 연산
    Best       - 시간: O(1) | 공간: O(1) - Mine_three와 동일
    Sub        - 시간: O(1) | 공간: O(1) - Mine_one과 동일
"""

import time


# =================================================================================
# Mine solution one - num % 2 나눗셈 + 삼항 연산자
# =================================================================================
def solution_mine_one(num: int) -> str:
    """
    나눗셈 나머지로 짝수/홀수를 판별하는 초기 풀이

    num % 2 == 0:
        2로 나눈 나머지가 0 → 짝수 → "Even"
        나머지가 1 → 홀수 → "Odd"

    음수 처리:
        Python % 연산은 항상 양수 나머지 반환
        -3 % 2 = 1 (홀수 ✓), -4 % 2 = 0 (짝수 ✓)

    0 처리:
        0 % 2 = 0 → "Even" ✓ (0은 짝수 조건 자연스럽게 충족)
    """
    return "Even" if num % 2 == 0 else "Odd"


# =================================================================================
# Mine solution two - num & 1 비트 연산 + 리스트 인덱싱
# =================================================================================
def solution_mine_two(num: int) -> str:
    """
    비트 AND로 2^0 자리를 추출 후 리스트 인덱싱으로 반환하는 풀이

    num & 1:
        1 = 0001(2): 2^0 자리만 1, 나머지 모두 0
        홀수: 2^0 = 1 → ["Even","Odd"][1] = "Odd"
        짝수: 2^0 = 0 → ["Even","Odd"][0] = "Even"

    한계:
        ['Even','Odd'] 리스트 객체 생성 + 인덱싱 오버헤드
        → mine_one보다 느림, mine_three로 개선 가능
    """
    return ["Even", "Odd"][num & 1]


# =================================================================================
# Mine solution three - num & 1 비트 연산 + 삼항 연산자 (mine_two 개선)
# =================================================================================
def solution_mine_three(num: int) -> str:
    """
    비트 AND + 삼항 연산자로 리스트 오버헤드를 제거한 개선 풀이

    mine_two 대비:
        ['Even','Odd'][num & 1] → 'Odd' if num & 1 else 'Even'
        리스트 객체 생성 없이 직접 문자열 반환
        실측 전 케이스에서 mine_one, mine_two보다 빠름

    num & 1의 진릿값:
        1(홀수): Python에서 truthy → 'Odd' 반환
        0(짝수): Python에서 falsy → 'Even' 반환
    """
    return "Odd" if num & 1 else "Even"


# =================================================================================
# Best solution - & 비트 + 삼항 (mine_three 주석 보강)
# =================================================================================
def solution_best(num: int) -> str:
    """
    비트 AND + 삼항 연산자로 실측 전 케이스 최속인 최적 풀이

    mine_three와 동일한 로직, 선정 근거 주석 보강:
        비트 AND: 최하위 비트로 홀짝 판별 (수학적 접근)
        삼항 연산자: 리스트 객체 생성 없이 직접 반환
        실측 전 케이스에서 가장 빠름 (0.069~0.074μs)
    """
    return "Odd" if num & 1 else "Even"


# =================================================================================
# Sub solution - % 나눗셈 + 삼항 (mine_one 주석 보강)
# =================================================================================
def solution_sub(num: int) -> str:
    """
    나눗셈 나머지로 짝수/홀수를 판별하는 서브 풀이

    Best 대비 특징:
        num % 2 == 0: 짝수/홀수 의도가 코드에 직접 드러남
        가독성 우위 → 처음 보는 사람도 즉시 이해
        성능은 Best(& 삼항)보다 느리나 μs 단위 차이
    """
    return "Even" if num % 2 == 0 else "Odd"


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[int, str]] = [
        # (num, 기댓값)
        (3,  "Odd"),    # 공식 예시 홀수
        (4,  "Even"),   # 공식 예시 짝수
        (0,  "Even"),   # 0은 짝수
        (-3, "Odd"),    # 음수 홀수
        (-4, "Even"),   # 음수 짝수
    ]

    solutions = [
        ("Mine_one   (% 삼항)  ", solution_mine_one),
        ("Mine_two   (& 리스트)", solution_mine_two),
        ("Mine_three (& 삼항)  ", solution_mine_three),
        ("Best       (& 삼항)  ", solution_best),
        ("Sub        (% 삼항)  ", solution_sub),
    ]

    # 워밍업 스텝
    _n, _ = test_cases[0]
    for _, func in solutions:
        func(_n)

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (num, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(num)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
