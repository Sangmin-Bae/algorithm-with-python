"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 약수의 개수와 덧셈
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/77884
    풀이일자   : 2025-05-20
===================================================================================
[문제 요약]
    left ~ right 범위의 각 정수에 대해
        약수 개수가 짝수 -> 더하기
        약수 개수가 홀수 -> 빼기
    결과를 반환

    제약 조건
        - 1 <= left <= right <= 1,000
===================================================================================
[입출력 예시]
    left | right | result
    -----|-------|--------
    13   | 17    | 43       (13+14+15-16+17, 16만 완전제곱수)
    24   | 27    | 52       (24-25+26+27, 25만 완전제곱수)
===================================================================================
[내 초기 풀이]
    solution_one: 완전제곱수 판별로 약수 개수 홀짝 직접 판단
        - 약수 대칭성 학습 내용 적용
        - 완전제곱수 -> 약수 개수 홀수 -> 빼기
        - math.isqrt(i)**2 == i 로 판별
        - 내부 루프 없음 -> O(N)

    solution_two: 완전 탐색으로 약수 개수 직접 카운트
        - range(1, i+1) 전체 순회로 약수 개수 count
        - 짝수 -> 더하기, 홀수 -> 빼기
        - 이중 루프 -> O(N²)

[개선 포인트]
    solution_one: (math.isqrt(i))**2 -> math.isqrt(i)**2 (불필요한 괄호 제거)
    solution_two: range(i, i+1) -> range(1, isqrt(i)+1)으로 √N 최적화
                    완전제곱수 중복 처리 필요 (j == i//j 조건)
===================================================================================
[수학적 근거 - 약수 개수와 완전제곱수]
    약수는 항상 쌍(x, n//x)으로 존재
        -> 일반적으로 약수 개수는 짝수

    완전제곱수(n = k²)의 경우
        -> √n = k가 자기 자신과 쌍을 이룸 (k x k)
        -> 쌍이 하나 깨져 약수 개수가 홀수

    ∴ 완전제곱수 -> 약수 개수 홀수 -> 빼기
        그 외    -> 약수 개수 짝수 -> 더하기
===================================================================================
[복잡도 분석]
    N = right - left + 1 (최대 1,000)

    Mine_one - 시간: O(N)     | 공간: O(1) - isqrt() O(1) x N번
    Mine_two - 시간: O(N²)    | 공간: O(1) - N x N = 최대 1,000,000번
    Best     - 시간: O(N)     | 공간: O(1) - Mine_one과 동일, 주석 보강
    Sub      - 시간: O(N√N)   | 공간: O(1) - N x √N ≈ 31,000번

    Best > Sub > Mine_two 순
    Best는 약수 개수를 세지 않고 완전제곱수 여부만 판별 -> 내부 루프 소면
===================================================================================
"""

import math
import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one - 완전제곱수 판별 (약수 개수 홀짝 직접 판단)
# ==============================================================================
def solution_mine_one(left: int, right: int) -> int:
    """
    약수 대칭성을 이용해 완전제곱수 여부로 홀짝을 판별하는 초기 풀이

    핵심 발상:
        - 약수는 항상 쌍으로 존재 -> 일반적으로 개수 짝수
        - 완전제곱수만 예외: √n이 자기 자신과 쌍 -> 개수 홀수
        - 완전제곱수 판별: math.isqrt(i)**2 == i

    개선 전 상태:
        - (math.isqrt(i))**2 -> 불필요한 괄호 존재
    """
    answer = 0

    for i in range(left, right + 1):
        if (math.isqrt(i)) ** 2 == i:   # 완전제곱수 판별
            answer -= i                 # 약수 개수 홀수 -> 빼기
        else:
            answer += i                 # 약수 개수 짝수 -> 더하기

    return answer


# ==============================================================================
# Mine solution two - 완전 탐색 (약수 개수 직접 카운트)
# ==============================================================================
def solution_mine_two(left: int, right: int) -> int:
    """
    각 수의 약수를 1부터 직접 세는 완전 탐색 풀이

    특징:
        - 가장 직관적, 수학적 통찰 붎필요
        - range(1, i+1) 전체 순회 -> 이중 루프 -> O(N²)
        - 개선 방향: range를 √i까지 줄이면 O(N√N)으로 개선 가능
    """
    answer = 0

    for i in range(left, right + 1):
        count = 0

        for j in range(1, i + 1):   # 1 ~ i 전체 순회
            if i % j == 0:
                count += 1          # 약수 발견 시 카운트

        if count % 2 == 0:
            answer += i             # 약수 개수 짝수 -> 더하기
        else:
            answer -= i             # 약수 개수 홀수 -> 빼기

    return answer


# ==============================================================================
# Best solution - Mine_one 개선 (괄호 정리 + 주석 보강)
# ==============================================================================
def solution_best(left: int, right: int) -> int:
    """
    완전제곱수 판별로 약수 개수 홀짝을 O(1)에 판단하는 최적 풀이

    Mine_one 대비 개선:
        - (math.isqrt(i))**2 -> math.isqrt(i)**2 (불필요한 괄호 제거)
        - ** 연산자가 함수 호출보다 우선순위 낮아 괄호 없이도 동일 동작

    수학적 근거:
        완전제곱수 -> 약수 개수 홀수 -> 빼기
        그 외      -> 약수 개수 짝수 -> 더하기
        math.isqrt(): 부동소수점 오차 없는 정수 제곱근

    [참고 풀이] 다른 사용자 방식 - float % 1 트릭
        sum(n if (n**0.5) % 1 else -n for n in range(left, right+1))
        - (n**0.5) % 1: 소수점 이하가 0이면 완전제곱수 (float 전용 트릭)
        - 이 문제 범위(<=1,000)에서는 부동소수점 오류 없음 (실측 확인)
        - 단, 큰 수에서 n**0.5가 k.0000...로 나올 경우 오판 위험 존재
        - math.isqrt()로 전환 불가 (isqrt는 정수 반환 -> %1 항상 0)
        - Best(isqrt)가 안정성과 가독성 모두 우위
    """
    answer = 0

    for i in range(left, right + 1):
        if math.isqrt(i) ** 2 == i:     # 완전제곱수: 약수 개수 홀수
            answer -= i
        else:                           # 그 외: 약수 개수 짝수
            answer += i

    return answer


# ==============================================================================
# Sub solution - Mine_two + √N 최적화
# ==============================================================================
def solution_sub(left: int, right: int) -> int:
    """
    약수 탐색 범위를 √i로 줄이고 쌍을 동시에 카운트하는 풀이

    Mine_two 대비 개선:
        - range(1, i+1) -> range(1, isqrt(i)+1): 탐색 범위 √N으로 축소
        - 약수 발견 시 count+=2 (쌍 동시 카운트)
        - 완전제곱수 예외: j == i//j 일 때 count-=1 (중복 방지)

    시간복잡도: O(N²) → O(N√N)
    Best(O(N))보다는 느리지만 Mine_two보다 효율적
    """
    answer = 0

    for i in range(left, right + 1):
        count = 0

        for j in range(1, math.isqrt(i) + 1):   # √i까지만 탐색
            if i % j == 0:
                count += 2                      # 약수 쌍 (j, i//j) 동시 카운트
                if j == i // j:                 # 완전제곱수: j와 i//j가 동일
                    count -= 1                  # 중복 제거

        if count % 2 == 0:
            answer += i
        else:
            answer -= i

    return answer


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int, int]] = [
        # (left, right, 기댓값)
        (13, 17, 43),  # 기본 예시 1
        (24, 27, 52),  # 기본 예시 2
        (1, 1, -1),  # 1은 완전제곱수(1²=1), 약수 1개(홀수) → -1
        (4, 4, -4),  # 4는 완전제곱수(2²=4), 약수 3개(홀수) → -4
        (3, 3, 3),  # 3은 완전제곱수 아님, 약수 2개(짝수) → +3
        (1, 10, 27),  # 1~10: 완전제곱수 1,4,9 → -14, 나머지 → +41, 합=27
        (1, 1000, 479668),  # 최대 범위 (완전제곱수: 1,4,...,961 총 31개)
    ]

    solutions = [
        ("Mine_one (완전제곱수 판별)", solution_mine_one),
        ("Mine_two (완전탐색 O(N²))", solution_mine_two),
        ("Best     (완전제곱수+주석)", solution_best),
        ("Sub      (√N 약수탐색)", solution_sub),
    ]

    print("=" * 68)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 68)

    for name, func in solutions:
        for idx, (left, right, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(left, right)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 68)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
