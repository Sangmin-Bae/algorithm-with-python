"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 내적
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/70128
    풀이일자   : 2025-05-21
===================================================================================
[문제 요약]
    길이가 같은 두 벡터 a, b의 내적을 반환
    내적 = a[0]xb[0] + a[1]xb[1] + ... + a[n-1]xb[n-1]

    제약 조건
        - a, b 길이 동일 보장 (1 이상 1,000 이하)
        - 원소값: -1,000 이상 1,000 이하 정수
===================================================================================
[입출력 예시]
    a           | b             | result
    ------------|---------------|--------
    [1,2,3,4]   | [-3,-1,0,2]   | 3         (1x-3 + 2x-1 + 3x0 + 4x2 = 3)
    [-1,0,-1]   | [1,0,-1]      | -2        (-1x1 + 0x0 + 1x-1 = -2)
===================================================================================
[내 초기 풀이]
    solution_one: sum(i * j for i, j in zip(a, b))
        수학 공식(Σaᵢ×bᵢ)과 1:1 대응되는 파이써닉한 한 줄 풀이
        zip으로 동시 순회, 제너레이터로 중간 리스트 없이 합산

[검토 후 제외한 방식들]
    명시적 반복문:
        합산 변수(total) 추가 필요, 코드 길어짐, 복잡도 개선 없음
        -> Sub로 보존

    range(len()) 인덱스 접근:
        두 리스트 동시 순회 시 zip이 더 자연스러움
        인덱스가 목적이 아닌 상황에서 불필요한 방식

    이중 for문:
        같은 위치 원소끼리의 연산 -> 이중 구조 불필요
        O(N²)로 복잡도 약화
===================================================================================
[수학적 배경 - 내적(Dot Product)]
    수식: a·b = Σ(aᵢ × bᵢ)
    기하학적 의미: a·b = |a| × |b| × cos(θ)
        θ > 0 → 같은 방향 (θ < 90°)
        θ = 0 → 수직      (θ = 90°)
        θ < 0 → 반대 방향 (θ > 90°)
    활용: 머신러닝의 가중합, 유사도 계산, 행렬 곱셈의 기본 연산
===================================================================================
[복잡도 분석]
    N = len(a) = len(b) (최대 1,000)

    Mine/Best   - 시간: O(N) | 공간: O(1) - 제너레이터, 중간 리스트 없음
    Sub         - 시간: O(N) | 공간: O(1) - total 변수만 추가

    O(N)이 이록적 하한선 - 모든 원소를 최소 1회 접근 필수
===================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution - zip + 제너레이터 + sum (한 줄 풀이)
# ==============================================================================
def solution_mine(a: List[int], b: List[int]) -> int:
    """
    수학 공식 Σ(aᵢ×bᵢ)을 파이써닉하게 표현한 초기 풀이

    선택 근거:
        - zip: 같은 위치 원소 동시 추출, 인덱스 불필요한 상황에 적합
        - 제너레이터: 중간 리스트 생성 없이 sum()에 바로 전달
        - 수학 공식과 코드가 1:1 대응 -> 의되 명확
    """
    return sum(i * j for i, j in zip(a, b))


# ==============================================================================
# Best solution - Mine과 동일, 주석 보강
# ==============================================================================
def solution_best(a: List[int], b: List[int]) -> int:
    """
    내적 공식을 zip + 제너레이터로 구현한 최적 풀이

    Mine과 동일한 로직, 수학적 배경 주석 보강:
        - 내적: Σ(aᵢ×bᵢ), 같은 위치 원소의 곱의 총합
        - zip으로 (aᵢ, bᵢ) 쌍을 순서대로 생성
        - 제너레이터 i*J를 하나씩 생성해 sum()에 전달
        - 중간 리스트 없음 -> 공간 O(1)
    """
    # 내적: 같은 위치 원소의 곱을 합산 Σ(aᵢ×bᵢ)
    return sum(i * j for i, j in zip(a, b))


# ==============================================================================
# Sub solution - 명시적 반복문 + total 누적
# ==============================================================================
def solution_sub(a: List[int], b: List[int]) -> int:
    """
    단계별로 명시적으로 표현한 풀이

    Best 대비 특징:
        - total 변수로 누적 합산 -> 중간값 확인 용이
        - 코드가 길어지지만 각 단계가 명확
        - 복잡도는 Best와 동일, 간결함만 차이

    검토 후 제외한 방식 기록:
        - range(len()): 인덱스 불필요, zip이 더 자연스러움
        - 이중 for문: 같은 위치 연산에 부적합, O(N²) 악화
    """
    total = 0

    for i, j in zip(a, b):
        total += i * j      # 같은 위치 원소의 곱을 누적

    return total


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[int], List[int], int]] = [
        # (a, b, 기댓값)
        ([1, 2, 3, 4], [-3, -1, 0, 2], 3),  # 기본 예시 1
        ([-1, 0, 1], [1, 0, -1], -2),  # 기본 예시 2
        ([1], [1], 1),  # 단일 원소
        ([0, 0, 0], [1, 2, 3], 0),  # 영벡터
        ([-1, -1], [-1, -1], 2),  # 음수 × 음수
        ([1000], [1000], 1000000),  # 최대 원소값
        ([1, 2, 3], [0, 0, 0], 0),  # 영벡터 내적 = 0
    ]

    solutions = [
        ("Mine (zip+generator)", solution_mine),
        ("Best (zip+generator)", solution_best),
        ("Sub  (explicit loop)", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (a, b, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(a[:], b[:])
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()