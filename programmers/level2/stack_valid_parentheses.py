"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 올바른 괄호
    유형       : Stack / Queue
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12909
    풀이일자   : 2026-08-01
================================================================================
[문제 요약]
    '('와 ')'로만 이루어진 문자열 s가 올바른 괄호인지 판별

    올바른 괄호: '('로 열리면 반드시 ')'로 닫혀야 함
    제약 조건
        - s 길이: 100,000 이하 자연수
        - s는 '(' 또는 ')'로만 구성
        - 효율성 테스트 있음
================================================================================
[입출력 예시]
    s        | answer
    ---------|-------
    "()()"   | true
    "(())()" | true
    ")()("   | false
    "(()("   | false
================================================================================
[핵심 아이디어 — 스택으로 쌍 매칭]
    '('를 만나면 스택에 push
    ')'를 만나면 스택에서 pop (쌍 완성)
    스택이 비었는데 ')'를 만나면 → 닫을 '('가 없음 → False
    순회 후 스택이 비어있으면 → 모든 쌍 완성 → True
    스택에 '('가 남아있으면 → 닫히지 않은 괄호 존재 → False

[손 추적 — "(())"]
    '(': stack=['(']
    '(': stack=['(','(']
    ')': stack=['('] (쌍 완성)
    ')': stack=[]    (쌍 완성)
    반환: len(stack)==0 → True ✓

[손 추적 — ")("]
    ')': stack 비어있음 → False 즉시 반환 ✓

[리스트 스택 vs 정수 스택 성능 비교]
    실측 (s 길이 100,000, 1,000회 반복):

    케이스          | 리스트 스택 | 정수 스택
    ----------------|-------------|----------
    올바른(50k쌍)   | 2.89ms      | 3.38ms  (케이스 따라 교차)
    반복()(50k)     | 3.11ms      | 2.54ms

    리스트 스택이 느린 경우:
        '(' 연속으로 50,000개 쌓이는 패턴
        리스트가 최대 50,000개까지 커짐 → 동적 메모리 재할당 발생
        재할당: 기존 배열 복사 + 새 메모리 할당

    정수 스택이 일관적인 이유:
        정수 변수 하나만 관리 → 메모리 재할당 없음
        어떤 입력 패턴에도 동일한 비용 구조

    stack < 1 vs stack == 0:
        이 문제에서 동일 (음수가 되기 전에 False 반환)
        not stack으로도 표현 가능 (0이 falsy)
================================================================================
[내 초기 풀이]
    solution_mine_one: 리스트를 스택으로 사용 (append/pop)
    solution_mine_two: 정수를 스택 카운터로 사용 (+1/-1)

[개선 포인트]
    solution_mine_one: 개선 필요 없음 - Sub
                       리스트 스택으로 동작 원리 명시적 표현
                       '(' 연속 패턴에서 리스트 재할당 비용 존재
    solution_mine_two: 개선 필요 없음 - Best
                       정수 카운터로 메모리 재할당 없음
                       어떤 입력 패턴에도 일관된 성능
================================================================================
[복잡도 분석]
    N = len(s) (최대 100,000)

    Mine_one - 시간: O(N) | 공간: O(N) - 리스트 스택 최대 N/2 크기
    Mine_two - 시간: O(N) | 공간: O(1) - 정수 카운터 변수 하나
    Best     - 시간: O(N) | 공간: O(1) - Mine_two와 동일
    Sub      - 시간: O(N) | 공간: O(N) - Mine_one과 동일
"""

import time


# ================================================================================
# Mine solution one - 리스트 스택 (append/pop)
# ================================================================================
def solution_mine_one(s: str) -> bool:
    """
    리스트를 스택으로 사용해 괄호 쌍을 매칭하는 초기 풀이

    핵심:
        '(': stack.append → 열린 괄호 저장
        ')': stack.pop → 쌍 완성 (닫힌 괄호 소비)
        not stack + ')': 닫을 '('가 없음 → 즉시 False

    if not stack:
        빈 스택에 pop()하면 IndexError 발생
        → ')'를 만났는데 매칭할 '('가 없다는 의미이기도 함
        두 역할을 동시에 수행

    else 사용 이유:
        s는 '('와 ')' 로만 구성 (제약 조건)
        '(' 아닌 경우 = ')' 확정 → if/elif 대신 else
    """
    stack = []

    for char in s:
        if char == "(":
            stack.append(char)
        else:
            if not stack:
                return False
            stack.pop()

    return len(stack) == 0


# ================================================================================
# Mine solution two - 정수 카운터 스택 (+1/-1)
# ================================================================================
def solution_mine_two(s: str) -> bool:
    """
    정수 카운터로 스택의 크기를 추적해 괄호 쌍을 매칭하는 풀이

    mine_one 대비:
        리스트 객체 생성 없음 → 메모리 재할당 없음
        '(': stack += 1 (push 대신)
        ')': stack -= 1 (pop 대신)
        공간 O(N) → O(1)

    stack < 1:
        ')' 를 만났는데 stack이 0 → 닫을 '('가 없음 → False
        이 조건 덕에 stack이 음수가 될 일 없음
        stack < 1 == not stack == stack == 0 (이 문제에서 동일)
    """
    stack = 0

    for char in s:
        if char == "(":
            stack += 1
        else:
            if stack < 1:
                return False
            stack -= 1

    return stack == 0


# ================================================================================
# Best solution - 정수 카운터 (mine_two 주석 보강)
# ================================================================================
def solution_best(s: str) -> bool:
    """
    정수 카운터로 O(1) 공간에서 올바른 괄호를 판별하는 최적 풀이

    mine_two와 동일한 로직, 선정 근거 주석 보강:
        공간 O(1): 정수 변수 하나로 스택 역할 대체
        메모리 재할당 없음: 리스트 스택 대비 '(' 연속 패턴에서 안정적
        일관된 성능: 입력 패턴에 무관하게 동일한 비용 구조
    """
    stack = 0

    for char in s:
        if char == "(":
            stack += 1
        else:
            if stack < 1:
                return False
            stack -= 1

    return stack == 0


# ================================================================================
# Sub solution - 리스트 스택 (mine_one 주석 보강)
# ================================================================================
def solution_sub(s: str) -> bool:
    """
    리스트 스택으로 괄호 쌍 매칭 원리를 명시적으로 표현하는 서브 풀이

    Best 대비 특징:
        append/pop으로 스택 push/pop 동작이 코드에 직접 드러남
        '(' 연속 패턴에서 리스트 동적 재할당 발생 → 최악 케이스에서 느릴 수 있음
        공간 O(N): 최악 '(((..(' 패턴에서 N/2 크기 리스트
        스택 자료구조 개념 학습 목적에 적합
    """
    stack = []

    for char in s:
        if char == "(":
            stack.append(char)
        else:
            if not stack:
                return False
            stack.pop()

    return len(stack) == 0


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[str, bool]] = [
        # (s, 기댓값)
        # 손 추적:
        # "()()" : (→1, )→0, (→1, )→0  → stack=0 → True
        ("()()",   True),
        # "(())()" : (→1, (→2, )→1, )→0, (→1, )→0 → True
        ("(())()", True),
        # ")()(" : ) 만났는데 stack=0 → False
        (")()(", False),
        # "(()(" : 마지막 stack=2 → False
        ("(()(",   False),
        # 추가 케이스:
        ("(",      False),   # 열린 괄호만
        (")",      False),   # 닫힌 괄호만
        ("()",     True),    # 최소 올바른 괄호
    ]

    solutions = [
        ("Mine_one (리스트스택)", solution_mine_one),
        ("Mine_two (정수카운터)", solution_mine_two),
        ("Best     (정수카운터)", solution_best),
        ("Sub      (리스트스택)", solution_sub),
    ]

    # 워밍업 스텝
    _s, _ = test_cases[0]
    for _, func in solutions:
        func(_s)

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
