"""
================================================================================
[문제 정보]
    사이트     : SWEA (SW Expert Academy)
    레벨       : D1
    문제명     : 6302. [파이썬 프로그래밍 기초(2) 파이썬의 기본 응용] 2. 자료구조 -리스트, 튜플 25
    유형       : Filter (위치 기준 제거), List Comprehension
    링크       : https://swexpertacademy.com/main/code/problem/problemDetail.do?contestProbId=AWcV_8mq5Q0DFAU4&categoryId=AWcV_8mq5Q0DFAU4&categoryType=CODE&problemTitle=&orderBy=PASS_RATE&selectCodeLang=ALL&select-1=&pageSize=10&pageIndex=4
    풀이일자   : 2026-10-29
================================================================================
[문제 요약]
    리스트 [12, 24, 35, 70, 88, 120, 155]에서
    첫 번째, 다섯 번째, 여섯 번째 항목을 제거한 리스트를 리스트 내포로 출력

    입력 방식 : 입력 없음 (리스트가 지문에 고정)
    적용 방식 : 고정된 리스트 → 매개변수 array, output → 반환값
    지문 조건 : 리스트 내포 사용
    참고      : "몇 번째"는 1부터 세는 위치 기준 (값 기준이 아님)
================================================================================
[입출력 예시]
    공식 예시
    array                            | return
    ---------------------------------|---------------------
    [12, 24, 35, 70, 88, 120, 155]   | [24, 35, 70, 155]

    자체 검증 케이스 (전부 손 계산)
    array                | return
    ---------------------|--------------------------
    []                   | []
    [5]                  | []                (1번째만 있고 제거됨)
    [1, 2, 3]            | [2, 3]            (5, 6번째가 없으면 1번째만 제거)
    [1, 2, 3, 4, 5]      | [2, 3, 4]         (1, 5번째 제거)
    [1, 2, 3, 4, 5, 6]   | [2, 3, 4]         (1, 5, 6번째 제거)
    [1, ..., 10]         | [2, 3, 4, 7, 8, 9, 10]
    [12] * 7             | [12, 12, 12, 12]  (같은 값이어도 위치 기준으로 3개만 제거)
    [1, ..., 100000]     | [2, 3, 4, 7, ..., 100000]  (대용량, 닫힌 식으로 기댓값 계산)
================================================================================
[풀이 전략]
    핵심: 값이 아니라 위치(순서)를 기준으로 제거
        enumerate : 원소와 위치를 함께 순회
        제거할 위치에 해당하지 않는 원소만 새 리스트에 담음
        지문의 "첫 번째, 다섯 번째, 여섯 번째"는 1부터 센 위치
        → 위치를 1부터 세면 {1, 5, 6}을 그대로 사용 가능

    위치를 1부터 세는 방법:
        mine_one : enumerate(array) 의 0부터 시작하는 인덱스에 1을 더해 비교 (idx + 1)
        best     : enumerate(array, 1) 로 시작값을 1로 지정, 더하기 없이 {1, 5, 6}과 비교
        sub      : 0부터 시작하는 인덱스에 맞춰 제거 위치를 {0, 4, 5}로 변환

    in 연산에 쓰는 컬렉션:
        리스트, 튜플은 앞에서부터 하나씩 비교, 집합은 해시로 조회
        비교 대상이 3개뿐이라 차이는 작음

    풀이 구성:
        mine_one : enumerate + idx + 1 not in [1, 5, 6] (직접 작성한 풀이)
        best     : enumerate(array, 1) + not in {1, 5, 6}
                   mine_one에서 idx + 1 계산을 없애고 집합으로 대체
        sub      : enumerate(array) + not in {0, 4, 5}
                   지문의 순서(1부터)를 인덱스(0부터)로 바꿔 써야 함

    손 추적 (공식 예시):
        위치 1: 12  → 제거
        위치 2: 24  → 유지
        위치 3: 35  → 유지
        위치 4: 70  → 유지
        위치 5: 88  → 제거
        위치 6: 120 → 제거
        위치 7: 155 → 유지
        → [24, 35, 70, 155] ✓
================================================================================
[개선 포인트]
    solution_mine_one : 개선 여지 있음 - idx + 1 계산을 enumerate의 시작값 지정으로 대체 가능
    solution_best     : 시작값 1 지정 + 집합 조회 - Best
    solution_sub      : 0부터 시작하는 인덱스 기준 - 지문 순서와 다른 숫자를 써야 함
================================================================================
[복잡도 분석]
    n = len(array)

    Mine_one - 시간: O(n) | 공간: O(n) - 원소마다 위치 비교 (비교 대상 3개 고정), 결과 리스트 저장
    Best     - 시간: O(n) | 공간: O(n) - mine_one과 동일
    Sub      - 시간: O(n) | 공간: O(n) - mine_one과 동일
"""

import time


# ================================================================================
# Mine solution one - enumerate + idx + 1
# ================================================================================
def solution_mine_one(array: list[int]) -> list[int]:
    """
    enumerate의 인덱스에 1을 더해 지문의 위치(1부터)와 비교하는 직접 작성한 풀이

    핵심:
        idx + 1 not in [1, 5, 6] : 제거 대상 위치가 아닌 원소만 유지
        지문의 순서 표현을 그대로 사용
    """
    return [n for idx, n in enumerate(array) if idx + 1 not in [1, 5, 6]]


# ================================================================================
# Best solution - enumerate(array, 1) + 집합
# ================================================================================
def solution_best(array: list[int]) -> list[int]:
    """
    enumerate의 시작값을 1로 지정하고 집합으로 제거 위치를 조회하는 최적 풀이

    핵심:
        enumerate(array, 1) : 위치를 1부터 셈, idx + 1 계산 불필요
        not in {1, 5, 6} : 제거할 위치를 지문 표현 그대로 집합으로 조회
    """
    return [n for idx, n in enumerate(array, 1) if idx not in {1, 5, 6}]


# ================================================================================
# Sub solution - enumerate + 0부터 시작하는 인덱스
# ================================================================================
def solution_sub(array: list[int]) -> list[int]:
    """
    0부터 시작하는 인덱스에 맞춰 제거 위치를 변환한 풀이

    핵심:
        첫 번째, 다섯 번째, 여섯 번째 → 인덱스 0, 4, 5
        not in {0, 4, 5} : 제거할 인덱스가 아닌 원소만 유지
    """
    return [n for idx, n in enumerate(array) if idx not in {0, 4, 5}]


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (array, 기댓값) - 전부 손 계산
        ([12, 24, 35, 70, 88, 120, 155], [24, 35, 70, 155]),    # 공식 예시
        ([], []),                                               # 빈 리스트 경계
        ([5], []),                                              # 1번째만 있음
        ([1, 2, 3], [2, 3]),                                    # 5, 6번째 없음
        ([1, 2, 3, 4, 5], [2, 3, 4]),                           # 1, 5번째 제거
        ([1, 2, 3, 4, 5, 6], [2, 3, 4]),                        # 1, 5, 6번째 제거
        (list(range(1, 11)), [2, 3, 4, 7, 8, 9, 10]),           # 10개
        ([12] * 7, [12, 12, 12, 12]),                           # 같은 값, 위치 기준 제거
        (list(range(1, 100001)),
         [2, 3, 4] + list(range(7, 100001))),                   # 대용량: 1, 5, 6번째 제거
    ]

    solutions = [
        ("Mine (idx + 1)", solution_mine_one),
        ("Best (start=1)", solution_best),
        ("Sub (0부터)", solution_sub),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
