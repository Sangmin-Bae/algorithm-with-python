"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 문자열 내림차순으로 배치하기
    유형       : Sort / String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12917
    풀이일자   : 2026-06-23
===================================================================================
[문제 요약]
    문자열 s의 각 문자를 큰 것부터 작은 순으로 정렬해 새로운 문자열 반환
    대문자는 소문자보다 작은 것으로 간주

    제약 조건
        - s 길이: 1 이상
        - 영문 대소문자로만 구성
        - 대문자 < 소문자 → Python 기본 ASCII 비교 순서와 일치
===================================================================================
[입출력 예시]
    s         | return
    ----------|-------
    "Zbcdefg" | "gfedcbZ"  (g=103 > f=102 > ... > b=98 > Z=90)
===================================================================================
[ASCII 코드 기반 정렬 근거]
    Python 문자 비교는 ASCII 코드 값 기준:
        대문자 A-Z: 65~90
        소문자 a-z: 97~122
        소문자 > 대문자 (ASCII 값 기준)

    문제 조건 "대문자는 소문자보다 작다"
        = Python 기본 문자 비교 순서와 완전히 일치
        = sorted(reverse=True)만으로 조건 충족, 별도 key 불필요

    손 추적 ("Zbcdefg"):
        Z=90, b=98, c=99, d=100, e=101, f=102, g=103
        내림차순: g(103) > f(102) > e(101) > d(100) > c(99) > b(98) > Z(90)
        → "gfedcbZ" ✓

    손 추적 ("aAbB"):
        a=97, A=65, b=98, B=66
        내림차순: b(98) > a(97) > B(66) > A(65)
        → "baBA" ✓
===================================================================================
[내 초기 풀이]
    solution_mine: sorted(reverse=True) + join

    핵심:
        sorted(s, reverse=True): 문자열을 이터러블로 받아 내림차순 정렬된 리스트 반환
        ''.join(...): 문자 리스트를 하나의 문자열로 결합

    기대와의 차이:
        초기 기대: "대문자가 먼저 오는 내림차순" → key 커스텀 필요
        실제 문제: "대문자 < 소문자" = ASCII 기본 순서 → key 불필요
        → sorted(reverse=True)만으로 해결 가능한 문제였음

[개선 포인트]
    solution_mine: 개선 필요 없음 - Best, Sub 없음

    Sub 채택 불가 이유:
        key=ord 방식: sorted(reverse=True)와 결과 동일 + ord() 호출 N회 오버헤드
            → 결과도 같고 더 느림, 존재 의미 없음
        ord() / chr() 변환, 대소문자 분리 후 합치기:
            sorted()가 내부적으로 처리하는 걸 Python 레벨에서 재구현
            더 복잡하고 느리므로 불필요
===================================================================================
[key 매개변수 — 커스텀 정렬 조건이 필요한 경우 참고]
    이 문제는 key 불필요. 조건이 달랐다면 필요했을 상황:

    예) "대문자가 소문자보다 크다"는 반대 조건의 내림차순:
        sorted(s, key=str.swapcase, reverse=True)
        swapcase(): 대↔소문자 반전 → 원래 대문자가 소문자로 변해 key값이 커짐
        → 대문자가 내림차순 앞에 오는 효과

        손 추적 ("aAbB", 반대 조건):
            a → A(65), A → a(97), b → B(66), B → b(98)
            key 내림차순: b(98) > a(97) > B(66) > A(65)
            대응 원본:     B        A        b        a
            결과: "BAba" (대문자 먼저)
===================================================================================
[복잡도 분석]
    N = len(s)

    Mine - 시간: O(N log N) | 공간: O(N) - sorted 결과 리스트 + join
    Best - 시간: O(N log N) | 공간: O(N) - Mine과 동일, 주석 보강

    정렬(O(N log N))이 지배
    이 문제에서 Best보다 나은 Sub 풀이 없음
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - sorted(reverse=True) + join
# =================================================================================
def solution_mine(s: str) -> str:
    """
    sorted()로 내림차순 정렬 후 join으로 결합하는 초기 풀이

    핵심:
        sorted(s, reverse=True): 문자열을 이터러블로 받아 내림차순 리스트 반환
        Python 문자 비교 = ASCII 코드 기준
        소문자(97~122) > 대문자(65~90) → 문제 조건과 일치, key 불필요
        ''.join(...): 문자 리스트 → 문자열 결합

    별도 key 불필요한 이유:
        문제 조건 "대문자 < 소문자" = Python 기본 ASCII 비교 순서
        sorted(reverse=True)만으로 의도한 결과 충족
    """
    return ''.join(sorted(s, reverse=True))


# =================================================================================
# Best solution - Mine 주석 보강
# =================================================================================
def solution_best(s: str) -> str:
    """
    ASCII 코드 기반 기본 정렬로 문제 조건을 자연스럽게 충족하는 최적 풀이

    Mine과 동일한 로직, 근거 주석 보강:
        sorted()는 C 레벨 Timsort 구현 → Python 루프보다 빠름
        문자열 자체가 이터러블 → 별도 리스트 변환 없이 직접 전달
        reverse=True: 내림차순 (기본값 False = 오름차순)
        key 미지정 → Python 기본 비교(ASCII) 사용 → 문제 조건과 일치

    Sub 없는 이유:
        key=ord: 결과 동일 + ord() N회 호출 오버헤드 → 개선 아님
        다른 방식(대소문자 분리 후 합치기 등): 더 복잡하고 느림
    """
    return ''.join(sorted(s, reverse=True))  # ASCII 내림차순 → 소문자 먼저, 대문자 뒤


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[str, str]] = [
        # (s, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # "Zbcdefg": Z=90, b=98, c=99, d=100, e=101, f=102, g=103
        #   내림차순: g>f>e>d>c>b>Z → "gfedcbZ"
        ("Zbcdefg",  "gfedcbZ"),
        # 추가 케이스:
        # "a": 단일 문자 → "a"
        ("a",        "a"),
        # "AbCd": A=65, C=67, b=98, d=100
        #   내림차순: d(100)>b(98)>C(67)>A(65) → "dbCA"
        ("AbCd",     "dbCA"),
        # "zZaA": z=122, a=97, Z=90, A=65
        #   내림차순: z(122)>a(97)>Z(90)>A(65) → "zaZA"
        ("zZaA",     "zaZA"),
        # "aAbB": a=97, A=65, b=98, B=66
        #   내림차순: b(98)>a(97)>B(66)>A(65) → "baBA"
        ("aAbB",     "baBA"),
        # "ZYXW": 모두 대문자, Z=90>Y=89>X=88>W=87 → "ZYXW"
        ("ZYXW",     "ZYXW"),
    ]

    solutions = [
        ("Mine (sorted+join)", solution_mine),
        ("Best (sorted+join)", solution_best),
    ]

    print("=" * 58)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 58)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 58)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
