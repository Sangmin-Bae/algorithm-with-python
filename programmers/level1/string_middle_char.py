"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 가운데 글자 가져오기
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12903
    풀이일자   : 2026-06-20
===================================================================================
[문제 요약]
    문자열 s의 가운데 글자 반환
    홀수 길이 → 가운데 1글자
    짝수 길이 → 가운데 2글자

    제약 조건
        - s 길이: 1 이상 100 이하
        - 길이 1: 홀수 → s[0] 반환
        - 길이 2: 짝수 → s[0:2] = 전체 반환
===================================================================================
[입출력 예시]
    s       | return
    --------|-------
    "abcde" | "c"    (홀수 5, q=2 → s[2]='c')
    "qwer"  | "we"   (짝수 4, q=2 → s[1:3]='we')
===================================================================================
[인덱스 수학 근거]
    q = l // 2: 가운데 인덱스 (홀수) 또는 가운데 오른쪽 인덱스 (짝수)

    손 추적:
        "abcde" (l=5, 홀수): q=5//2=2 → s[2]='c'        ✓
        "qwer"  (l=4, 짝수): q=4//2=2 → s[1:3]='we'     ✓
        "ab"    (l=2, 짝수): q=2//2=1 → s[0:2]='ab'     ✓
        "a"     (l=1, 홀수): q=1//2=0 → s[0]='a'        ✓

    홀짝 분기:
        홀수: l % 2 == 1 → s[q] (1글자)
        짝수: l % 2 == 0 → s[q-1:q+1] (2글자)
===================================================================================
[내 초기 풀이]
    solution_mine: 명시적 변수 l, q + 삼항 연산자

    한 줄 표현 시도 및 막힌 지점:
        (l := len(s)) % 2로 l을 walrus 바인딩까지는 접근
        문제: q = l // 2를 삼항 연산자의 두 항 모두에서 참조해야 함
            삼항 연산자 평가 순서: A if C else B → C(조건) 먼저 평가
            앞 항은 조건 True일 때만, 뒤 항은 False일 때만 실행
            → q를 어느 한 항에서 바인딩하면 다른 항에서 UnboundLocalError 발생
            → 조건절에서만 바인딩해야 두 항 모두에서 참조 가능
            → 이 구조에서 walrus 한 줄 표현이 안전하게 동작하지 않음

[개선 포인트]
    solution_mine: 개선 필요 없음 - Best
        명시적 변수 l, q가 인덱스 계산 의도를 가장 명확히 표현
        q를 두 항 모두에서 참조하는 구조에서는 walrus 한 줄이 근본적으로 불가
===================================================================================
[한 줄 표현 — walrus 활용]
    s[l // 2] if (l := len(s)) % 2 else s[l//2 - 1: l // 2 + 1]

    핵심 발상:
        q 변수에 집착하지 않으면 l // 2를 두 항에서 직접 써도 됨
        l // 2는 O(1) 정수 나눗셈 → 두 번 써도 O(1) + O(1) = O(1)

    walrus 바인딩 위치:
        (l := len(s)): 조건절에서 바인딩 → 앞/뒤 항 모두에서 l 참조 가능

    시도 과정에서 발견된 함정:
        s[(q := (l := len(s))//2)] if l % 2 else s[q-1:q+1]
            → 조건(l%2) 먼저 평가, l 미정의 → UnboundLocalError
        s[(q := len(s)//2)] if (l := len(s)) % 2 else s[q-1:q+1]
            → 짝수 시 앞 항 미실행 → q 미정의 → UnboundLocalError
        s[l//2] if (l := len(s)) % 2 else s[l//2-1:l//2+1]
            → l만 조건절에서 바인딩, l//2 직접 계산 → 안전하게 동작 ✓
===================================================================================
[복잡도 분석]
    N = len(s) (최대 100, 사실상 상수)

    Mine - 시간: O(1) | 공간: O(1) - 인덱스 산술 연산, 결과 최대 2글자
    Best - 시간: O(1) | 공간: O(1) - Mine과 동일, 주석 보강
    Sub  - 시간: O(1) | 공간: O(1) - walrus 한 줄, l//2 두 번 계산
    Ref  - 시간: O(1) | 공간: O(1) - 슬라이싱 수식 통일, 삼항 연산자 없음

    슬라이싱 결과: 최대 2글자 → O(1)
    N ≤ 100 고정 → 모든 풀이 실질적으로 O(1)에 수렴
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - 명시적 변수 l, q + 삼항 연산자
# =================================================================================
def solution_mine(s: str) -> str:
    """
    길이와 중앙 인덱스를 명시적 변수로 분리하고 삼항 연산자로 홀짝 분기하는 초기 풀이

    핵심:
        l = len(s): 문자열 길이
        q = l // 2: 가운데 인덱스 (홀수) 또는 가운데 오른쪽 인덱스 (짝수)
        l % 2: 홀수 True → s[q], 짝수 False → s[q-1:q+1]
    """
    l = len(s)
    q = l // 2

    return s[q] if l % 2 else s[q - 1:q + 1]


# =================================================================================
# Best solution - Mine 주석 보강
# =================================================================================
def solution_best(s: str) -> str:
    """
    명시적 변수와 삼항 연산자로 홀짝을 분기하는 최적 풀이

    Mine과 동일한 로직, 근거 주석 보강:
        q = l // 2: 홀수이면 정중앙 인덱스, 짝수이면 가운데 오른쪽 인덱스
        홀수: s[q] → 1글자
        짝수: s[q-1:q+1] → q-1 이상 q 이하 2글자

    walrus 한 줄이 불가한 이유:
        q를 삼항 연산자 두 항 모두에서 참조해야 하는 구조
        조건절에서만 바인딩 가능한데, q=0 케이스에서 falsy 함정 발생
        → 명시적 변수가 유일하게 안전한 선택
    """
    l = len(s)
    q = l // 2

    return s[q] if l % 2 else s[q - 1:q + 1]  # 홀수 → 1글자, 짝수 → 2글자


# =================================================================================
# Sub solution - walrus 한 줄 표현 (l만 바인딩)
# =================================================================================
def solution_sub(s: str) -> str:
    """
    walrus로 l만 바인딩하고 l // 2 연산을 직접 사용하는 한 줄 풀이

    핵심 발상:
        q 변수에 집착하지 않으면 l // 2 자체를 두 항에서 직접 쓸 수 있음
        l // 2는 O(1) 정수 나눗셈 → 두 번 연산해도 O(1) + O(1) = O(1)

    walrus 바인딩 위치:
        (l := len(s)): 조건절에서 l 바인딩
        → 앞 항(s[l//2])과 뒤 항(s[l//2-1:l//2+1]) 모두에서 l 참조 가능
        → q 바인딩 불필요, l // 2를 각 항에서 직접 계산

    이전 시도들의 실패 원인과 비교:
        s[(q := (l := len(s))//2)] if l % 2 else s[q-1:q+1]
            → 조건(l%2)이 먼저 평가, l 미정의 → UnboundLocalError
        s[(q := len(s)//2)] if (l := len(s)) % 2 else s[q-1:q+1]
            → 짝수일 때 앞 항 미실행 → q 미정의 → UnboundLocalError
        s[l//2] if (l := len(s)) % 2 else s[l//2-1:l//2+1]  ← 이 방식
            → l만 조건절에서 바인딩, 두 항에서 l//2 직접 계산 → 안전
    """
    return s[l // 2] if (l := len(s)) % 2 else s[l // 2 - 1: l // 2 + 1]


# =================================================================================
# Ref solution - 삼항 연산자 없이 슬라이싱 수식으로 통일
# =================================================================================
def solution_ref(s: str) -> str:
    """
    삼항 연산자 없이 슬라이싱 범위를 수식 하나로 통일하는 풀이

    핵심 아이디어:
        홀짝 분기를 조건문 없이 시작 인덱스 수식으로 흡수
        s[l//2 - (1 - l%2) : l//2 + 1]
            홀수(l%2=1): 1-1=0 → s[l//2 - 0 : l//2+1] = s[q:q+1]   → 1글자
            짝수(l%2=0): 1-0=1 → s[l//2 - 1 : l//2+1] = s[q-1:q+1] → 2글자

    손 추적:
        "abcde" (l=5, 홀수): s[2-(1-1):2+1] = s[2:3] = 'c'  ✓
        "qwer"  (l=4, 짝수): s[2-(1-0):2+1] = s[1:3] = 'we' ✓
        "a"     (l=1, 홀수): s[0-(1-1):0+1] = s[0:1] = 'a'  ✓
        "ab"    (l=2, 짝수): s[1-(1-0):1+1] = s[0:2] = 'ab' ✓

    Best 대비 특징:
        삼항 연산자, walrus 없이 수학 수식 하나로 처리
        `(1 - l%2)`: 홀수=0, 짝수=1 → 시작 인덱스 조정값
        가독성은 낮지만 예상을 벗어난 접근이라 참고 가치 있음
    """
    l = len(s)
    return s[l // 2 - (1 - l % 2): l // 2 + 1]


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[str, str]] = [
        # (s, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # "abcde": l=5, q=2 → 홀수 → s[2]='c'
        ("abcde", "c"),
        # "qwer": l=4, q=2 → 짝수 → s[1:3]='we'
        ("qwer",  "we"),
        # 추가 케이스:
        # "a": l=1, q=0 → 홀수 → s[0]='a'  (최소 길이, q=0 엣지케이스)
        ("a",     "a"),
        # "ab": l=2, q=1 → 짝수 → s[0:2]='ab'
        ("ab",    "ab"),
        # "abc": l=3, q=1 → 홀수 → s[1]='b'
        ("abc",   "b"),
        # "abcd": l=4, q=2 → 짝수 → s[1:3]='bc'
        ("abcd",  "bc"),
    ]

    solutions = [
        ("Mine (명시적 변수)   ", solution_mine),
        ("Best (명시적 변수)   ", solution_best),
        ("Sub  (walrus 한 줄)  ", solution_sub),
        ("Ref  (슬라이싱 통일) ", solution_ref),
    ]

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()