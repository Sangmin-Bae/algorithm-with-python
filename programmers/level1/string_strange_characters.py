"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 이상한 문자 만들기
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12930
    풀이일자   : 2026-07-01
===================================================================================
[문제 요약]
    문자열 s를 공백 기준으로 단어 분리 후
    각 단어의 짝수 인덱스(0,2,4...) → 대문자, 홀수 인덱스(1,3,5...) → 소문자 변환
    변환된 단어들을 다시 공백으로 결합하여 반환

    제약 조건
        - 단어 구분: "하나 이상의 공백문자"
        - 각 단어별로 인덱스를 독립적으로 적용 (전체 문자열 인덱스 아님)
        - 첫 번째 글자 = 0번째 인덱스 = 짝수 → 대문자
===================================================================================
[입출력 예시]
    s                | return
    -----------------|-------------------
    "try hello world"| "TrY HeLlO WoRlD"
===================================================================================
[핵심 포인트 — split(' ') vs split()]
    지문: "하나 이상의 공백문자로 구분"
    → 연속 공백이 있을 수 있음 → 공백 보존 필요

    s = "try  hello"  (공백 2개)
        s.split(' ')  → ['try', '', 'hello']   공백 사이 빈 문자열 생성
        s.split()     → ['try', 'hello']        연속 공백 무시, 빈 문자열 없음

    split()를 쓰면 연속 공백 정보 손실:
        ' '.join(['try', 'hello']) → "try hello"  (공백 1개로 압축)

    split(' ')를 쓰면 공백 보존:
        '' 변환 결과도 '' → ' '.join(['try', '', 'hello']) → "try  hello" (공백 유지)

    → 이 문제에서 split(' ')가 올바른 선택
===================================================================================
[내 초기 풀이]
    solution_mine_one: 이중 for 루프 + enumerate + upper/lower
    solution_mine_two: 중첩 리스트 컴프리헨션 원라인

[개선 포인트]
    solution_mine_one: 개선 필요 없음 - Best
        단어별 독립 인덱스라는 로직이 이중 루프 구조에 직접 대응
        각 단계(단어 분리 → 문자 변환 → 결합)가 명확히 드러남

    solution_mine_two:
        ["".join([...])]: 내부 리스트 컴프리헨션 → 중간 리스트 객체 생성
        "".join()은 제너레이터도 수용 가능하나 join() + 제너레이터는 실제로 더 느림
        → Sub는 개선이 아닌 join() + 제너레이터 동작 원리 기록 목적
===================================================================================
[join() + 제너레이터 vs 리스트 컴프리헨션 — 중요한 반례]
    직관: 제너레이터 = 중간 리스트 없음 → 더 빠를 것
    실측: join() + 제너레이터가 join() + 리스트보다 느림

    CPython join() 내부 동작 차이:
        join(리스트 컴프리헨션):
            리스트 길이를 미리 알 수 있음
            → 결과 문자열 메모리 한 번에 할당
            → 1회 순회로 완성

        join(제너레이터):
            길이를 미리 알 수 없음
            → 내부에서 임시 리스트를 만들며 원소 수집 (1회 순회)
            → 임시 리스트 기반 메모리 할당 후 결과 문자열 구성 (2회 순회)
            → 외부에서 리스트를 만들어 넘기는 것과 동일한 메모리 생성 + 추가 순회

    실측 결과 (timeit 200,000회 평균):
        join(리스트 컴프리헨션): 약 2.19μs
        join(제너레이터):        약 3.19μs  ← 약 46% 느림

    join()에서는 리스트 컴프리헨션이 유리
    제너레이터가 유리한 경우: sum(), any(), all()처럼 조기 종료 가능하거나 원소를 하나씩 소비하는 함수에 넘길 때
===================================================================================
[복잡도 분석]
    N = len(s), W = 단어 수, L = 단어 평균 길이

    Mine_one - 시간: O(N) | 공간: O(N) - 전체 문자 1회 순회, answer 리스트
    Mine_two - 시간: O(N) | 공간: O(N) - 중첩 컴프리헨션, 중간 리스트 생성
    Best     - 시간: O(N) | 공간: O(N) - Mine_one과 동일, 주석 보강
    Sub      - 시간: O(N) | 공간: O(N) - 제너레이터 사용, join() 내부 임시 리스트 생성

    모든 풀이 시간복잡도 O(N) — 전체 문자 1회 순회가 지배
    Sub: 중간 리스트를 제거했지만 join() 내부에서 임시 리스트를 생성
         → Mine_two 대비 실제 성능 개선 없음, 오히려 2회 순회로 느림
"""

import time


# =================================================================================
# Mine solution one - 이중 for 루프 + enumerate
# =================================================================================
def solution_mine_one(s: str) -> str:
    """
    이중 for 루프로 단어별 문자를 변환하는 명시적 초기 풀이

    핵심:
        s.split(' '): 공백 기준 분리, 연속 공백 → 빈 문자열로 보존
        enumerate(word): 문자와 인덱스 동시 접근
        idx % 2: 0이면 짝수(대문자), 1이면 홀수(소문자)
        ' '.join(answer): 공백으로 단어 결합 (연속 공백도 복원)
    """
    answer = []

    for word in s.split(' '):
        converted = ''
        for idx, char in enumerate(word):
            if idx % 2:
                converted += char.lower()   # 홀수 인덱스 → 소문자
            else:
                converted += char.upper()   # 짝수 인덱스 → 대문자
        answer.append(converted)

    return ' '.join(answer)


# =================================================================================
# Mine solution two - 중첩 리스트 컴프리헨션 원라인
# =================================================================================
def solution_mine_two(s: str) -> str:
    """
    중첩 리스트 컴프리헨션으로 mine_one을 원라인으로 압축한 풀이

    구조:
        외부: [... for word in s.split(' ')] → 단어별 변환 리스트 생성
        내부: ["".join([...])]: 각 단어의 문자 변환 후 결합
        ' '.join([...]): 단어들을 공백으로 결합

    개선 가능:
        내부 ["".join([...])]의 리스트 컴프리헨션 → 제너레이터로 교체
        "".join()이 이터러블을 직접 받으므로 [...]가 불필요
    """
    return ' '.join(["".join([char.lower() if idx % 2 else char.upper() for idx, char in enumerate(word)]) for word in s.split(' ')])


# =================================================================================
# Best solution - 이중 for 루프 (mine_one 주석 보강)
# =================================================================================
def solution_best(s: str) -> str:
    """
    이중 for 루프로 단어별 독립 인덱스 변환을 명시적으로 표현하는 최적 풀이

    mine_one과 동일한 로직, 근거 주석 보강:
        split(' '): 연속 공백 보존 (split()는 공백 정보 손실)
        enumerate: 인덱스와 문자를 동시에 순회하는 Python 관용 패턴
        단어별 독립 인덱스: 이중 루프 구조가 이 조건을 자연스럽게 표현
        join: split(' ')로 분리한 것을 ' '.join으로 복원 → 공백 구조 유지
    """
    answer = []

    for word in s.split(' '):
        converted = ''
        for idx, char in enumerate(word):
            converted += char.upper() if idx % 2 == 0 else char.lower()
        answer.append(converted)

    return ' '.join(answer)


# =================================================================================
# Sub solution - 중첩 컴프리헨션 + 제너레이터 (mine_two 개선)
# =================================================================================
def solution_sub(s: str) -> str:
    """
    join() + 제너레이터 조합의 실제 동작을 확인하기 위한 서브 풀이

    mine_two 대비 변경:
        ["".join([...])] → "".join(...)로 내부 리스트 컴프리헨션 제거
        이론: 중간 리스트 객체 생성 없음 → 메모리 절감 기대

    실제 측정 결과 (timeit 200,000회):
        Mine_two (리스트): 약 2.19μs
        Sub (제너레이터):  약 3.19μs  ← 약 46% 느림

    느린 이유 — CPython join() 내부 동작:
        join(리스트): 길이 미리 파악 → 메모리 한 번 할당 → 1회 순회
        join(제너레이터): 길이 미리 알 수 없음
            → 내부적으로 임시 리스트를 만들며 원소 수집 (1회 순회)
            → 임시 리스트 기반 메모리 할당 후 결과 구성 (2회 순회)
            → 결국 리스트를 외부에서 만들어 넘기는 것과 동일한 메모리 생성
              + 추가 순회 1번 더 발생

    중요한 발견:
        "제너레이터 = 항상 더 빠름"이라는 관념을 깨는 반례
        join()은 예외적으로 리스트 컴프리헨션이 더 빠름
        제너레이터가 유리한 함수: sum(), any(), all() 등 조기 종료 가능하거나 원소를 하나씩 소비하는 경우
    """
    return ' '.join("".join(char.upper() if idx % 2 == 0 else char.lower() for idx, char in enumerate(word)) for word in s.split(' '))


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[str, str]] = [
        # (s, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # "try hello world":
        #   "try"  → T(0)r(1)Y(2) = "TrY"
        #   "hello"→ H(0)e(1)L(2)l(3)O(4) = "HeLlO"
        #   "world"→ W(0)o(1)R(2)l(3)D(4) = "WoRlD"
        #   → "TrY HeLlO WoRlD"
        ("try hello world", "TrY HeLlO WoRlD"),
        # 추가 케이스:
        # 단일 문자 단어: "a" → "A" (idx=0, 짝수)
        ("a", "A"),
        # 연속 공백 처리: "hi  there" (공백 2개)
        #   split(' ') → ['hi', '', 'there']
        #   "hi"→"Hi", ""→"", "there"→"ThErE"
        #   ' '.join → "Hi  ThErE" (공백 2개 유지)
        ("hi  there", "Hi  ThErE"),
        # 숫자 없이 단어 하나
        ("hello", "HeLlO"),
    ]

    solutions = [
        ("Mine_one (이중루프)    ", solution_mine_one),
        ("Mine_two (중첩컴프리)  ", solution_mine_two),
        ("Best     (이중루프)    ", solution_best),
        ("Sub      (제너레이터)  ", solution_sub),
    ]

    # 워밍업 스텝
    _s, _ = test_cases[0]
    for _, func in solutions:
        func(_s)

    print("=" * 64)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
