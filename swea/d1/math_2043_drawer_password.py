"""
================================================================================
[문제 정보]
    사이트     : SWEA (SW Expert Academy)
    레벨       : D1
    문제명     : 2043. 서랍의 비밀번호
    유형       : Math (구간 정수의 개수)
    링크       : https://swexpertacademy.com/main/code/problem/problemDetail.do?contestProbId=AV5QJ_8KAx8DFAUq&categoryId=AV5QJ_8KAx8DFAUq&categoryType=CODE&problemTitle=&orderBy=PASS_RATE&selectCodeLang=ALL&select-1=&pageSize=10&pageIndex=4
    풀이일자   : 2026-10-25
================================================================================
[문제 요약]
    비밀번호 P (000 ~ 999)와 시작 번호 K가 주어질 때
    K부터 1씩 증가하며 확인해 P를 맞추기까지 몇 번 시도하는지 구함

    입력 방식 : 정수 P, K (입력 순서가 P, K)
    적용 방식 : 입력 → 매개변수 p, k, output → 반환값
    참고      : K부터 증가하며 찾으므로 K ≤ P인 입력을 전제
================================================================================
[입출력 예시]
    공식 예시
    p, k    | return
    --------|-------
    123, 100 | 24       (100부터 123까지 24번)

    자체 검증 케이스 (전부 손 계산)
    p, k     | return
    ---------|------------------
    0, 0     | 1               (000부터 시작해 첫 시도에 맞춤)
    5, 5     | 1               (시작 번호가 곧 비밀번호)
    1, 0     | 2               (0, 1)
    100, 99  | 2               (99, 100)
    500, 1   | 500             (1 ~ 500)
    999, 0   | 1000            (000 ~ 999 전부)
    999, 999 | 1
================================================================================
[풀이 전략]
    핵심: K부터 P까지의 정수 개수 = P - K + 1
        양 끝(K와 P)을 모두 포함하므로 P - K에 1을 더함
        예: 100 ~ 123 → 123 - 100 + 1 = 24

    풀이 구성:
        mine_one   : 뺄셈 공식 p - k + 1 (직접 작성한 풀이)
        mine_two   : for 반복으로 시도 횟수를 1씩 증가 (직접 작성한 풀이)
        mine_three : sum + 제너레이터 식으로 1을 더함 (직접 작성한 풀이)
        best       : mine_one과 동일 (반복 없이 상수 시간)
        sub        : len(range(k, p + 1)), mine_three의 개선
                     range는 길이를 계산식으로 알고 있어 값을 만들지 않고 len만 호출
                     (mine_three의 sum(1 for ...)이 하던 일을 한 번에 처리)

    손 추적 (공식 예시) p = 123, k = 100:
        123 - 100 + 1 = 24 ✓
================================================================================
[개선 포인트]
    solution_mine_one   : 개선 여지 없음 - 공식 한 줄, O(1)
    solution_mine_two   : 개선 여지 있음 - 개수를 세는 반복, O(p - k)
    solution_mine_three : 개선 여지 있음 - 값을 만들어 1씩 더함, len(range(...))로 간결해짐
    solution_best       : mine_one과 동일 로직 - Best
    solution_sub        : mine_three의 반복을 range 길이 조회로 대체 - O(1)
================================================================================
[복잡도 분석]
    m = p - k + 1 (구간 크기)

    Mine_one   - 시간: O(1) | 공간: O(1)
    Mine_two   - 시간: O(m) | 공간: O(1) - m번 반복
    Mine_three - 시간: O(m) | 공간: O(1) - 제너레이터가 m개 값을 생성
    Best       - 시간: O(1) | 공간: O(1) - mine_one과 동일
    Sub        - 시간: O(1) | 공간: O(1) - range 객체 생성과 len 조회
"""

import time


# ================================================================================
# Mine solution one - 뺄셈 공식
# ================================================================================
def solution_mine_one(p: int, k: int) -> int:
    """
    K부터 P까지의 정수 개수를 뺄셈으로 구하는 직접 작성한 풀이

    핵심:
        p - k + 1 : 양 끝(k와 p)을 모두 포함하므로 차이에 1을 더함
    """
    return p - k + 1


# ================================================================================
# Mine solution two - for 반복으로 개수 증가
# ================================================================================
def solution_mine_two(p: int, k: int) -> int:
    """
    k부터 p까지 반복하며 시도 횟수를 1씩 증가시키는 직접 작성한 풀이

    핵심:
        range(k, p + 1) : k부터 p까지 (끝값 미포함이라 p + 1)
        count += 1 : 시도할 때마다 횟수 증가
    """
    count = 0

    for i in range(k, p + 1):
        count += 1

    return count


# ================================================================================
# Mine solution three - sum + 제너레이터 식
# ================================================================================
def solution_mine_three(p: int, k: int) -> int:
    """
    mine_two를 sum과 제너레이터 식으로 바꿔 count 변수를 없앤 직접 작성한 풀이

    핵심:
        sum(1 for ...) : 값마다 1을 내보내 합산
    """
    return sum(1 for i in range(k, p + 1))


# ================================================================================
# Best solution - mine_one과 동일 로직
# ================================================================================
def solution_best(p: int, k: int) -> int:
    """
    mine_one과 동일한 로직의 최적 풀이

    선정 근거:
        반복 없이 상수 시간, 가장 간결
    """
    return p - k + 1


# ================================================================================
# Sub solution - len(range)
# ================================================================================
def solution_sub(p: int, k: int) -> int:
    """
    range의 길이를 조회해 개수를 구하는 풀이 (mine_three의 개선)

    핵심:
        len(range(k, p + 1)) : range는 시작, 끝, 간격으로 길이를 바로 계산
        값을 하나씩 만들지 않으므로 구간이 커져도 계산량이 같음
    """
    return len(range(k, p + 1))


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (p, k, 기댓값) - 전부 손 계산
        (123, 100, 24),                                     # 공식 예시
        (0, 0, 1),                                          # 최솟값 000
        (5, 5, 1),                                          # 시작 번호가 곧 비밀번호
        (1, 0, 2),                                          # 0, 1
        (100, 99, 2),                                       # 99, 100
        (500, 1, 500),                                      # 1 ~ 500
        (999, 0, 1000),                                     # 전체 구간
        (999, 999, 1),                                      # 최댓값에서 시작
    ]

    solutions = [
        ("Mine1 (공식)", solution_mine_one),
        ("Mine2 (for)", solution_mine_two),
        ("Mine3 (sum+gen)", solution_mine_three),
        ("Best (공식)", solution_best),
        ("Sub (len+range)", solution_sub),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
