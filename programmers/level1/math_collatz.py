"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 콜라츠 추측
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12943
    풀이일자   : 2026-06-16
===================================================================================
[문제 요약]
    주어진 수 num에 콜라츠 연산을 반복해 1이 될 때까지의 횟수를 반환
    500번 반복까지 1이 되지 않으면 -1 반환

    콜라츠 연산:
        짝수: n // 2
        홀수: n * 3 + 1

    제약 조건
        - 1 ≤ num < 8,000,000
        - 500번 상한 → 무한 루프 위험 없음
===================================================================================
[입출력 예시]
    num    | result
    -------|-------
    6      | 8      (6→3→10→5→16→8→4→2→1, 8번)
    16     | 4      (16→8→4→2→1, 4번)
    626331 | -1     (500번 반복해도 1이 되지 않음)
===================================================================================
[내 초기 풀이]
    solution_mine: while 루프 + 삼항 연산자 + 조기 탈출

    핵심 구조:
        while n != 1: 1이 될 때까지 반복
        n = n // 2 if n % 2 == 0 else n * 3 + 1: 삼항 연산자로 홀짝 분기
        answer += 1: 반복 횟수 누적
        answer > 500 → return -1: 500번 초과 시 조기 탈출

[개선 포인트]
    solution_mine:
        조기 탈출 조건 위치: if answer > 500이 연산 전
            흐름: answer=500 → 조건(500>500 False) → 연산 → answer=501
                    answer=501 → 조건(501>500 True) → return -1
            → 실제로 501번 연산 후 -1 반환
            문제 조건 "500번 반복까지" 엄밀 적용: answer >= 500으로 수정
            채점 통과는 되나 조건 정밀도 측면에서 개선 필요

        개선 방향:
            if answer >= 500: return -1  (연산 전 체크)
            또는 연산 후 answer 증가 시점에 조건 확인
===================================================================================
[콜라츠 추측 이론]
    1937년 Collatz가 제기한 미해결 수학 문제:
        "어떤 양의 정수에서 시작하든 콜라츠 연산을 반복하면 반드시 1에 도달한다"
        현재까지 반례가 발견되지 않았으나 수학적으로 증명되지 않음

    예시 (n=6):
        6 → 3 (짝수, 6//2)
        3 → 10 (홀수, 3×3+1)
        10 → 5 (짝수, 10//2)
        5 → 16 (홀수, 5×3+1)
        16 → 8 → 4 → 2 → 1 (짝수 연속)
        총 8번 ✓

    while vs 재귀:
        while: 반복 횟수 상한이 있고 상태(n, answer)를 명시적으로 관리
        재귀: 콜라츠 수열의 재귀적 성질(f(n) = 1 + f(next))을 직접 표현
                Python 기본 재귀 깊이 제한 1,000 → 500 상한 내 안전
===================================================================================
[복잡도 분석]
    콜라츠 수열의 종료 단계 수 = C(num) (수학적으로 미증명, 상한 500으로 제한)

    Mine - 시간: O(C(num)) | 공간: O(1)  - while 반복, 추가 자료구조 없음
    Best - 시간: O(C(num)) | 공간: O(1)  - Mine + 조건 정밀도 개선
    Sub  - 시간: O(C(num)) | 공간: O(C(num)) - 재귀 호출 스택

    500 상한으로 모든 풀이 실질적으로 O(1)에 수렴
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - while 루프 + 삼항 연산자 + 조기 탈출
# =================================================================================
def solution_mine(num: int) -> int:
    """
    while 루프로 콜라츠 연산을 반복하며 횟수를 세는 초기 풀이

    핵심:
        while n != 1: 1이 될 때까지 반복 (num=1이면 즉시 0 반환)
        삼항 연산자: 짝수/홀수 분기를 한 줄로 표현
        answer > 500: 500번 초과 시 조기 탈출

    개선 가능:
        조기 탈출 조건이 연산 전에 위치 → 실제로 501번 연산 후 -1 반환
        answer >= 500으로 수정하면 정확히 500번에서 종료
    """
    answer = 0
    n = num

    while n != 1:
        if answer > 500:            # 연산 전 체크: 실제로 501번 연산 후 -1
            return -1
        n = n // 2 if n % 2 == 0 else n * 3 + 1    # 홀짝 분기 삼항 연산자
        answer += 1

    return answer


# =================================================================================
# Best solution - 조건 정밀도 개선 (>= 500)
# =================================================================================
def solution_best(num: int) -> int:
    """
    조기 탈출 조건을 answer >= 500으로 수정한 최적 풀이

    Mine 대비 개선:
        answer > 500 → answer >= 500
        500번 반복해도 1이 되지 않으면 -1 반환하는 문제 조건과 정확히 일치

    흐름:
        answer=499 → 조건(499>=500 False) → 연산 → answer=500
        answer=500 → 조건(500>=500 True) → return -1  ← 정확히 500번 반복 후 종료

    num=1 처리:
        while n != 1 조건에서 즉시 탈출 → answer=0 반환 ✓
    """
    answer = 0
    n = num

    while n != 1:
        if answer >= 500:           # 500번 반복 시 즉시 -1 반환
            return -1
        n = n // 2 if n % 2 == 0 else n * 3 + 1
        answer += 1

    return answer


# =================================================================================
# Sub solution - 재귀 방식
# =================================================================================
def solution_sub(num: int, count: int = 0) -> int:
    """
    재귀로 콜라츠 수열의 재귀적 성질을 직접 표현한 서브 풀이

    Best 대비 특징:
        f(n, count) = f(next_n, count+1): 콜라츠 수열 재귀 구조를 직접 표현
        기저 조건: count >= 500 → -1, n == 1 → count
        Python 기본 재귀 깊이 제한 1,000 → 500 상한 내 안전

    재귀 호출 스택:
        최대 500번 재귀 → 공간 O(500) = O(1) 수렴
        while 대비 호출 스택 오버헤드 있음
    """
    if count >= 500:                # 500번 도달 → -1
        return -1
    if num == 1:                    # 1 도달 → 횟수 반환
        return count
    next_n = num // 2 if num % 2 == 0 else num * 3 + 1
    return solution_sub(next_n, count + 1)


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int]] = [
        # (num, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # 6: 6→3→10→5→16→8→4→2→1, 8번
        (6,      8),
        # 16: 16→8→4→2→1, 4번
        (16,     4),
        # 626331: 500번 반복해도 1 미도달 → -1
        (626331, -1),
        # 추가 케이스:
        # 1: num=1이면 0 반환 (while 즉시 탈출)
        (1,      0),
        # 2: 2→1, 1번
        (2,      1),
        # 3: 3→10→5→16→8→4→2→1, 7번
        (3,      7),
    ]

    solutions = [
        ("Mine (while >500) ", solution_mine),
        ("Best (while >=500)", solution_best),
        ("Sub  (재귀)       ", solution_sub),
    ]

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (num, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(num)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
