"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 숫자 문자열과 영단어
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/81301
    풀이일자   : 2026-05-28
================================================================================
[문제 요약]
    숫자의 일부 자릿수가 영단어로 바뀐 문자열 s를 원래 정수로 복원하여 반환
    예: "one4seveneight" -> 1478

    제약 조건
        - s 길이: 1 이상 50 이하
        - "zero"로 시작하는 경우 없음
        - 반환값: 1 이상 2,000,000,000 이하
================================================================================
[입출력 예시]
    s                    | result
    ---------------------|-------
    "one4seveneight"     | 1478
    "23four5six7"        | 234567
    "2three45sixseven"   | 234567
    "123"                | 123
================================================================================
[내 초기 풀이]
    영단어-숫자 쌍 table을 순회하며 replace() 반복 치환 후 int() 변환

    자료구조 고민:
        딕셔너리 vs 리스트 내 튜플
        -> 키-값 조회 없이 순서대로 순회만 하므로 둘 다 유의미한 차이 없음
        -> 리스트 튜플 선택 (순회 목적에 적합)

[검토 후 판단한 다른 방식들]
    1. 정규표현식 re.sub + lambda
        - re.sub(pattern, lambda m: table[m.group()], s) 형태
        - 단일 순회로 모든 영단어를 한 번에 치환
        - N=50에서 replace 반복 대비 순회 횟수 차이 무의미
        - lambda 문법으로 가독성 낮아짐 -> Sub로 채택

    2. functools.reduce
        - reduce(lambda s, kv: s.replace(*kv), table, s)
        - for 루프와 완전히 동일한 동작
        - 가독성만 낮아지고 실질적 이득 없음 -> 채택 안함

[개선 포인트]
    Mine: answer = s 별도 변수 -> s 직접 갱신으로 변수 하나 제거
================================================================================
[replace() 반복이 비효율적인가]
    N = len(s) <= 50, K = 영단어 종류 수 = 10

    replace() 1회: O(N) 순회
    replace() 10회: O(KxN) = O(10x50) = O(500)

    N <= 50 고정 -> 사실상 O(1)
    정규표현식 단일 순회(O(N)=O(50))와 500 vs 50 연산 차이
    -> 체감 불가, 실질적 비효율 없음

[복잡도 분석에서 변수 구분의 필요성]
    이중 루프를 보면 O(N²)으로 착각하기 쉬움
    반드시 각 루프의 반복 횟수를 결정하는 변수가 같은지 다른지 확인해야 함

    이 문제 분석:
        외부 루프: K = 10 (영단어 종류 수, 입력과 무관한 상수)
        내부 replace: N = len(s) (입력에 비례하는 변수)
        -> K x N = 10 x N -> O(N) ← O(N²)이 아님

    O(N²)이 되는 조건:
        두 루프의 반복 횟수가 모두 같은 N에 비례할 때
        예) for i in range(N): if target in list  → O(N) × O(N) = O(N²)

    체크리스트:
        1. 각 루프의 반복 횟수를 결정하는 변수가 무엇인가?
        2. 입력 크기 N과 같은 변수인가, 다른 변수(상수 K 등)인가?
        3. 상수라면 Big-O에서 제거 -> 실질 복잡도는 내부 루프 기준
================================================================================
[정규표현식 테이블 기반 치환 원리]
    re.sub(pattern, repl, string)에서 repl에 함수를 넣을 수 있음
    패턴 매칭 시마다 함수가 호출되어 치환값 결정

    pattern = "zero|one|two|...|none"   (모든 영단어를 | 로 연결)
    lambda m: table[m.group()]          (매칭된 문자열 -> 딕셔너리 조회)

    "one4seveneight" 처리 과정:
    "one"  매칭 → table["one"]="1"  → "14seveneight"
    "seven"매칭 → table["seven"]="7"→ "147eight"
    "eight"매칭 → table["eight"]="8"→ "1478"
================================================================================
[복잡도 분석]
    N = len(s) (최대 50), K = 영단어 종류 수 = 10

    Mine - 시간: O(K×N) | 공간: O(N) — replace 10회 반복
    Best - 시간: O(K×N) | 공간: O(N) — Mine과 동일, answer 변수 제거
    Sub  - 시간: O(N)   | 공간: O(N) — 단일 순회, 패턴 컴파일 비용 있음

    N ≤ 50 고정 → 모든 풀이 사실상 O(1)
    Sub가 이론상 순회 횟수 적으나 이 문제에서 차이 없음
================================================================================
"""

import re
import time
from typing import List, Tuple


# ==============================================================================
# Mine solution — replace 반복 + answer 변수
# ==============================================================================
def solution_mine(s: str) -> int:
    """
    영단어-숫자 쌍 table을 순회하며 replace()로 순차 치환하는 초기 풀이

    개선 전 상태:
        - answer = s: 별도 변수 불필요, s 직접 갱신으로 제거 가능
        - 로직 자체는 정확하고 직관적
    """
    answer = s

    table = [
        ("zero", "0"), ("one", "1"), ("two", "2"), ("three", "3"), ("four", "4"),
        ("five", "5"), ("six", "6"), ("seven", "7"), ("eight", "8"), ("nine", "9")
    ]

    for word, num in table:
        answer = answer.replace(word, num)  # 영단어 → 숫자 문자 치환

    return int(answer)


# ==============================================================================
# Best solution — replace 반복 + s 직접 갱신
# ==============================================================================
def solution_best(s: str) -> int:
    """
    answer 변수 없이 s를 직접 갱신하는 개선 풀이

    Mine 대비 개선:
        - answer = s 초기화 제거 → s 직접 갱신
        - 변수 하나 감소, 의도 더 명확

    이 문제에서 Best인 이유:
        N ≤ 50이라 replace 반복이 전혀 비효율적이지 않음
        정규표현식 대비 가독성 우위
    """
    table = [
        ("zero", "0"), ("one", "1"), ("two", "2"), ("three", "3"), ("four", "4"),
        ("five", "5"), ("six", "6"), ("seven", "7"), ("eight", "8"), ("nine", "9")
    ]

    for word, num in table:
        s = s.replace(word, num)  # s 직접 갱신

    return int(s)


# ==============================================================================
# Sub solution — 정규표현식 + lambda
# ==============================================================================
def solution_sub(s: str) -> int:
    """
    정규표현식으로 모든 영단어를 단일 순회로 치환하는 풀이

    핵심 구조:
        pattern = "zero|one|...|nine"  모든 영단어를 | 로 연결
        lambda m: table[m.group()]     매칭된 문자열을 딕셔너리로 조회

    Best 대비 특징:
        - 단일 순회 O(N) vs replace 반복 O(K×N)
        - N ≤ 50이라 실질적 차이 없음
        - lambda + m.group() 문법으로 가독성 낮음
        - 딕셔너리 사용: 매칭 → 조회 구조에 적합
    """
    table = {
        "zero": "0", "one": "1", "two": "2", "three": "3", "four": "4",
        "five": "5", "six": "6", "seven": "7", "eight": "8", "nine": "9"
    }

    # 모든 영단어를 | 로 연결한 패턴 생성
    pattern = "|".join(table.keys())

    # 패턴 매칭 시마다 lambda로 딕셔너리 조회 후 치환
    return int(re.sub(pattern, lambda m: table[m.group()], s))


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[str, int]] = [
        # (s, 기댓값)
        ("one4seveneight", 1478),  # 기본 예시 1
        ("23four5six7", 234567),  # 기본 예시 2
        ("2three45sixseven", 234567),  # 기본 예시 3
        ("123", 123),  # 영단어 없음
        ("onetwothree", 123),  # 전부 영단어
        ("nine", 9),  # 단일 영단어
        ("fivezerotwo", 502),  # zero 포함
    ]

    solutions = [
        ("Mine (answer변수)", solution_mine),
        ("Best (s직접갱신)", solution_best),
        ("Sub  (정규표현식)", solution_sub),
    ]

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (s, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(s)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
