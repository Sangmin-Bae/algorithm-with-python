"""
================================================================================
[문제 정보]
    사이트     : SWEA (SW Expert Academy)
    레벨       : D1
    문제명     : 1938. 아주 간단한 계산기
    유형       : Math (사칙연산)
    링크       : https://swexpertacademy.com/main/code/problem/problemDetail.do?contestProbId=AV5PjsYKAMIDFAUq&categoryId=AV5PjsYKAMIDFAUq&categoryType=CODE&problemTitle=&orderBy=PASS_RATE&selectCodeLang=ALL&select-1=&pageSize=10&pageIndex=3
    풀이일자   : 2026-10-21
================================================================================
[문제 요약]
    두 자연수 a, b에 대해 + , - , * , / 순서로 사칙연산한 결과를 출력
    나누기는 소수점 이하를 버림

    입력 방식 : 자연수 a, b (1 ≤ a, b ≤ 9), 입력된 순서가 a, b
    적용 방식 : 입력 → 매개변수 a, b
                output(네 줄) → 네 결과를 순서대로 담은 리스트 [합, 차, 곱, 몫]을 반환
    참고      : a가 b보다 작을 수 있어 차가 음수가 될 수 있음 (a - b 그대로 출력)
================================================================================
[입출력 예시]
    공식 예시
    a, b | return
    -----|---------------
    8, 3 | [11, 5, 24, 2]

    자체 검증 케이스 (전부 손 계산)
    a, b | return
    -----|---------------
    1, 1 | [2, 0, 1, 1]
    9, 9 | [18, 0, 81, 1]
    1, 9 | [10, -8, 9, 0]     (a < b: 차는 음수, 몫은 0)
    9, 1 | [10, 8, 9, 9]
    5, 2 | [7, 3, 10, 2]      (5 // 2 = 2, 소수점 이하 버림)
    2, 5 | [7, -3, 10, 0]     (2 // 5 = 0)
================================================================================
[풀이 전략]
    핵심: 사칙연산 네 개를 순서대로 계산해 리스트에 담기
        합 a + b, 차 a - b, 곱 a * b, 몫 a // b
        소수점 이하를 버리는 나눗셈은 몫 연산자 //

    // 와 int(a / b):
        a, b가 자연수이면 두 결과가 같음
        a // b : 몫을 내림 (음수에서는 -7 // 2 == -4)
        int(a / b) : 소수점 이하를 버림, 0 방향 (int(-7 / 2) == -3)
        이 문제는 a, b가 자연수라 차이 없음

    풀이 구성:
        mine_one : 연산자 네 개를 리스트로 묶어 반환 (직접 작성한 풀이)
        best     : mine_one과 동일 (연산 4개를 직접 나열, 더 간결한 변형이 없음)
        sub      : operator 모듈 함수(add, sub, mul, floordiv)를 순서대로 적용
                   연산이 늘어나도 목록만 바꾸면 되는 확장형, 이 문제에서는 코드가 더 길고 약간 느림

    손 추적 (공식 예시) a = 8, b = 3:
        8 + 3 = 11
        8 - 3 = 5
        8 * 3 = 24
        8 // 3 = 2 (8 = 3 * 2 + 2)
        → [11, 5, 24, 2] ✓
================================================================================
[개선 포인트]
    solution_mine_one : 개선 여지 없음 - 연산을 그대로 나열
    solution_best     : mine_one과 동일 로직 - Best
    solution_sub      : 연산 함수 목록을 순회 - 연산 종류가 많아질 때 유리
================================================================================
[복잡도 분석]
    Mine_one - 시간: O(1) | 공간: O(1) - 연산 4번, 결과 4개
    Best     - 시간: O(1) | 공간: O(1) - mine_one과 동일
    Sub      - 시간: O(1) | 공간: O(1) - 연산 4번 + 함수 호출 4번
"""

import time
from operator import add, floordiv, mul, sub


# ================================================================================
# Mine solution one - 사칙연산 나열
# ================================================================================
def solution_mine_one(a: int, b: int) -> list[int]:
    """
    합, 차, 곱, 몫을 순서대로 리스트에 담아 반환하는 직접 작성한 풀이

    핵심:
        a // b : 소수점 이하를 버리는 나눗셈 (자연수에서 int(a / b)와 동일)
        입력된 순서대로 a, b를 사용 (a가 b보다 작아도 a - b 그대로 계산)
    """
    return [a + b, a - b, a * b, a // b]


# ================================================================================
# Best solution - mine_one과 동일 로직
# ================================================================================
def solution_best(a: int, b: int) -> list[int]:
    """
    mine_one과 동일한 로직의 최적 풀이

    선정 근거:
        연산 네 개를 직접 나열해 가장 간결, 더 나은 변형이 없음
    """
    return [a + b, a - b, a * b, a // b]


# ================================================================================
# Sub solution - operator 모듈 함수 순회
# ================================================================================
def solution_sub(a: int, b: int) -> list[int]:
    """
    연산 함수를 순서대로 적용하는 풀이

    핵심:
        (add, sub, mul, floordiv) : 연산자와 같은 기능의 함수
        연산 종류가 많아질 때 목록만 바꾸면 되는 확장형
    """
    return [op(a, b) for op in (add, sub, mul, floordiv)]


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (a, b, 기댓값) - 전부 손 계산
        (8, 3, [11, 5, 24, 2]),                             # 공식 예시
        (1, 1, [2, 0, 1, 1]),                               # 최솟값
        (9, 9, [18, 0, 81, 1]),                             # 최댓값, 같은 수
        (1, 9, [10, -8, 9, 0]),                             # a < b: 차는 음수, 몫은 0
        (9, 1, [10, 8, 9, 9]),                              # a > b
        (5, 2, [7, 3, 10, 2]),                              # 몫의 소수점 이하 버림
        (2, 5, [7, -3, 10, 0]),                             # a < b, 몫 0
    ]

    solutions = [
        ("Mine (나열)", solution_mine_one),
        ("Best (나열)", solution_best),
        ("Sub (operator)", solution_sub),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
