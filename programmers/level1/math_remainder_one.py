"""
===================================================================================
[문제 정보]
    사이트   : Programmers
    레벨     : Level 1
    문제명   : 나머지가 1이 되는 수 찾기
    유형     : Math
    링크     : https://school.programmers.co.kr/learn/courses/30/lessons/87389
    풀이일자 : 2025-05-18
===================================================================================
[문제 요약]
    자연수 n에 대해 n % x == 1을 만족하는 x 중 최솟값을 반환

    제약 조건
        - 3 <= n <= 1,000,000
        - 항상 정답이 존재함 (빈 결과 없음)
===================================================================================
[입출력 예시]
    n   | result
    ----|--------
    10  | 3         (10%3=1, 10%9=1 -> min=3)
    12  | 11        (12%11=1 -> 11)
===================================================================================
[내 초기 풀이]
    solution_one    : n%x==1 직접 탐색, divisors 리스트 + min()
    solution_two    : (n-1)%x==0 수학적 변환, divisors[1]로 두 번째 값 반환
    solution_three  : solution_two + 리스트 제거 + range(2, n) 조기 탈출

    발상 전환:
        1단계(one)    : 조건을 코드로 직역
        2단계(two)    : n%x==1 <==> (n-1)%x==0 수학적 동치 변환
        3단계(three)  : 리스트 불필요, range(2, n) + 첫 값이 곧 최솟값

[개선 포인트]
    solution_one    : range(1, n+1) -> range(2, n)으로 범위 축소 가능
                        i=1(n%1=0), i=n(n%n=0)은 조건 불만족 확정
    solution_two    : divisors[1] 반환 이규가 코드만으로 불명확 (주석 필요)
    solution_three  : Best로 발전:
                        조기 탈출은 n-1이 소수일 때 O(N) 최악 발생
                        √N 탐색 + 조기 탈출 결합으로 O(√N) 보장
===================================================================================
[수학적 동치 증명]
    n % x == 1
    -> n = x * q + 1    (q는 몫)
    -> n - 1 = x * q
    -> (n-1) % x == 0

    ∴ "n%x==1을 만족하는 x 찾기" = "n-1의 약수 중 1 제외 최솟값 찾기"
===================================================================================
[약수 대칭성]
    x가 n-1의 약수이면 -> (n-1)//x 도 반드시 약수
    약수 쌍은 √(n-1)을 기준으로 대칭
    -> 1 ~ √(n-1) 범위만 탐색해도 모든 약수 발견 가능
    -> O(N) -> O(√N) 으로 개선

    주의: int(n**0.5) 대신 math.isqrt(n) 사용 권장
            -> 부동소수점 오차 없는 정수 제곱근
===================================================================================
[복잡도 분석]
    N = n (최대 1,000,000)

    Mine_one    - 시간: O(N)  | 공간: O(N) - divisors 리스트 + min() 추가 순회
    Mine_two    - 시간: O(N)  | 공간: O(N) - divisors 리스트
    Mine_three  - 시간: O(N)  | 공간: O(1) - 조기 탈출 (n-1 소수 시 최악 O(N))
    Best        - 시간: O(√N) | 공간: O(1) - √N 탐색 + 조기 탈출, 항상 보장
    Sub         - 시간: O(N)  | 공간: O(1) - 조기 탈출 (평균 빠르나 최악 O(N))

    실측 비교 (n=1,000,004, n-1=1,000,003 소수 — 최악 케이스):
    Mine_one/two  : ~55ms   (전체 순회)
    Mine_three/Sub: ~58ms   (소수라 끝까지 순회)
    Best          :  0.05ms (√N=1000번만 순회)
===================================================================================
"""

import math
import time
from typing import List, Tuple


# =================================================================================
# Mine solution one - n%x==1 직접 탐색 + divisors + min()
# =================================================================================
def solution_mine_one(n: int) -> int:
    """
    문제 조건을 직접 코드로 표현한 초기 풀이

    개서 전 상태:
        - range(1, n+1): i=1은 n%1=0, i=n은 n%n으로 조건 불만족 확정
            -> range(2, n)으로 줄일 수 있음
        - divisors 리스트 + min(): 전체 순회 후 min() 한 번 더 순회
            -> O(N) 공간, 조기 탈출 방식으로 개선 가능
    """
    divisors = []

    for i in range(1, n + 1):
        if n % i == 1:
            divisors.append(i)

    return min(divisors)


# =================================================================================
# Mine solution two - (n-1)%x==0 수학적 변환 + divisors[1]
# =================================================================================
def solution_mine_two(n: int) -> int:
    """
    n%x==1을 (n-1)%x==0으로 변환해 n-1의 약수를 찾는 풀이

    핵심 발상:
        n%x==1 <==> (n-1)%x==0  (수학적 동치)
        -> 문제를 "n-1의 약수 중 1 제외 최솟값 찾기"로 변환

    개선 전 상태:
        - divisors[1]: 1이 항상 divisors[0]이므로 두 번째 값 반환
            코드만 봐서는 왜 [1]인지 불명확 -> 주석 필요
        - 리스트 전체 수집 후 인덱스 접근 -> 조기 탈출로 개선 가능
    """
    divisors = []

    for i in range(1, n):
        if (n - 1) % i == 0:
            divisors.append(i)

    # divisors[0]은 항상 1 (모든 수는 1로 나누어 떨어짐) -> 제외
    # divisors[1]은 1을 제외한 n0-1의 최소 약수 = 정답
    return divisors[1]


# =================================================================================
# Mine solution three - 리스트 제거 + range(2, n) 조기 탈출
# =================================================================================
def solution_mine_three(n: int) -> int:
    """
    divisors 리스트 없이 조건 만족 즉시 반환하는 풀이

    핵심 발상:
        - range(2, n): 1은 항상 조건 만족해 제외, n은 조건 불만족 확정
        - 오름차순 순회이므로 첫 번째 만족값이 곧 최소값
        - 찾는 즉시 return으로 불필요한 순회 제거

    한계:
        - n-1이 소수인 경우 최소 약수 = n-1 자체
        -> range 거의 끝까지 순회 -> 최악 O(N)
    """
    for i in range(2, n):
        if (n - 1) % i == 0:
            return i    # 오름차순 첫 번째 약수 = 최솟값, 즉시 반환

    return n - 1        # 문제 제약상 도달 불가 (항상 정답 존재 보장), 타입 일관성 유지


# =================================================================================
# Best solution - √N 탐색 + 조기 탈출 결합
# =================================================================================
def solution_best(n: int) -> int:
    """
    약수 대칭성을 활용해 √(n-1)까지만 탐색하는 최적 풀이

    핵심 아이디어:
        - n%x==1 <==> (n-1)%x==0  (수학적 동치)
        - 약수는 √(n-1) 기준으로 쌍으로 존재
            -> 1 ~ √(n-1) 범위에서 찾은 작은 약수가 곧 최솟값
        -오름차순 순회이므로 첫 발견값이 최솟값 -> 즉시 return

    mine_three 대비 개선:
        - n-1이 소수여도 √(n-1)번만 순회
        - 어떤 입력에도 O(√N) 보장

    edge case: 약수 미발견 시 n-1 자체가 소수 -> n-1이 유일한 약수
        검증: n%(n-1) = n-(n-1) = 1 ✓ 항상 성립
    """
    m = n - 1

    for x in range(2, math.isqrt(m) + 1):
        if m % x == 0:  # x가 m의 약수 = n%x==1을 만족
            return x    # 오름차순 첫 번째 = 최솟값, 즉시 탈출

    return m            # 약수 없음 -> m이 소수 -> m 자체가 정답


# =================================================================================
# Sub solution - 원 조건 직접 적용 + 조기 탈출
# =================================================================================
def solution_sub(n: int) -> int:
    """
    수학적 변환 없이 원 조건 n%x==1을 직접 적용한 조기 탈출 풀이

    Best 대비 특징:
        - 조건식이 문제 그대로라 직관적
        - 수학적 변환 없이도 동일 결과
        - 단, n-1이 소수인 최악 케이스에서 O(N) 발생 가능

    mine_one 대비 개선:
        - range(2, n)으로 범위 최적화
        - 리스트 없이 조기 탈출 -> 공간 O(N) -> O(1)
    """
    for x in range(2, n):
        if n % x == 1:      # 문제 조건 직접 적용
            return x        # 오름차순 첫 번째 = 최솟값, 즉시 탈출

    return n - 1            # 문제 제약상 도달 불가 (항상 정답 존재 보장), 타입 일관성 유지


# ==============================================================================
# 다섯 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """다섯 풀이의 정확성과 성능을 동시에 검증한다."""

    test_cases: List[Tuple[int, int]] = [
        # (n, 기댓값)
        (10, 3),  # 10%3=1, 10%9=1 → min=3
        (12, 11),  # 12%11=1 → 11
        (3, 2),  # 최솟값 n=3: 3%2=1 → 2
        (4, 3),  # 4%3=1 → 3
        (1000000, 3),  # n-1=999999=3×... → 최소약수=3
        (7, 2),  # 7%2=1 → 2
        (13, 2),  # 13%2=1 → min=2
        (1000004, 1000003),  # n-1=1000003 소수 → 최악 케이스
    ]

    solutions = [
        ("Mine_one   (직접+리스트+min)", solution_mine_one),
        ("Mine_two   (변환+리스트+idx)", solution_mine_two),
        ("Mine_three (변환+조기탈출)", solution_mine_three),
        ("Best       (√N+조기탈출)", solution_best),
        ("Sub        (직접+조기탈출)", solution_sub),
    ]

    print("=" * 68)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 68)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 68)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
