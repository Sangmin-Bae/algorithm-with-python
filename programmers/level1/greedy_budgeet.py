"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 예산
    유형       : Greedy / Sort
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12982
    풀이일자   : 2025-05-24
================================================================================
[문제 요약]
    각 부서 신청 금액을 정확히 지원(부분 지원 불가)하되
    예산 내에서 최대한 많은 부서를 지원할 때 최대 부서 수 반환

    제약 조건
        - d 길이: 1 이상 100 이하
        - d 원소: 1 이상 100,000 이하
        - budget: 1 이상 10,000,000 이하
================================================================================
[입출력 예시]
    d           | budget | result
    ------------|--------|-------
    [1,3,2,5,4] | 9      | 3
    [2,2,3,3]   | 10     | 4
================================================================================
[Greedy 전략 - 왜 작은 금액부터 선택하는 게 최대 부서 수인가]
    직관:
        같은 예산으로 더 많은 부서를 지원하려면
        한 부서당 드는 비용이 작아야 함
        -> 비용이 작은 부서부터 선택하는 게 전체 부서 수를 최대화

    교환 논증(Exchange Argument) 증명:
        최적해 S가 있고 S에 큰 금액 x가 포함되어 있다고 가정
        선택되지 않은 금액 중 x보다 작은 y가 있다면:
            x를 y로 교체 -> 합계 감소, 부서 수 동일
            감소된 합계 -> 예산 여유 -> 추가 부서 선택 가능성 증가
        -> 큰 금액을 작은 금액으로 교체할수록 항상 유리하거나 동등
        -> 오름차순 정렬 후 순서대로 선택이 항상 최적

    ∴ 이 문제는 Greedy가 성립:
        "작은 금액부터 선택" = 매 단계 최선 = 전체 최선
================================================================================
[내 초기 풀이]
    solution_one: 오름차순 정렬 후 누적 합산, 총 예산 초과 시 탈출
    solution_two: 전체 합산에서 가장 큰 값을 pop하며 예산 이하로 줄이기

[개선 포인트]
    solution_one: total 변수 -> budget 직접 차감으로 변수 하나 제거
    solution_two: 루프 안에서 매번 sum(d) 호출 -> O(N²)
                    -> sum 1회 계산 후 pop 시 해당 값만 빼기 -> O(N)
                    -> d.pop()이 원본 수정 -> sorted()로 복사본 사용
================================================================================
[복잡도 분석]
    N = len(d) (최대 100)

    Mine_one - 시간: O(N log N) | 공간: O(N) — sorted() 새 리스트
    Mine_two - 시간: O(N²)      | 공간: O(1) — 루프마다 sum() 재호출
    Best     - 시간: O(N log N) | 공간: O(N) — sorted() 새 리스트
    Sub      - 시간: O(N log N) | 공간: O(N) — sorted() 새 리스트

    N ≤ 100이라 모든 풀이 즉시 실행
    Mine_two의 O(N²) 습관은 큰 입력에서 문제 발생 가능
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one - 오름차순 정렬 + 누적 합산
# ==============================================================================
def solution_mine_one(d: List[int], budget: int) -> int:
    """
    오름차순 정렬 후 순서대로 합산하며 예산 초과 시 탈출하는 초기 풀이

    개선 전 상태:
        - total 변수 별도 사용 -> budget 직접 차감으로 변수 하나 제거 가능
        - 로직 자체는 Greedy 전략에 부합
    """

    dept = 0
    total = 0

    for i in sorted(d):     # 오름차순 정렬: 작은 금액부터 선택
        total += i

        if total <= budget:
            dept += 1       # 예산 내 -> 지원 가능 부서 수 증가
        else:
            break           # 예산 초과 -> 탈출

    return dept


# ==============================================================================
# Mine solution two - 전체 합산 후 큰 값 제거
# ==============================================================================
def solution_mine_two(d: List[int], budget: int) -> int:
    """
    전체 합산에서 가장 큰 값을 제거하며 예산 이하로 줄이는 풀이

    개선 전 상태:
        - sum(d)를 루프 안에서 매번 호출 -> O(N²)
            (루프 N번 × sum() O(N) = O(N²))
        - d.pop()이 원본 배열 직접 수정 -> 함수 외부에서 d 재사용 시 버그 위험
        - default return 0은 구조적 안정성 목적 (도달 불가)
    """
    d.sort()

    for i in range(len(d)):
        s = sum(d)      # <- 루프마다 O(N) 재호출, O(N²) 원인

        if s > budget:
            d.pop()     # 가장 큰 값 제거 (원본 수정 주의)
        else:
            return len(d)

    return 0            # 구조적 안정성 목적, 실제 도달 불가


# ==============================================================================
# Best solution - Greedy (budget 직접 차감)
# ==============================================================================
def solution_best(d: List[int], budget: int) -> int:
    """
    오름차순 정렬 후 budget을 직접 차감하며 초과 시 즉시 탈출하는 최적 풀이

    Mine_one 대비 개선:
        - total 변수 제거 -> budget 직접 차감
        - if budget < 0으로 조건 단순화

    Greedy 전략:
        오름차순 정렬 -> 작은 금액부터 선택
        -> 예산 소모 최소화 -> 최대 부서 수 보장
        -> 교환 논증으로 최적성 증명
    """
    dept = 0

    for cost in sorted(d):      # 오름차순: 작은 금액부터 선택
        budget -= cost          # 예산에서 직접 차감
        if budget < 0:          # 초과 시 즉시 탈출
            break
        dept += 1

    return dept


# ==============================================================================
# Sub solution - 전체 합산 후 큰 값 제거 (Mine_two 개선)
# ==============================================================================
def solution_sub(d: List[int], budget: int) -> int:
    """
    전체 합산에서 가장 큰 값을 제거하며 예산 이하로 줄이는 개선 풀이

    Mine_two 대비 개선:
        - sorted()로 복사본 생성 -> 원본 d 보존
        - sum() 1회만 계산 후 pop 시 해당 값만 차감 ->  O(N²) → O(N log N)
        - 빈 배열 예외 처리 추가

    Best 대비 특징:
        - "큰 것을 빼는" 역방향 발상
        - 복잡도는 동일하나 직관성이 낮음
    """
    sorted_d = sorted(d)        # 원본 보존을 위해 복사본 생성
    total = sum(sorted_d)       # 합산 1회만 계산

    while total > budget:
        total -= sorted_d.pop()     # 가장 큰 값 제거 + total 갱신 (O(1))
        if not sorted_d:            # 모든 부서 제거 -> 지원 불가
            return 0

    return len(sorted_d)


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[int], int, int]] = [
        # (d, budget, 기댓값)
        ([1, 3, 2, 5, 4], 9, 3),  # 기본 예시 1
        ([2, 2, 3, 3], 10, 4),  # 기본 예시 2: 전부 지원 가능
        ([1], 1, 1),  # 단일 부서, 정확히 일치
        ([5], 4, 0),  # 단일 부서, 예산 부족
        ([1, 1, 1, 1, 1], 3, 3),  # 동일 금액 여러 부서
        ([100000] * 100, 9999999, 99),  # 최대 원소, 예산 부족 1개
        ([1] * 100, 100, 100),  # 전부 지원 가능
    ]

    solutions = [
        ("Mine_one (누적합산)", solution_mine_one),
        ("Mine_two (전체합-큰값제거)", solution_mine_two),
        ("Best     (budget직접차감)", solution_best),
        ("Sub      (개선된큰값제거)", solution_sub),
    ]

    print("=" * 68)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 68)

    for name, func in solutions:
        for idx, (d, budget, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(d[:], budget)  # 원본 보존을 위해 복사 전달
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 68)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
