"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 하샤드 수
    유형       : Math / String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12947
    풀이 일자  : 2026-05-14
===================================================================================
[문제 요약]
    양의 정수 x의 각 자릿수의 합으로 x가 나누어 떨어지면 하샤드 수.
    x 하샤두 수이면 True, 아니면 False를 반환

    제약 조건
        - x는 1 이상 10000 이하인 정수
===================================================================================
[입출력 예시]
    x       | return
    --------|--------
    10      | True      (1+0=1, 10%1=0)
    12      | True      (1+2=3, 12%3=0)
    11      | False     (1+1=2, 12%2=1)
    13      | False     (1+3=4, 13%4=1)
===================================================================================
[내 초기 풀이]
    - answer 변수로 True/False 상태를 관리
    - 리스트 컴프리헨션으로 자릿수 합산
    - 로직은 정확하나 파이썬답지 않은 표현 방식

[개선 포인트]
    - answer 변수 제거 -> x % digit_sum == 0 결과를 직접 반환
    - 리스트 컴프리헨션 [] -> 제너레이터 표현식으로 불필요한 리스트 객체 생성 제거
===================================================================================
[풀이 전략]
    Mine) answer 변수 + 리스트 컴프리헨션
        - 조건 분기로 answer를 False로 전환 후 반환
        - 시간 O(N) / 공간 O(N)

    Best) str 변환 + 제너레이터 표현식
        - str(x)로 자릿수 분리 후 sum()으로 합산
        - 불리언 표현식을 직접 반환 (중간 변수 불필요)
        - 시간 O(N) / 공간 O(N) - N: 자릿수 수

    Sub) 수학적 자릿수 추출 (% 10, // 10)
        - str() 없이 나머지 연산으로 자릿수를 하나씩 추출
        - 타 언어에서도 동일하게 적용 가능한 범용 패턴
        - 시간 O(N) / 공간 O(1)
===================================================================================
[복잡도 분석]
    N = x의 자릿수 수 (x <= 10000이므로 N <= 5, 사실상 상수)

    Mine    - 시간: O(N)  | 공간: O(N) - 리스트 객체 생성
    Best    - 시간: O(N)  | 공간: O(N) - str(x) 문자열 객체 생성
    Sub     - 시간: O(N)  | 공간: O(1) - 정수 변수 2개, 추가 자료구조 없음

    Comment
        - 실질적으로 세 풀이 모두 O(1)로 봐도 무방 (N <= 5 고정)
"""

import time
from typing import List, Tuple

# =================================================================================
# Mine solution - 내 초기 풀이
# =================================================================================
def solution_mine(x: int) -> bool:
    """
    answer 변수로 True/False 상태를 관리하는 초기 풀이

    개선 전 상태:
        - answer = True로 초기화 후 조건에서 False로 전환하는 패턴
        - 리스트 컴프리헨션으로 자릿수 변환 (불필요한 리스트 객체 생성)
        - 로직은 정확하나 파이썬 표현 방식으로 개선 여지 있음
    """
    answer = True
    value = sum([int(d) for d in str(x)])   # 리스트를 만든 후 sum에 전달
    if x % value != 0:
        answer = False
    return answer

# =================================================================================
# Best solution - str 변환 + 제너레이터 + 불리언 직접 반환
# =================================================================================
def solution_best(x: int) -> bool:
    """
    자릿수 합을 구해 x가 나누어 떨어지는지 바로 반환

    핵심 포인트:
        - 제너레이터 표현식: 불필요한 리스트 객체 생성 없이 sum()에 직접 전달
        - X % digit_sum == 0 의 결과가 bool이므로 변수 없이 바로 return
    """
    digit_sum = sum(int(d) for d in str(x))
    return x % digit_sum == 0


# =================================================================================
# Sub solution - 수학적 자릿수 추출 (% 10, //10)
# =================================================================================
def solution_sub(x: int) -> bool:
    """
    str() 없이 나머지 연산으로 자릿수를 하나씩 추출해 합산

    핵심 포인트:
        - tmp % 10: 현재 1의 자리 숫자 추출
        - tmp //= 10: 1의 자리 제거 후 다음 자리로 이동
        - 파이썬 외 타 언어에서도 동일하게 적용 가능한 범용 패턴
    """
    digit_sum = 0
    tmp = x

    while tmp > 0:
        digit_sum += tmp % 10
        tmp //= 10

    return x % digit_sum == 0


# =================================================================================
# 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, bool]] = [
        # (입력, 기댓값)
        (10, True),     # 1+0=1,    10%1=0
        (12, True),     # 1+2=3,    12%3=0
        (11, False),    # 1+1=2,    11%2=1
        (13, False),    # 1+3=4,    13%4=1
        (1, True),      # 1,        1%1=0   (최솟값)
        (10000, True),  # 1+0+0+0+0=1,  10000%1=0   (최댓값)
        (18, True),     # 1+8=9,    18%9=0  (문제 설명 예시)
        (19, False),    # 1+9=10,   19%10=9
    ]

    solutions = [
        ("Mine (answer 변수)", solution_mine),
        ("Best (str+generator)", solution_best),
        ("Sub (math % // )", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<28} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (x, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(x)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<28} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 64)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
