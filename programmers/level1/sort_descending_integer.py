"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 정수 내림차순으로 배치하기
    유형       : Sort / String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12933
    풀이일자   : 2025-05-15
===================================================================================
[문제 요약]
    정수 n의 각 자릿수를 내림차순으로 정렬한 새로운 정수를 반환

    제약 조건
        - n은 1 이상, 8,000,000,000 이하인 자연수
        - 파이썬 int는 임의 정밀도 -> 8 * 10^9 범위 문제 없음
        - 타 언어(Java, C++)에서는 long 타입 필요 (int 최대 약 2.1 * 10^9)
===================================================================================
[입출력 예시]
    n      | return
    -------|-------
    118372 | 873211     (1,1,8,3,7,2 -> 내림차순 -> 8,7,3,2,1,1)
===================================================================================
[내 초기 풀이]
    - sort() 메서드를 먼저 시도 -> 반환값이 None임을 확인
    - sorted() 내장 함수로 변경해 한 줄 체이닝 완성
    - [c for c in str(n)] 리스트 컴프리헨션 사용 (개선 여지 있음)

[개선 포인트]
    - [c for c in str(n)] -> str(n) 직접 전달
    - str 자체가 이터러블이므로 중간 리스트 객체 생성 불필요
===================================================================================
[풀이 전략]
    공통 파이프라인: 정수 -> 문자열 -> 정렬 -> 결합 -> 정수

    Mine) sroted() + 리스트 컴프리헨션
        - [c for c in str(n)]으로 문자 리스트를 만든 후 sorted()에 전달
        - 시간 O(N log N) / 공간 O(N)

    Best) sorted() 직접 체이닝
        - str(n) 자체를 sorted()에 전달, 중간 리스트 생성 없음
        - 시간 O(N log N) / 공간 O(N)

    Sub) sort() + 명시적 변수
        - list로 변환 후 in-place sort(), 단계별로 명확
        - 시간 O(N log M) / 공간 O(N)
===================================================================================
[복잡도 분석]
    N = n의 자릿수 개수 (n <= 8,000,000,000이므로 N <= 10, 사실상 정수)

    Mine    - 시간: O(N log N) | 공간: O(N) - 리스트 컴프리헨션 + sorted 결과
    Best    - 시간: O(N log N) | 공간: O(N) - sorted 결과 리스트
    Sub     - 시간: O(N log N) | 공간: O(N) - list 변환 + in-place sort

    정렬(O(N log N))이 지배함 - N <= 10 고정이라 실질적으로 O(1)에 수렴
===================================================================================
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - 내 초기 풀이
# =================================================================================
def solution_mine(n: int) -> int:
    """
    리스트 컴프리헨션으로 문자 리스트를 만든 후 sorted()로 정렬하는 초기 풀이

    개선 전 상태:
        - sort() 시도 -> None 반환 확인 후 sorted()로 전환
        - [c for c in str(n)]: str(n) 자체가 이터러블이므로 불필요한 리스트 생성
    """
    return int(''.join(sorted([c for c in str(n)], reverse=True)))


# =================================================================================
# Best solution - sorted() 직접 체이닝
# =================================================================================
def solution_best(n: int) -> int:
    """
    str(n)을 sorted()에 직접 전달해 중간 리스트 생성을 제거한 풀이

    Mine 대비 개선 포인트:
        - str(n) 자체가 이터러블 -> [c for c in str(n)] 불필요
        - 파이프라인: int -> str -> sorted -> join -> int
    """
    # str(n) 자체가 이터러블이므로 바로 sorted()에 전달 가능
    return int(''.join(sorted(str(n), reverse=True)))


# =================================================================================
# Sub solution - sort() + 명시적 변수
# =================================================================================
def solution_sub(n: int) -> int:
    """
    list로 변환 후 in-place sort()를 사용하는 단계별 명시적 풀이

    핵심 포인트:
        - sort()는 리스트 인스턴스 메서드, 반환값 None, 원본 in-place 수정
        - list(str(n)) 변환이 필요한 이유: sort()는 리스트에만 존재하는 메서드
        - 각 단계가 분리되어 있어 디버깅 시 중간값 확인 용이
    """
    digits = list(str(n))       # 문자열 -> 리스트 변환 (sort() 사용을 위해 필요)
    digits.sort(reverse=True)   # in-place 정렬 - 반환값 None, 원본 직접 수정
    return int(''.join(digits))


# =================================================================================
# 풀이 결과 비교 검증 | 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int]] = [
        # (입력, 기댓값)
        (118372,      873211),      # 기본 예시
        (1,           1),           # 최솟값, 단일 자릿수
        (8000000000,  8000000000),  # 최댓값 (자릿수: 8,0,0,0,0,0,0,0,0,0 -> 8000000000_
        (987654321,   987654321),   # 이미 내림차순
        (123456789,   987654321),   # 오름차순 입력
        (1000,        1000),        # 0이 포함된 경우 (1,0,0,0 -> 1000)
        (10,          10),          # 0이 포함된 두 자리 (1,0 -> 10)
    ]

    solutions = [
        ("Mine (list comprehension)", solution_mine),
        ("Best (sorted direct)", solution_best),
        ("Sub (sort in-place)", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed*1000:8.4f}ms")
        print("-" * 64)

# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
