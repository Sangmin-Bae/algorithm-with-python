"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 두 정수 사이의 합
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12912
    풀이일자   : 2026-06-05
================================================================================
[문제 요약]
    a와 b 사이에 속한 모든 정수의 합 반환
    a, b 대소관계 미정. a == b이면 그 수 반환

    제약 조건
        - a, b: -10,000,000 이상 10,000,000 이하
        - a, b 대소관계 미정
================================================================================
[입출력 예시]
    a | b | return
    --|---|-------
    3 | 5 | 12    (3+4+5=12)
    3 | 3 | 3     (a==b: 그 수 반환)
    5 | 3 | 12    (a>b도 처리)
================================================================================
[내 초기 풀이]
    solution_one  : a>b이면 스왑 후 sum(range(a, b+1))
    solution_two  : min/max로 정렬 후 sum(range())
    solution_three: 등차수열 합 공식 적용 → O(1)

    발상 진화:
        1단계(one)  : 직접 스왑으로 a<=b 보장
        2단계(two)  : min/max 함수로 더 간결하게
        3단계(three): 등차수열 합 공식으로 순회 제거

[등차수열 합 공식 유도]
    일반 공식: S = n(2a + (n-1)d) / 2  (a=첫항, d=공차, n=항수)
    공차 d=1 대입: S = n(2a + n - 1) / 2
    a + (a + n - 1) = a + l  (l=마지막항)으로 정리:
        S = n(a + l) / 2

    이 문제 적용:
        n = abs(a - b) + 1  (항의 개수)
        a + l = a + b       (첫항 + 마지막항, 순서 무관)
        S = (abs(a-b)+1) * (a+b) // 2

[연산자 우선순위 확인]
    (abs(a-b)+1) * (a+b) // 2
    → 파이썬은 *, // 왼쪽부터 계산
    → ((abs(a-b)+1) * (a+b)) // 2  ← 실제 계산 순서

[연산자 우선순위 확인]
    (abs(a-b)+1) * (a+b) // 2
    → 파이썬은 *, // 왼쪽부터 계산
    → ((abs(a-b)+1) * (a+b)) // 2  ← 실제 계산 순서

    n * (a+b)가 항상 짝수인 증명 (홀짝성 분석):
        a, b 홀짝성이 같을 때:
            a+b = 짝수+짝수 or 홀수+홀수 = 짝수
            → a+b가 짝수 → n*(a+b)는 짝수

        a, b 홀짝성이 다를 때:
            b-a = 홀수-짝수 or 짝수-홀수 = 홀수
            n = (b-a) + 1 = 홀수 + 1 = 짝수
            → n이 짝수 → n*(a+b)는 짝수

    두 경우 모두 n*(a+b)는 짝수
    ∴ // 2 시 소수점 손실 없음
================================================================================
[복잡도 분석]
    N = abs(a-b)+1 (최대 2천만)

    Mine_one/two - 시간: O(N) | 공간: O(1) — range 이터러블 순회
    Best         - 시간: O(1) | 공간: O(1) — 산술 연산만
    Sub          - 시간: O(N) | 공간: O(1) — range 이터러블 순회

    a=-10,000,000, b=10,000,000이면:
        Mine: 2천만 번 덧셈
        Best: 연산 3번
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one — 스왑 후 sum(range())
# ==============================================================================
def solution_mine_one(a: int, b: int) -> int:
    """
    a > b이면 스왑해서 a <= b를 보장한 뒤 sum(range())로 합산하는 초기 풀이

    핵심:
        range() 자체가 이터러블 → sum()에 직접 전달 가능
        리스트 컴프리헨션 불필요
        a == b이면 range(a, a+1) = [a] → sum = a  ✓

    개선 가능:
        스왑 로직 → min/max 함수로 더 간결하게
    """
    if a > b:
        a, b = b, a
    return sum(range(a, b + 1))


# ==============================================================================
# Mine solution two — min/max + sum(range())
# ==============================================================================
def solution_mine_two(a: int, b: int) -> int:
    """
    min/max 함수로 정렬 처리하는 개선 풀이

    Mine_one 대비 개선:
        스왑 로직 제거
        min/max 각각 O(1), 중첩 아니므로 O(1)+O(1)
        더 파이써닉하고 간결

    여전히 O(N) 순회 발생
    """
    return sum(range(min(a, b), max(a, b) + 1))


# ==============================================================================
# Best solution — 등차수열 합 공식 O(1)
# ==============================================================================
def solution_best(a: int, b: int) -> int:
    """
    등차수열 합 공식으로 순회 없이 O(1)로 합산하는 최적 풀이

    공식 유도:
        S = n(a + l) / 2  (n=항수, a=첫항, l=마지막항)
        n = abs(a-b) + 1
        a + l = a + b     (순서 무관, 첫항+마지막항)

    연산 순서:
        n * (a+b) // 2
        → ((n * (a+b)) // 2)  (*, // 왼쪽부터)
        → n*(a+b)는 항상 짝수 → // 2 시 손실 없음
    """
    # 등차수열 합: S = n × (첫항 + 마지막항) / 2
    # n = 항의 개수, 첫항 + 마지막항 = a + b (순서 무관)
    return (abs(a - b) + 1) * (a + b) // 2


# ==============================================================================
# Sub solution — min/max + sum(range())
# ==============================================================================
def solution_sub(a: int, b: int) -> int:
    """
    min/max + sum(range()) 방식

    Best 대비 특징:
        O(N) 순회 발생
        의도가 직관적으로 드러남
        a, b 범위가 작을 때 가독성 우위
    """
    return sum(range(min(a, b), max(a, b) + 1))


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int, int]] = [
        # (a, b, 기댓값)
        # 손 추적:
        # (3,5): 3+4+5=12
        (3, 5, 12),
        # (3,3): a==b → 3
        (3, 3, 3),
        # (5,3): a>b → 3+4+5=12
        (5, 3, 12),
        # (-3,3): -3+-2+-1+0+1+2+3=0
        (-3, 3, 0),
        # (-5,-3): -5+-4+-3=-12
        (-5, -3, -12),
        # (1,2): 1+2=3
        (1, 2, 3),
        # (0,0): a==b==0 → 0
        (0, 0, 0),
    ]

    solutions = [
        ("Mine_one (스왑+range)", solution_mine_one),
        ("Mine_two (min/max+range)", solution_mine_two),
        ("Best     (등차수열공식)", solution_best),
        ("Sub      (min/max+range)", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (a, b, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(a, b)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
