import time


# ================================================================================
# Mine solution one - 문자열 변환 + sum
# ================================================================================
def solution_mine_one(N: int) -> int:
    """
    정수를 문자열로 바꿔 각 자릿수를 int로 되돌려 합산하는 직접 작성한 풀이

    핵심:
        str(N)을 순회하면 각 자릿수 문자를 얻음
        int(x)로 되돌려 sum + 제너레이터로 합산
    """
    return sum(int(x) for x in str(N))


# ================================================================================
# Mine solution two - divmod 반복
# ================================================================================
def solution_mine_two(N: int) -> int:
    """
    10으로 나누며 나머지를 누적하는 직접 작성한 풀이

    핵심:
        divmod(N, 10) → (몫, 나머지): 나머지가 1의 자리
        몫을 N에 다시 대입하며 N > 0 동안 반복
        1의 자리부터 추출되므로 순서가 필요하면 reversed 필요
    """
    total = 0

    while N > 0:
        N, r = divmod(N, 10)
        total += r

    return total


# ================================================================================
# Best solution (algo) - % 와 // 반복
# ================================================================================
def solution_best_algo(N: int) -> int:
    """
    알고리즘 원리 우선 최적 풀이: 나머지와 몫을 따로 구하는 나눗셈 풀이

    핵심:
        total += N % 10 : 1의 자리 누적
        N //= 10        : 1의 자리 제거
        자릿수가 적은 정수(64비트 범위)에서 divmod보다 빠름
        큰 정수(약 200자리 이상)에서는 연산이 두 번이라 divmod보다 느림
    """
    total = 0

    while N > 0:
        total += N % 10
        N //= 10

    return total


# ================================================================================
# Best solution (practical) - 바이트열 합산
# ================================================================================
def solution_best_practical(N: int) -> int:
    """
    성능 우선 최적 풀이: 문자열을 바이트열로 바꿔 ASCII 값으로 합산

    핵심:
        '0'~'9'의 ASCII 값은 48 + 자릿수 (48은 '0'의 ASCII 값)
        sum(s.encode()) = 자릿수의 합 + 48 * 자릿수 개수
        → 48 * len(s)를 빼면 자릿수의 합

    주의:
        N >= 0 에서만 올바름 (음수의 '-' 문자가 섞이면 틀린 값)
        int → str 변환은 4300자리 한도가 있어 초과하면 ValueError
    """
    s = str(N)

    return sum(s.encode()) - 48 * len(s)


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    repeat = 30

    test_cases: list[tuple] = [
        # (N, 기댓값) - 전부 손 계산
        (12345, 15),                                   # 공식 예시
        (0, 0),                                        # 0 경계
        (7, 7),                                        # 한 자리
        (100, 1),                                      # 0이 섞인 수
        (123, 6),
        (999_999_999, 81),                             # 9가 9개
        (123456789012345678, 81),                      # 45 + 36
        (10 ** 18 - 1, 162),                           # 9가 18개
        (int("1" * 1000), 1000),                       # 대용량: 1이 1000개
        (int("9" * 4000), 36000),                      # 대용량: 9가 4000개 (str 한도 4300 이하)
    ]

    solutions = [
        ("Mine one (str)",       solution_mine_one),
        ("Mine two (divmod)",    solution_mine_two),
        ("Best algo (% //)",     solution_best_algo),
        ("Best practical (enc)", solution_best_practical),
    ]

    # 워밍업: 첫 테스트 케이스로 모든 풀이를 1회씩 실행
    warmup_args = test_cases[0][:-1]
    for _, func in solutions:
        func(*warmup_args)

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'평균 소요시간':>12}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (*args, expected) in enumerate(test_cases, 1):
            output = func(*args)

            start = time.perf_counter()
            for _ in range(repeat):
                func(*args)
            elapsed = (time.perf_counter() - start) / repeat

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed*1000:>10.4f}ms")
        print("-" * 64)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
