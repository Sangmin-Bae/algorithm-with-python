"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 크기가 작은 부분문자열
    유형       : String / Sliding Window
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/147355
    풀이일자   : 2026-06-29
===================================================================================
[문제 요약]
    숫자 문자열 t에서 p와 길이가 같은 부분문자열 중
    나타내는 수가 p 이하인 것의 개수를 반환

    제약 조건
        - p 길이: 1 이상 18 이하
        - t 길이: p 길이 이상 10,000 이하
        - t, p는 숫자 문자열, 0으로 시작하지 않음
        - p 길이 최대 18 → 최대 10^18 → Python int 임의 정밀도로 문제없음
===================================================================================
[입출력 예시]
    t              | p     | result
    ---------------|-------|-------
    "3141592"      | "271" | 2      (141, 159만 271 이하)
    "500220839878" | "7"   | 8      (5,0,0,2,2,0,3,7 이하)
    "10203"        | "15"  | 3      (10,02,03이 15 이하)
===================================================================================
[핵심 아이디어 — 문자열 비교로 숫자 대소 판별]
    Python 문자열 비교: 사전식(lexicographic) — 왼쪽부터 문자 하나씩 비교

    "141" <= "271":
        '1' vs '2' → ord('1')=49 < ord('2')=50 → True ✓
    "314" <= "271":
        '3' vs '2' → ord('3')=51 > ord('2')=50 → False ✓

    이게 숫자 비교와 동일하게 동작하는 전제 조건:
        부분문자열 길이 = p 길이로 항상 동일
        → 자릿수가 같으면 사전식 비교 = 숫자 크기 비교

    길이가 다를 때는 성립하지 않음:
        "9" > "10" (문자열): '9' > '1' → True
        9 < 10 (숫자): False  ← 반대 결과
        → 이 문제에서 길이가 항상 같으므로 int() 변환 불필요

[슬라이딩 윈도우 인덱스 설계]
    범위: range(len(t) - len(p) + 1)
    마지막 인덱스 i = len(t) - len(p):
        t[i : i+len(p)] = t[len(t)-len(p) : len(t)] → 정확히 마지막 부분문자열
    +1 이유: range()는 끝값 미포함 → 마지막 인덱스 포함하려면 +1

    손 추적 (t="3141592", p="271", len_p=3):
        range(7-3+1) = range(5) → i=0,1,2,3,4
        i=0: t[0:3]="314" > "271" → 제외
        i=1: t[1:4]="141" ≤ "271" → 포함 ✓
        i=2: t[2:5]="415" > "271" → 제외
        i=3: t[3:6]="159" ≤ "271" → 포함 ✓
        i=4: t[4:7]="592" > "271" → 제외
        → 2 ✓
===================================================================================
[내 초기 풀이]
    solution_mine_one  : 명시적 for 루프 + count 변수 누적
    solution_mine_two  : 리스트 컴프리헨션 + len()
    solution_mine_three: 제너레이터 + sum()

[개선 포인트]
    solution_mine_one  : 개선 필요 없음 - Sub (명시적, 가독성 우위)
    solution_mine_two  :
        리스트 컴프리헨션으로 중간 리스트 생성 → O(N) 공간 소비
        len()은 제너레이터를 받지 못함 → 리스트 필요
        solution_mine_three의 sum(1 for ...) 방식이 공간 더 효율적
    solution_mine_three: 개선 필요 없음 - Best
        제너레이터: 중간 리스트 없이 sum()에 직접 전달 → O(1) 공간
        sum(1 for ... if 조건) = 조건 만족 원소 수 계산 관용 패턴
===================================================================================
[풀이별 공간 복잡도 비교]
    Mine_one  : O(1) — count 변수만 사용
    Mine_two  : O(N) — 조건 만족 인덱스 리스트 생성
    Mine_three: O(1) — 제너레이터로 중간 리스트 없음
    Best      : O(1) — Mine_three와 동일
    Sub       : O(1) — Mine_one과 동일

    len() vs sum(1 for ...):
        len(리스트컴프리헨션): 리스트 전체 생성 후 크기 반환 → O(N) 공간
        sum(1 for ... if 조건): 제너레이터로 원소 하나씩 처리 → O(1) 공간
        조건 만족 원소 개수를 구할 때는 sum(1 for ...) 패턴이 더 효율적
===================================================================================
[복잡도 분석]
    N = len(t) (최대 10,000), L = len(p) (최대 18)
    슬라이딩 윈도우 횟수: N - L + 1

    Mine_one   - 시간: O((N-L)×L) | 공간: O(L) - 슬라이싱 O(L) × (N-L)번
    Mine_two   - 시간: O((N-L)×L) | 공간: O(N) - 중간 리스트 생성
    Mine_three - 시간: O((N-L)×L) | 공간: O(L) - 제너레이터
    Best       - 시간: O((N-L)×L) | 공간: O(L) - Mine_three와 동일
    Sub        - 시간: O((N-L)×L) | 공간: O(L) - Mine_one과 동일

    슬라이싱 t[i:i+L]이 매번 O(L) 문자열 객체 생성
    모든 풀이 시간복잡도 동일 O(N×L)
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution one - 명시적 for 루프 + count 변수
# =================================================================================
def solution_mine_one(t: str, p: str) -> int:
    """
    명시적 for 루프로 슬라이딩 윈도우를 순회하며 조건 만족 개수를 세는 초기 풀이

    핵심:
        range(len(t) - len(p) + 1): out of range 방지 + 마지막 부분문자열 포함
        t[i:i+len(p)]: 인덱스 i부터 p 길이만큼 슬라이싱
        <= p: 자릿수가 같으므로 사전식 비교 = 숫자 크기 비교
    """
    count = 0
    for i in range(len(t) - len(p) + 1):
        if t[i:i + len(p)] <= p:       # 문자열 사전식 비교 = 숫자 크기 비교
            count += 1
    return count


# =================================================================================
# Mine solution two - 리스트 컴프리헨션 + len()
# =================================================================================
def solution_mine_two(t: str, p: str) -> int:
    """
    리스트 컴프리헨션으로 조건 만족 인덱스를 모아 len()으로 개수를 구하는 풀이

    len()은 제너레이터를 받지 못함:
        len(x for x in range(5)) → TypeError
        len([x for x in range(5)]) → 5 (리스트 필요)
    → 리스트 컴프리헨션으로 중간 리스트 생성 → O(N) 공간

    Mine_three 대비:
        중간 리스트 생성 비용 추가
        sum(1 for ...) 방식이 공간 더 효율적
    """
    return len([i for i in range(len(t) - len(p) + 1) if t[i:i + len(p)] <= p])


# =================================================================================
# Mine solution three - 제너레이터 + sum()
# =================================================================================
def solution_mine_three(t: str, p: str) -> int:
    """
    제너레이터 + sum()으로 중간 리스트 없이 조건 만족 개수를 구하는 풀이

    sum(1 for i in range(...) if 조건):
        조건 만족 시 1을 yield → 1의 합 = 조건 만족 개수
        제너레이터: 중간 리스트 생성 없이 sum()에 직접 전달 → O(1) 공간
        조건 만족 개수를 구하는 Python 관용 패턴
    """
    return sum(1 for i in range(len(t) - len(p) + 1) if t[i:i + len(p)] <= p)


# =================================================================================
# Best solution - 제너레이터 + sum() (mine_three 주석 보강)
# =================================================================================
def solution_best(t: str, p: str) -> int:
    """
    제너레이터 + sum()으로 공간 효율적으로 개수를 구하는 최적 풀이

    mine_three와 동일한 로직, 근거 주석 보강:
        슬라이딩 윈도우: range(len(t)-len(p)+1)로 경계 안전하게 순회
        문자열 비교 <=: 자릿수 동일 보장으로 사전식 = 숫자 크기 비교
        sum(1 for ... if ...): 중간 리스트 없는 개수 계산 관용 패턴
    """
    return sum(1 for i in range(len(t) - len(p) + 1) if t[i:i + len(p)] <= p)


# =================================================================================
# Sub solution - 명시적 for 루프 (mine_one 주석 보강)
# =================================================================================
def solution_sub(t: str, p: str) -> int:
    """
    명시적 for 루프로 각 단계를 분리해 표현하는 서브 풀이

    Best 대비 특징:
        count 변수와 for 루프로 각 단계가 명확히 드러남
        슬라이딩 윈도우 동작 원리(인덱스 1씩 이동, 부분문자열 추출, 비교)가
        코드 구조에 직접 대응
        디버깅 시 중간값 확인 용이
    """
    count = 0
    for i in range(len(t) - len(p) + 1):
        if t[i:i + len(p)] <= p:
            count += 1
    return count


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[str, str, int]] = [
        # (t, p, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # "3141592", "271": range(5)
        #   "314">"271", "141"<="271"✓, "415">"271", "159"<="271"✓, "592">"271"
        #   → 2
        ("3141592",      "271", 2),
        # "500220839878", "7": range(12)
        #   "5"<="7"✓,"0"✓,"0"✓,"2"✓,"2"✓,"0"✓,"8">"7","3"✓,"9">"7","8">"7","7"✓,"8">"7"
        #   → 8
        ("500220839878", "7",   8),
        # "10203", "15": range(4)
        #   "10"<="15"✓, "02"<="15"✓, "20">"15", "03"<="15"✓
        #   → 3
        ("10203",        "15",  3),
        # 추가 케이스:
        # t==p: 부분문자열이 p 하나뿐, t[0:len(p)]=t=p → 1
        ("271",          "271", 1),
    ]

    solutions = [
        ("Mine_one   (for+count) ", solution_mine_one),
        ("Mine_two   (컴프리+len)", solution_mine_two),
        ("Mine_three (gen+sum)   ", solution_mine_three),
        ("Best       (gen+sum)   ", solution_best),
        ("Sub        (for+count) ", solution_sub),
    ]

    # 워밍업 스텝
    _t, _p, _ = test_cases[0]
    for _, func in solutions:
        func(_t, _p)

    print("=" * 66)
    print(f"{'풀이':<28} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 66)

    for name, func in solutions:
        for idx, (t, p, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(t, p)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<28} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 66)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
