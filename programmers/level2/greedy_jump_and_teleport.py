"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 점프와 순간 이동
    유형       : Greedy / Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12980
    풀이일자   : 2026-05-16
===================================================================================
[문제 요약]
    0에서 출발해 N까지 이동. 두 가지 행동 가능.
        - 점프:       현재 위치 + K -> 건전지 K 소모
        - 순간이동:   현재 위치 x 2 -> 건전지 소모 없음
    건전지 사용량(점프 총합)의 최솟값을 반환

    제약 조건
        - N: 1 이상 10억 이하 -> O(N) 탐색은 시간 초과, O(log N) 필요
===================================================================================
[입출력 예시]
    N      | result
    -------|-------
    5      | 2      (1점프->순간->순간->1점프: 0->1->2->4->5)
    6      | 2      (1점프->순간->1점프->순간: 0->1->2->3->6)
    5000   | 5
===================================================================================
[내 초기 풀이 - solution_one: 오답 + 비효율]
    접근: jump=1-N 모든 경우에서 초기 jump 후 2배 순간이동 반복
    문제 1 (오답): 중간 점프 경우를 처리 못 함
                    예) 1점프->순간->1점프->순간 (N=6) 케이스 누락
    문제 2 (비효율): O(N log N) -> N=10억 시 약 300억 번 연산

[내 두번째 풀이 - solution_two: 정답]
    발상: 앞->뒤 탐색은 경우의 수 폭발, 뒤->앞은 결정론적
    핵심: 홀수 위치는 순간이동으로 도달 불가 (x2의 결과는 항상 짝수)
            -> 홀수일 때만 점프 1회 필요
    연결: divmod로 2씩 나누는 과정 = 이진수 변환과 동일
            -> 이진수 1의 개수 = 최소 건전지 사용량

[개선 포인트]
    - usage=1 초기화 이유 주석 명시 (0에서 순간이동 불가, 최초 점프 필수)
    - remainder 초기화 변수 제거 (divmod 결과로 바로 받으니 불필요)
===================================================================================
[풀이 전략]
    공통 핵심: 역발향(N->0) + 홀수일 때만 점프 카운트

    Mine_one) 순방향 완전 탐색 (오답)
        - jump=1-N 모든 경우 탐색 후 min()
        - 시간 O(N log N) / 공간 O(N)

    Mine_two) 역방향 divmod (정답)
        - N을 2로 나누며 나머지 1이 발생할 때마다 카운트
        - 시간 O(log N) / 공간 O(1)

    Best) 역방향 divmod (mine_two 개선)
        - mine_two에서 불필요한 변수 제거 + 주석 보강
        - 시간 O(log N) / 공간 O(1)

    Sub) bin() 이진수 직접 변환
        - 이진수 1의 개수 = 최소 점프 횟수를 파이썬 내장 함수로 직접 표현
        - 시간 O(log N) / 공간 O(log N)
===================================================================================
[복잡도 분석]
    N = 입력값 (1 이상 10^9 이하)

    Mine_one  - 시간: O(N log N)  | 공간: O(N)      -> 효율성 테스트 실패
    Mine_two  - 시간: O(log N)    | 공간: O(1)      -> 통과
    Best      - 시간: O(log N)    | 공간: O(1)      -> 통과
    Sub       - 시간: O(log N)    | 공간: O(log N) - bin() 문자열 저장

    O(log N) 실질 의미: N=10억 -> log₂(10^9) ≈ 30번만 반복
===================================================================================
"""

import time
from typing import List, Tuple

# =================================================================================
# Mine solution one - 순방향 완전 탐색 (오답 + 비효율)
# =================================================================================
def solution_mine_one(n: int) -> int:
    """
    jump=1~N 모든 경우에서 초기 jump 후 2배 순간이동 반복하는 초기 풀이

    실패 원인:
        1. 오답: 중간 점프가 섞이는 경우 누락
            예) N = 6: 1점프->순간->1점프->순간 경우를 처리 못 함
        2. 비효율: O(N log N) -> N=10억 시 시간 초과
    """
    battery_cases = []

    for jump in range(1, n + 1):    # 초기 점프 횟수 1~N 모든 경우 탐색
        distance = jump

        # 초기 jump 거리에서 2배 순간이동 반복
        while distance * 2 <= n:
            distance *= 2

        # 남은 거리(순간 이동 불가)는 jump로 이동했다고 가정
        usage = (n - distance) + jump
        battery_cases.append(usage)

    return min(battery_cases)


# =================================================================================
# Mine solution two - 역방향 divmod (정답)
# =================================================================================
def solution_mine_two(n: int) -> int:
    """
    N에서 0 방향으로 역산하며 홀수 발생 시 점프 카운트하는 풀이

    핵심 발상:
        - 순간이동(x2)의 역연산은 ÷2 (짝수일 때만 가능)
        - 홀수 위치는 순간이동으로 도달 불가 -> 반드시 점프 1회 필요
        - divmod로 2씩 나누는 과정 = 이진수 변환과 동일 구조
    """
    usage = 1       # 최초 점프 1회 선반영 (0에서 순간이동 불가)
    quotient = n
    remainder = 0   # 개선 가능: 불필요한 초기화

    while quotient != 1:
        quotient, remainder = divmod(quotient, 2)
        if remainder == 1:  # 홀수 위치 = 점프 필요
            usage += 1

    return usage


# =================================================================================
# Best solution - 역방향 divmod (mine_two 개선)
# =================================================================================
def solution_best(n: int) -> int:
    """
    N을 역방향으로 추적하며 홀수 발생 횟수를 카운트

    mine_two 대비 개선:
        - remainder 초기화 변수 제거 (divmod 언패킹으로 바로 처리)
        - usage=1 이유 주석 명시

    이진수 연결:
        - 2로 나누는 과정: 이진수 변환
        - 나머지 1 발생 = 이진수의 1 = 점프 필요 순간
        - 결국 bin(n).count('1')과 동일한 결과
    """
    # 0에서 순간이동 불가(0x2=0), 최초 점프 1회는 항상 필수
    usage = 1

    quotient = n
    while quotient != 1:
        quotient, remainder = divmod(quotient, 2)
        if remainder == 1:  # 홀수 위치 -> 순간이동으로 도달 불가 -> 점프 1회
            usage += 1

    return usage


# =================================================================================
# Sub solution - bin() 이진수 직접 변환
# =================================================================================
def solution_sub(n:int) -> int:
    """
    n을 이진수로 변환했을 때 1의 개수를 반환

    수학적 근거:
        -  이진수 각 자릿수의 1 = 역방향 추적 시 홀수가 된 순간
        - 홀수 = 순간이동으로 도달 불가 = 점프 필요
        - bin(5) = '0b101' -> 1이 2개 -> 정답 2

    주의: bin() 결과에 '0b' prefix가 붙지만 '0b'에 '1'이 없으므로
            [2:] 슬라이싱 없이 count('1') 사용 가능
    """
    return bin(n).count('1')


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int]] = [
        # (입력, 기댓값),
        (5,          2),    # 기본 예시: 101(2) -> 1이 2개
        (6,          2),    # 기본 얘시: 110(2) -> 1이 2개
        (5000,       2),    # 1001110001000(2) -> 1이 5개
        (1,          1),    # 최솟값: 1(2) -> 1이 1개
        (1000000000, 13),   # 최댓값: 111011100110101100101000000000(2) -> 1이 13개
        (7,          3),    # 111(2) -> 1이 3개
        (8,          1),    # 1000(2) -> 1이 1개 (순간 2의 거듭제곱)
    ]

    # mine_one은 N=10억 입력 시 시간 초과로 비교 대상에서 제외
    solutions = [
        ("Mine two (divmod 역방향)", solution_mine_two),
        ("Best     (divmod 개선)", solution_best),
        ("Sub      (bin count)", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")

    # mine_one 별도 검증 (소규모 입력만)
    print("\nMine_one 검증 (소규모 입력만 - N=10억 시 시간 초과)")
    print("=" * 64)
    small_cases = [(5, 2), (6, 2), (7, 3), (8, 1)]
    for idx, (n, expected) in enumerate(small_cases, 1):
        start = time.perf_counter()
        output = solution_mine_one(n)
        elapsed = time.perf_counter() - start
        status = "PASS" if output == expected else "FAIL"
        print(f"{'Mine_one (순방향 완전탐색)':<30} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
