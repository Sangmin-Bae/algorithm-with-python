"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : x만큼 간격이 있는 n개의 숫자
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12954
    풀이일자   : 2026-05-31
================================================================================
[문제 요약]
    x부터 시작해 x씩 증가하는 숫자를 n개 담은 리스트 반환
    x * i (i=1~n) = [x, 2x, 3x, ..., nx]

    제약 조건
        - x: -10,000,000 이상 10,000,000 이하 (0 포함, 음수 가능)
        - n: 1 이상 1,000 이하
================================================================================
[입출력 예시]
    x  | n | answer
    ---|---|------------------
    2  | 5 | [2, 4, 6, 8, 10]
    4  | 3 | [4, 8, 12]
    -4 | 2 | [-4, -8]          ← 음수: 절댓값 증가, 방향은 음수
================================================================================
[내 초기 풀이]
    solution_one: 리스트 컴프리헨션 [x*i for i in range(1, n+1)]
    solution_two: 명시적 반복문 + append

[검토한 다른 방식]
    numpy 방식:
        list(np.arange(1, n+1) * x)
        - numpy array에 스칼라 곱하면 각 원소에 적용 (브로드캐스팅)
        - 일반 리스트 * x는 원소 연산이 아닌 리스트 반복이라 불가
        - 단, 코딩테스트 환경에서 numpy 사용 불가할 수 있음

    range 직접 활용:
        range(x, x*n+1, x)
        - x=0일 때 ValueError (range step이 0 불가)
        - x 제약 조건에 0이 포함되므로 사용 불가
================================================================================
[numpy vs 순수 파이썬 성능 실측]
    crossover point: n ≈ 1,000

    n=100:   list_comp 우위  (numpy 오버헤드 > 연산 이득)
    n=1,000: numpy 약간 우위 (0.89배)
    n=10,000+: numpy 점점 유리 (C 레벨 벡터 연산)

    numpy가 빠른 이유:
        C 레벨 SIMD 벡터 연산 사용
        파이썬 루프 없이 연속 메모리 블록 연산
        n이 클수록 이점 증가

    이 문제(n ≤ 1,000): 경계선, 어느 쪽도 실질 차이 없음
================================================================================
[복잡도 분석]
    N = n (최대 1,000)

    Mine_one/Best - 시간: O(N) | 공간: O(N) — 리스트 컴프리헨션
    Mine_two/Sub  - 시간: O(N) | 공간: O(N) — 명시적 반복문

    N ≤ 1,000 → 즉시 실행
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one — 리스트 컴프리헨션
# ==============================================================================
def solution_mine_one(x: int, n: int) -> List[int]:
    """
    리스트 컴프리헨션으로 x*i (i=1~n)를 한 줄로 생성하는 초기 풀이

    핵심:
        x * i → x, 2x, 3x, ..., nx (x씩 증가하는 n개)
        음수 x도 올바르게 처리됨 (-4*1=-4, -4*2=-8)
    """
    return [x * i for i in range(1, n + 1)]


# ==============================================================================
# Mine solution two — 명시적 반복문 + append
# ==============================================================================
def solution_mine_two(x: int, n: int) -> List[int]:
    """
    명시적 반복문으로 리스트를 초기화하고 append로 원소를 추가하는 풀이

    Mine_one과 동일한 로직, 단계별로 명확한 표현
    """
    answer = []
    for i in range(1, n + 1):
        answer.append(x * i)
    return answer


# ==============================================================================
# Best solution — 리스트 컴프리헨션 (Mine_one과 동일, 주석 보강)
# ==============================================================================
def solution_best(x: int, n: int) -> List[int]:
    """
    리스트 컴프리헨션으로 간결하게 표현한 최적 풀이

    이 문제에서 Best인 이유:
        - 반환값이 리스트 → 리스트 생성 과정 필수 → 컴프리헨션이 가장 간결
        - range 방식: x=0일 때 ValueError (제약 조건에 0 포함이라 불가)
        - numpy: 코딩테스트 환경 의존 + n≤1,000에서 이점 없음
    """
    # x * i (i=1~n): x, 2x, 3x, ..., nx
    return [x * i for i in range(1, n + 1)]


# ==============================================================================
# Sub solution — 명시적 반복문 (Mine_two와 동일, 주석 보강)
# ==============================================================================
def solution_sub(x: int, n: int) -> List[int]:
    """
    명시적 반복문으로 각 단계를 분리한 풀이

    Best 대비 특징:
        - 각 단계가 명확 → 디버깅 시 중간값 확인 용이
        - 복잡도 동일, 가독성 차이만 있음
    """
    answer = []
    for i in range(1, n + 1):
        answer.append(x * i)    # x씩 증가하는 값 누적
    return answer


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int, List[int]]] = [
        # (x, n, 기댓값)
        (2,  5, [2, 4, 6, 8, 10]),      # 기본 예시 1
        (4,  3, [4, 8, 12]),             # 기본 예시 2
        (-4, 2, [-4, -8]),               # 음수 x
        (0,  3, [0, 0, 0]),              # x=0: 모두 0
        (1,  1, [1]),                    # 최소 n
        (-1, 5, [-1,-2,-3,-4,-5]),       # x=-1
        (10000000, 3, [10000000, 20000000, 30000000]),  # 최대 x
    ]

    solutions = [
        ("Mine_one (리스트컴프리헨션)", solution_mine_one),
        ("Mine_two (명시적반복)",      solution_mine_two),
        ("Best     (컴프리헨션+주석)", solution_best),
        ("Sub      (명시적반복+주석)", solution_sub),
    ]

    print("=" * 66)
    print(f"{'풀이':<28} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 66)

    for name, func in solutions:
        for idx, (x, n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(x, n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<28} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 66)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
