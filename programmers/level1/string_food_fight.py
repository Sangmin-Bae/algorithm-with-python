"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 푸드 파이트 대회
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/134240
    풀이일자   : 2026-07-04
===================================================================================
[문제 요약]
    두 선수가 각각 왼쪽/오른쪽 끝에서 동일한 음식을 동일한 순서로 먹도록
    음식 배치 문자열을 반환. 중앙은 물(0)

    제약 조건
        - food 길이: 2 이상 9 이하
        - food 원소: 1 이상 1,000 이하
        - food[0]: 물, 항상 1 → 양쪽 분배 불필요, range(1, ...) 시작
        - 정답 길이 3 이상 보장
===================================================================================
[입출력 예시]
    food       | result
    -----------|----------------
    [1,3,4,6]  | "1223330333221"
    [1,7,1,2]  | "111303111"
===================================================================================
[핵심 관찰 — 이 문제가 요구하는 로직]
    특별한 알고리즘이 필요하지 않음
    문제의 대칭 구조를 파악하는 것이 핵심:

        "두 선수가 동일한 음식을 동일한 순서로 먹어야 한다"
        → 각 음식 종류별로 food[i] // 2만큼씩 각 선수에게 배분
        → 한 선수의 배열 s를 만들면 전체는 s + '0' + s[::-1]

    수식:
        s = Σ str(i) * (food[i] // 2)  for i in 1..len(food)-1
        result = s + '0' + s[::-1]

    손 추적 ([1,3,4,6]):
        i=1: str(1) * (3//2) = "1" * 1 = "1"
        i=2: str(2) * (4//2) = "2" * 2 = "22"
        i=3: str(3) * (6//2) = "3" * 3 = "333"
        s = "1" + "22" + "333" = "122333"
        result = "122333" + "0" + "333221" = "1223330333221" ✓
===================================================================================
[내 초기 풀이]
    solution_mine_one: 딕셔너리로 한 선수 음식량 정리 후 join + 제너레이터
    solution_mine_two: 딕셔너리 없이 즉시 문자열 누적

    hash 방식 시도 이유:
        이전 "가장 가까운 같은 글자" 문제에서 hash 방식이 핵심이었던 경험
        → 이번에도 먼저 정리 후 처리하는 패턴 적용 시도
        이 문제에서 hash가 필수는 아니나 사고 패턴 연습으로 의미 있음

[개선 포인트]
    solution_mine_one:
        딕셔너리 생성은 해시 쓰기만 → 문자열 객체 생성 없음 (빠름)
        join(generator): 내부에서 임시 리스트 생성 + 2회 순회 → 오버헤드 큼
        딕셔너리 1단계(빠름) + join(generator) 2단계(느림) → 총합이 즉시누적보다 느림
        join(리스트 컴프리헨션)으로 교체하면 일부 개선 가능

    solution_mine_two:
        s += str(i) * (food[i] // 2): food 길이만큼 문자열 객체 반복 생성/갱신
        food 길이가 늘어날수록 갱신 횟수 증가 → 오버헤드 누적
        그러나 딕셔너리 방식의 join(generator) 오버헤드보다는 작음

    단계별 실측 (food 길이=1000, food[i]=2 고정):
        딕셔너리 1단계(해시 쓰기):   54μs
        join(generator) 2단계:      107μs
        딕셔너리 총합:              162μs
        즉시누적(+=):               140μs

    4가지 방식 비교 (food 길이=1000):
        dict + join(generator):   166μs  ← 가장 느림
        dict + join(리스트):      153μs
        즉시누적(+=):             145μs
        리스트 수집 + join(리스트): 118μs ← 가장 빠름

    Best 개선 방향:
        parts = [] → parts.append(...) → ''.join(parts)
        리스트에 부분 문자열을 모은 후 join 1회로 결합
        join(리스트): 리스트 길이 미리 알 수 있음 → 메모리 1회 할당 → 1회 순회
        → 즉시누적의 반복 갱신 오버헤드 없음 + join(generator) 오버헤드 없음
===================================================================================
[복잡도 분석]
    K = len(food) - 1 (최대 8, 사실상 상수)
    M = max(food[i]) (최대 1,000)
    L = 결과 문자열 길이 ≤ K × M

    Mine_one - 시간: O(K×M) | 공간: O(K×M) - 딕셔너리 + join 결과 문자열
    Mine_two - 시간: O(K×M) | 공간: O(K×M) - 누적 문자열 + 결과
    Best     - 시간: O(K×M) | 공간: O(K×M) - Mine_two와 동일, 주석 보강
    Sub      - 시간: O(K×M) | 공간: O(K×M) - Mine_one과 동일, 주석 보강

    K≤8 상수 → 사실상 O(M)이 지배
    두 풀이 복잡도 동일, 실질적 차이 없음
    [::-1] 슬라이싱: O(L) 새 문자열 생성
"""

import time


# =================================================================================
# Mine solution one - 딕셔너리 정리 후 join + 제너레이터
# =================================================================================
def solution_mine_one(food: list[int]) -> str:
    """
    딕셔너리로 한 선수의 음식량을 정리한 뒤 join으로 결합하는 초기 풀이

    핵심:
        f[i] = food[i] // 2: 한 선수가 먹을 i번 음식 개수 (홀수 버림)
        "".join(str(k)*v for k,v in f.items()): 음식 인덱스를 개수만큼 반복 결합
        s + '0' + s[::-1]: 왼쪽 선수 배열 + 물 + 오른쪽 선수 배열(역순)

    딕셔너리 선택 이유:
        이전 hash 학습 영향으로 "먼저 정리 후 처리" 패턴 적용
        이 문제에서 필수는 아니나 사고 패턴 연습으로 의미 있음

    개선 가능:
        join(제너레이터) → join(리스트 컴프리헨션): 실제 성능은 리스트가 유리
        food 길이 상수 수준으로 실질 차이 없음
    """
    f = {}
    for i in range(1, len(food)):
        f[i] = food[i] // 2

    s = "".join(str(k) * v for k, v in f.items())
    return s + '0' + s[::-1]


# =================================================================================
# Mine solution two - 딕셔너리 없이 즉시 문자열 누적
# =================================================================================
def solution_mine_two(food: list[int]) -> str:
    """
    딕셔너리 없이 for 루프에서 즉시 한 선수 배열 문자열을 누적하는 풀이

    mine_one 대비 개선:
        딕셔너리 생성 단계 제거 → 1단계 순회로 s 완성
        s += str(i) * (food[i] // 2): 문자열 불변 객체 → 매번 새 객체 생성

        실제 병목: food의 길이 → s += 반복 횟수를 결정
                   food 길이가 늘어날수록 문자열 갱신 횟수 증가
        두 풀이 공통 비용: food[i] 값 → str(i) * (food[i] // 2) 문자열 크기 결정
                           mine_one도 동일하게 발생하므로 성능 차이에 영향 없음

        mine_one 대비 즉시누적이 느린 이유:
            mine_one: 딕셔너리에 값 추가(빠름) → join 1회(느림)
            mine_two: s += K번 갱신(K = food 길이 - 1)
            → Best(list+join)으로 갱신 횟수와 join 오버헤드 모두 해소

    food[0] 건너뛰기:
        food[0] = 물(항상 1) → 양쪽 분배 불필요 → range(1, ...)
    """
    s = ""
    for i in range(1, len(food)):
        s += str(i) * (food[i] // 2)   # 한 선수 음식 배열 누적
    return s + '0' + s[::-1]


# =================================================================================
# Best solution - 즉시 누적 방식 (mine_two 주석 보강)
# =================================================================================
def solution_best(food: list[int]) -> str:
    """
    리스트에 부분 문자열을 모은 후 join 1회로 결합하는 최적 풀이

    즉시누적(mine_two) 대비 개선:
        s += ...: food 길이만큼 문자열 객체 반복 생성/갱신
        parts.append(...) → ''.join(parts): 부분 문자열을 리스트에 모아 1회 결합

    join(리스트) 선택 이유:
        이전 학습(이상한 문자 만들기, join+generator 반직관 발견)에서 확인:
        join(리스트): 길이 미리 알 수 있음 → 메모리 1회 할당 → 1회 순회
        join(generator): 내부 임시 리스트 + 2회 순회 → 더 느림

    실측 (food 길이=1000):
        dict + join(generator):   166μs
        즉시누적(+=):             145μs
        리스트 수집 + join(리스트): 118μs ← 가장 빠름
    """
    parts = []
    for i in range(1, len(food)):
        parts.append(str(i) * (food[i] // 2))
    s = ''.join(parts)
    return s + '0' + s[::-1]


# =================================================================================
# Sub solution - 딕셔너리 방식 (mine_one 주석 보강)
# =================================================================================
def solution_sub(food: list[int]) -> str:
    """
    딕셔너리로 한 선수 음식량을 정리한 뒤 결합하는 서브 풀이

    Best 대비 특징:
        딕셔너리 f에 한 선수 음식량을 먼저 집계 후 처리
        "정리 후 처리" 2단계 구조가 명시적으로 드러남
        더 복잡한 문제에서 음식량 기반 추가 처리가 필요할 때 확장 용이

    join(제너레이터) 사용:
        이전 학습(이상한 문자 만들기)에서 확인된 반직관적 사실:
        join + 제너레이터가 join + 리스트보다 실제로 느림
        food 길이 상수 수준이라 실질 영향 없음
    """
    f = {}
    for i in range(1, len(food)):
        f[i] = food[i] // 2

    s = "".join(str(k) * v for k, v in f.items())
    return s + '0' + s[::-1]


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[list[int], str]] = [
        # (food, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # [1,3,4,6]:
        #   i=1: "1"*(3//2)="1"
        #   i=2: "2"*(4//2)="22"
        #   i=3: "3"*(6//2)="333"
        #   s="122333" → "1223330333221"
        ([1, 3, 4, 6], "1223330333221"),
        # [1,7,1,2]:
        #   i=1: "1"*(7//2)="111"
        #   i=2: "2"*(1//2)=""   (1//2=0, 아무것도 안 더해짐)
        #   i=3: "3"*(2//2)="3"
        #   s="1113" → "111303111"
        ([1, 7, 1, 2], "111303111"),
        # 추가 케이스:
        # [1,1]: food[1]=1, 1//2=0 → s="" → "0"
        # 단, 정답 길이 3 이상 보장이므로 실제 입력으로 주어지지 않음
        # 아래는 경계값 확인용
        # [1,2]: food[1]=2, 2//2=1 → s="1" → "101"
        ([1, 2], "101"),
        # [1,1000]: food[1]=1000, 1000//2=500 → s="1"*500 → s+"0"+s
        ([1, 1000], "1" * 500 + "0" + "1" * 500),
    ]

    solutions = [
        ("Mine_one (dict+gen)  ", solution_mine_one),
        ("Mine_two (즉시누적)  ", solution_mine_two),
        ("Best     (list+join) ", solution_best),
        ("Sub      (dict+gen) ", solution_sub),
    ]

    # 워밍업 스텝
    _food, _ = test_cases[0]
    for _, func in solutions:
        func(_food)

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (food, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(food)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
