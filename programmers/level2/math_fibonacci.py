"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 피보나치 수
    유형       : Math / DP
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12945
    풀이일자   : 2026-08-09
================================================================================
[문제 요약]
    F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2) 규칙의 n번째 피보나치 수를
    1234567로 나눈 나머지 반환

    제약 조건
        - n: 2 이상 100,000 이하 자연수
================================================================================
[입출력 예시]
    n | return
    --|-------
    3 | 2      (F(3)=2)
    5 | 5      (F(5)=5)
================================================================================
[중간 나머지 연산의 필요성 — 모듈러 산술]
    피보나치 수는 지수적으로 증가 (F(100,000)은 수만 자리)
    Python 임의 정밀도 정수: 자릿수 늘수록 덧셈이 O(자릿수)로 느려짐

    모듈러 산술 합동 성질:
        (a + b) % m = ((a % m) + (b % m)) % m
        → 중간 계산에 미리 나머지 연산 → 항상 1234567 미만 유지
        → 덧셈이 O(1)에 가깝게 유지 → 속도 향상

    최종에만 나머지 연산 → 수만 자리 수 더하기 반복 → 시간 초과

[풀이별 접근 방식]
    풀이1: 변수 2개(a, b) 교체 반복 → O(1) 공간, 가장 빠름
    풀이2: 리스트에 순서대로 저장 → O(N) 공간, 인덱스 접근 명시적
    풀이3: 크기 3 순환 버퍼 → O(1) 공간, % 연산 오버헤드로 풀이2보다 느림
    풀이4: 순수 재귀 → O(2^n) 시간, 중복 호출로 시간 초과
    풀이5: 메모이제이션 재귀 → O(N) 시간, dict/재귀 오버헤드로 가장 느림
           재귀 깊이 100,000 → sys.setrecursionlimit 필요

[실측 결과 — n=100,000, 1,000회 반복]
    풀이1 (변수 2개):     4.391ms  ← 가장 빠름
    풀이2 (리스트 N개):   8.933ms
    풀이3 (순환버퍼 3개): 10.139ms ← 풀이2보다 느림 (% 연산 3회/루프)
    풀이5 (메모이제이션): 32.449ms ← 가장 느림 (dict 조회 + 재귀 오버헤드)

    풀이3이 풀이2보다 느린 이유:
        fib[idx%3], fib[(idx-2)%3], fib[(idx-1)%3]: 매 루프 % 연산 3회
        단순 인덱스 접근(풀이2)보다 오버헤드 큼
================================================================================
[내 초기 풀이]
    solution_mine_one  : 변수 2개 반복 (O(N) 시간, O(1) 공간)
    solution_mine_two  : 리스트 N개 (O(N) 시간, O(N) 공간)
    solution_mine_three: 순환 버퍼 3개 (O(N) 시간, O(1) 공간)
    solution_mine_four : 순수 재귀 (O(2^N) 시간 → 시간 초과)
    solution_mine_five : 메모이제이션 재귀 (O(N) 시간, setrecursionlimit 필요)

[개선 포인트]
    solution_mine_one  : 개선 필요 없음 - Best
                         O(1) 공간, 실측 가장 빠름
    solution_mine_two  : 개선 필요 없음 - Sub
                         인덱스로 이전 값 접근, 동작 원리 명시적
    solution_mine_three: % 연산 오버헤드로 풀이2보다 느림
                         용어 정정: 슬라이딩 윈도우 → 순환 버퍼(Circular Buffer)
    solution_mine_four : O(2^N) → 시간 초과, 학습 목적
    solution_mine_five : setrecursionlimit 필요, dict 오버헤드로 가장 느림
================================================================================
[복잡도 분석]
    N = n (최대 100,000)

    Mine_one   - 시간: O(N) | 공간: O(1) - 변수 2개만 사용
    Mine_two   - 시간: O(N) | 공간: O(N) - 리스트 N+1개 생성
    Mine_three - 시간: O(N) | 공간: O(1) - 크기 3 순환 버퍼
    Mine_four  - 시간: O(2^N) | 공간: O(N) - 재귀 스택 N 깊이 (시간 초과)
    Mine_five  - 시간: O(N) | 공간: O(N) - 메모 dict N개
    Best       - 시간: O(N) | 공간: O(1) - Mine_one과 동일
    Sub        - 시간: O(N) | 공간: O(N) - Mine_two와 동일
"""

import sys
sys.setrecursionlimit(150000)

import time


# ================================================================================
# Mine solution one - 변수 2개 반복
# ================================================================================
def solution_mine_one(n: int) -> int:
    """
    a, b 두 변수를 교체하며 피보나치 수를 계산하는 최적 풀이

    a, b = 0, 1 → F(0), F(1) 초기화
    매 루프: a, b = b, (a+b)%1234567
        a: 이전 값으로 업데이트
        b: 현재 + 이전 합 (나머지 연산으로 크기 제한)

    모듈러 합동 성질:
        (a+b) % m = ((a%m) + (b%m)) % m
        → 중간에 나머지 연산으로 항상 1234567 미만 유지
        → 덧셈이 O(1)에 가깝게 유지

    O(1) 공간: 변수 2개만 사용
    """
    if n == 0: return 0
    if n == 1: return 1

    a, b = 0, 1
    for _ in range(2, n + 1):
        a, b = b, (a + b) % 1234567

    return b


# ================================================================================
# Mine solution two - 리스트 N개
# ================================================================================
def solution_mine_two(n: int) -> int:
    """
    리스트에 피보나치 수를 순서대로 저장하는 풀이

    fib[idx] = (fib[idx-2] + fib[idx-1]) % 1234567:
        인덱스로 이전 두 값에 명시적으로 접근
        F(n) = F(n-2) + F(n-1) 공식이 코드에 직접 드러남

    O(N) 공간: 리스트에 N+1개 원소 저장
    fib[-1]: 마지막 원소 = F(n)
    """
    fib = [0, 1]

    for idx in range(2, n + 1):
        fib.append((fib[idx - 2] + fib[idx - 1]) % 1234567)

    return fib[-1]


# ================================================================================
# Mine solution three - 순환 버퍼 크기 3
# ================================================================================
def solution_mine_three(n: int) -> int:
    """
    크기 3 순환 버퍼(Circular Buffer)로 메모리를 O(1)로 유지하는 풀이

    용어 정정: 슬라이딩 윈도우 → 순환 버퍼(Circular Buffer)
        슬라이딩 윈도우: 연속된 구간이 이동하는 패턴
        순환 버퍼: 고정 크기 배열을 인덱스로 순환하며 재사용

    fib[idx%3] = (fib[(idx-2)%3] + fib[(idx-1)%3]) % 1234567:
        % 3: 인덱스를 0~2로 순환
        → 이전 값을 덮어쓰며 공간 재활용

    풀이2보다 느린 이유:
        매 루프마다 % 연산 3회 추가 → 단순 인덱스 접근보다 오버헤드 큼
    """
    fib = [0] * 3
    fib[0], fib[1] = 0, 1

    for idx in range(2, n + 1):
        fib[idx % 3] = (fib[(idx - 2) % 3] + fib[(idx - 1) % 3]) % 1234567

    return fib[n % 3]


# ================================================================================
# Mine solution four - 순수 재귀 (시간 초과)
# ================================================================================
def solution_mine_four(n: int) -> int:
    """
    피보나치 정의를 재귀로 직접 구현한 풀이 (시간 초과)

    시간 초과 이유:
        F(5) = F(3) + F(4) → F(3)이 두 번 호출
        중복 호출이 지수적으로 증가 → O(2^N)
        n=100,000에서 사실상 계산 불가

    학습 목적: 재귀 정의 자체를 코드로 표현
    메모이제이션(풀이5)으로 O(N)으로 개선 가능
    """
    def fibo(k: int) -> int:
        if k == 0: return 0
        if k == 1: return 1
        return (fibo(k - 2) + fibo(k - 1)) % 1234567

    return fibo(n)


# ================================================================================
# Mine solution five - 메모이제이션 재귀
# ================================================================================
def solution_mine_five(n: int) -> int:
    """
    메모이제이션으로 중복 계산을 제거한 재귀 풀이

    memo dict:
        계산된 fibo(k) 결과를 저장
        이미 계산된 값은 재귀 호출 없이 즉시 반환 → O(N)

    setrecursionlimit 필요:
        n=100,000이면 재귀 깊이 100,000
        Python 기본 한도 1000 → 런타임 에러
        sys.setrecursionlimit(150000)으로 해결

    실측 가장 느린 이유:
        O(N) 시간이지만 dict 해시 조회 + 재귀 함수 호출 오버헤드
        단순 for 루프(풀이1) 대비 7배 이상 느림
    """
    memo = {}

    def fibo(k: int) -> int:
        if k == 0: return 0
        if k == 1: return 1
        if k in memo: return memo[k]
        memo[k] = (fibo(k - 2) + fibo(k - 1)) % 1234567
        return memo[k]

    return fibo(n)


# ================================================================================
# Best solution - 변수 2개 반복 (mine_one 주석 보강)
# ================================================================================
def solution_best(n: int) -> int:
    """
    변수 2개로 O(N) 시간, O(1) 공간에 피보나치 수를 구하는 최적 풀이

    mine_one과 동일한 로직, 선정 근거 주석 보강:
        O(1) 공간: 리스트/dict 없이 변수 2개만
        실측 n=100,000: 4.391ms (풀이2 8.933ms, 풀이5 32.449ms 대비 우위)
        모듈러 합동 성질로 중간 나머지 연산 → 항상 소규모 정수 덧셈 유지
    """
    if n == 0: return 0
    if n == 1: return 1

    a, b = 0, 1
    for _ in range(2, n + 1):
        a, b = b, (a + b) % 1234567

    return b


# ================================================================================
# Sub solution - 리스트 N개 (mine_two 주석 보강)
# ================================================================================
def solution_sub(n: int) -> int:
    """
    리스트에 피보나치 수를 저장하며 동작 원리를 명시적으로 표현하는 서브 풀이

    Best 대비 특징:
        fib[idx-2], fib[idx-1]: 인덱스로 이전 두 값에 명시적 접근
        F(n) = F(n-2) + F(n-1) 공식이 코드에 직접 드러남
        O(N) 공간: 리스트 N+1개 생성 (Best O(1) 대비)
        실측 Best 대비 약 2배 느림 (리스트 append + 인덱스 접근 오버헤드)
    """
    fib = [0, 1]

    for idx in range(2, n + 1):
        fib.append((fib[idx - 2] + fib[idx - 1]) % 1234567)

    return fib[-1]


# ================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[int, int]] = [
        # (n, 기댓값)
        # 공식 예시
        (3,  2),
        (5,  5),
        # 추가 케이스:
        (2,  1),       # F(2)=1
        (10, 55),      # F(10)=55
        (100000, None),  # 최대값 (기댓값은 풀이1로 계산)
    ]

    # 최대값 기댓값 계산
    _ref = solution_mine_one(100000)
    test_cases[-1] = (100000, _ref)

    # solution_mine_four는 소규모에서만 검증
    small_cases = test_cases[:4]

    solutions_all = [
        ("Mine_one   (변수2개)   ", solution_mine_one),
        ("Mine_two   (리스트N)   ", solution_mine_two),
        ("Mine_three (순환버퍼)  ", solution_mine_three),
        ("Mine_five  (메모이제이션)", solution_mine_five),
        ("Best       (변수2개)   ", solution_best),
        ("Sub        (리스트N)   ", solution_sub),
    ]

    # 워밍업 스텝
    _n, _ = test_cases[0]
    for _, func in solutions_all:
        func(_n)

    print("=" * 66)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 66)

    print("--- Mine_four (소규모만, 시간 초과 풀이) ---")
    for idx, (n, expected) in enumerate(small_cases, 1):
        start = time.perf_counter()
        output = solution_mine_four(n)
        elapsed = time.perf_counter() - start
        status = "PASS" if output == expected else "FAIL"
        print(f"{'Mine_four   (순수재귀)  ':<26} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
    print("-" * 66)

    for name, func in solutions_all:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start
            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 66)


# ================================================================================
# 실행 진입점
# ================================================================================
if __name__ == "__main__":
    solution_comparison()
