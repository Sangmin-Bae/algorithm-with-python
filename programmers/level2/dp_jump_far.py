"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 멀리 뛰기
    유형       : DP (Dynamic Programming)
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12914
    풀이일자   : 2026-05-23
================================================================================
[문제 요약]
    1칸 또는 2칸씩 뛰어 n칸을 이동하는 방법의 수를 1234567로 나눈 나머지 반환

    제약 조건
        - 1 <= n <= 2,000
================================================================================
[입출력 예시]
    n   | result
    ----|--------
    4   | 5         -> (1,1,1,1), (1,2,1), (1,1,2), (2,1,1), (2,2)
    3   | 3         -> (1,1,1), (1,2), (2,1)
================================================================================
[f(n)의 정의 - DP의 출발ㄹ점]
    f(n) = "n칸을 이동하는 방법의 총 가짓수"

    수식이 아니라 현실 문제의 답을 담는 함수로 이해해야 함:
        f(1) = 1 -> [1]                                         -> 1가지
        f(2) = 2 -> [1,1], [2]                                  -> 2가지
        f(3) = 3 -> [1,1,1], [2,1], [1,2]                       -> 3가지
        f(4) = 5 -> [1,1,1,1], [2,1,1], [1,2,1], [1,1,2], [2,2] -> 5가지
================================================================================
[점화식 도출 - 왜 f(n) = f(n-1) + f(n-2)인가]
    n칸에 도달하는 마지막 점프를 역으로 생각:

    경우 A: 마지막에 1칸 뛰기 -> 직전에 (n-1)칸에 있었음
        -> (n-1)칸까지 오는 모든 방법 뒤에 1칸만 추가
        -> 경우의 수 = f(n-1)

    경우 B: 마지막에 2칸 뛰기 -> 직전에 (n-2)칸에 있었음
        -> (n-2)칸까지 오는 모든 방법 뒤에 2칸만 추가
        -> 경우의 수 = f(n-2)

    두 경우는 겹치지 않음 (마지막 점프 크기가 다름)
    두 경우 외에 다른 경우 없음 (1칸 or 2칸만 가능)
    -> f(n) = f(n-1) + f(n-2)

    n=4 검증:
        경우 A: f(3)=3가지 뒤에 1 추가 -> [1,1,1,1], [2,1,1], [1,2,1]
        경우 B: f(2)=2가지 뒤에 2 추가 -> [1,1,2], [2,2]
        f(4) = 3 + 2 = 5 ✓
================================================================================
[피보나치 "수열" vs 피보나치 "점화식" - 반드시 구분해야 하는 개념]
    피보나치 수열     : 1, 1, 2, 3, 5, 8, 13, ...  (초기값 1, 1인 구체적 수열)
    피보나치 점화식   : f(n) = f(n-1) + f(n-2)     (초기값과 무관한 구조적 규칙)

    같은 점화식에 초기값이 다르면 수열이 완전히 달라짐:
        초기값 1, 1 -> 1, 1, 2, 3, 5, 8, 13, ...   (피보나치 수열)
        초기값 1, 2 -> 1, 2, 3, 5, 8, 13, 21, ...  (이 문제의 수열)

    이 문제가 "피보나치 점화식"인 이유:
        수열의 값이 같아서가 아니라
        "현재 항 = 직전 두 항의 합" 구조가 같기 때문

    참고: 이 문제의 f(n) = 피보나치 수열의 F(n+1)
        f(1)=1=F(2), f(2)=2=F(3), f(3)=3=F(4), f(4)=5=F(5)
        -> 이 문제 수열은 피보나치를 한 칸 뒤로 밀어놓은 것과 동일
================================================================================
    1. 오버플로우 방지: f(2000)은 천문한적으로 큰 수
    2. 나머지 연산 분배 법칙:
        (a + b) % m = ((a % m) + (b % m)) % m
        -> 매 단계마다 나머지를 취해도 최종 결과 동일
        -> 큰 수를 다루지 않고 항상 작은 수로 유지 가능
    3. 채점 기준 통일: 언어 무관하게 동일한 결과 보장
================================================================================
[내 초기 풀이 - 조합(Combination) 방식]
    접근: 2칸 뛰기 횟수 i = 0 ~ n//2로 순회하면 C(p, i) 합산

    조합이 맞는 수학적 근거:
        - 2칸 뛰기 i번, 1칸 뛰기 (n-2i)번 -> 총 점프 횟수 p = n-i
        - p개 점프 중 i개를 2칸으로 선택하는 위치 = 조합 C(p, i)
        - 순열이 아닌 이유: 2칸짜지 점프끼리는 서로 구별되지 않음
            "어느 위치에 2칸 뛰기를 배치하는가"만 중요 -> 조합

    n=4 검증:
        i=0: C(4,0) = 1 -> [1,1,1,1]
        i=1: C(3,1) = 3 -> [2,1,1], [1,2,1], [1,1,2]
        i=2: C(2,2) = 1 -> [2,2]
        합계 = 5 ✓ 수학적으로 완벽히 성립하는 풀이

[Best 풀이 - DP (피보나치 점화식)]
    f(n) = f(n-1) + f(n-2), dp 배열로 구현
    초기값: dp[1]=1, dp[2]=2

[Sub 풀이 - 공간 최적화 DP]
    dp 배열 대신 변수 a, b 두 개로 직전 두 값만 유지
    공간복잡도 O(N) -> O(1)

[개선 포인트]
    Mine: math.comb 반복 호출 비용 발생, 점화식 구조 코드에 안 보임
    Best: dp 배열 전체 저장, 직관적
    Sub: 변수 2개만 사용, 공간 절감
================================================================================
[풀이 전략]
    Mine)   조합: 2칸 뛰기 횟수별 C(p, i) 합산        O(NxK) / O(1)
    Best)   DP 배열: dp[i] = dp[i-1] + dp[i-2]        O(N)   / O(N)
    Sub)    공간 최적화 DP: 변수 a, b 두 개만 유지    O(N)   / O(1)
================================================================================
[복잡도 분석]
    N = n (최대 2,000)

    Mine    - 시간: O(NxK)    | 공간: O(1) - k: math.comb 내부 비용
    Best    - 시간: O(N)      | 공간: O(N) - dp 배열 전체 저장
    Sub     - 시간: O(N)      | 공간: O(1) - 변수 2개만 유지
================================================================================
"""

import math
import time
from typing import List, Tuple


# ==============================================================================
# Mine solution - 조합(Combination) 방식
# ==============================================================================
def solution_mine(n: int) -> int:
    """
    2칸 뛰기 횟수 i를 0~n//2로 순회하며 조합으로 경우의 수를 계산

    [조합이 성립하는 이유]
        2칸 뛰기 i번, 1칸 뛰기 (n-2i)번 사용 시
        총 점프 횟수 p = (n-2i) + i = n-i
        p개 점프 중 i개를 "2칸"으로 배치할 위치 선택 -> C(p, i)

        순열이 아닌 이유:
            [2,2,1]에서 첫번째 2와 두번째 2를 바꿔도 [2,2,1]로 동일
            -> 같은 크기의 점프끼리 구별 불필요 -> 순서 없는 선택 = 조합

        [한계]
            math.comb 반복 호출 비용 발생
            점화식 구조가 코드에서 직접 보이지 않음
    """
    count = 0
    x = n // 2                          # 2칸 뛰기 최대 횟수

    for i in range(x + 1):
        if i == 0:
            count += 1                  # 전부 1칸: [1,1,...,1] 1가지
        else:
            p = (n - (2 * i)) + i       # 총 점프 횟수 = n - i
            count += math.comb(p, i)    # p개 중 i개를 2칸으로 배치

    return count % 1234567


# ==============================================================================
# Best solution - DP 배열 (피보나치 점화식)
# ==============================================================================
def solution_best(n: int) -> int:
    """
    dp[i] = "i칸을 이동하는 방법의 수"로 정의하고 Bottom-Up으로 채우는 풀이

    [dp[i]의 의미]
        dp[1] = 1 -> [1]            -> 1가지
        dp[2] = 2 -> [1,1], [2]     -> 2가지
        dp[i]     -> i칸 이동 방법의 수

    [1234567 나머지]
        (a+b)%m = ((a%m)+(b%m))%m 성질 덕분에
        매 단계마다 나머지를 취해도 최종 결과 동일
    """
    if n == 1:
        return 1

    dp = [0] * (n + 1)
    dp[1] = 1   # 1칸: [1] -> 1가지
    dp[2] = 2   # 2킨: [1,1], [2] -> 2가지

    for i in range(3, n + 1):
        # i칸 = (i-1)칸에서 1칸 뛰기 + (i-2)에서 2칸 뛰기
        dp[i] = (dp[i-1] + dp[i-2]) % 1234567

    return dp[n]


# ==============================================================================
# Sub solution - 공간 최적화 DP (변수 2개)
# ==============================================================================
def solution_sub(n: int) -> int:
    """
    dp 배열 대신 변수 a, b 두 개로 직전 두 값만 유지하는 공간 최적화 풀이

    [핵심 관찰]
        dp[i]를 계산할 때 dp[i-1], dp[i-2] 두 값만 필요
        do[i-3] 이전 값은 다시 쓰지 않음
        -> 배열 전체 저장 불필요, 변수 2개만 충분

    [a, b의 의미]
        a = dp[i-2] (두 단계 전 값)
        b = dp[i-1] (한 단계 전 값)

        초기: a=dp[1]=1, b=dp[2]=2

    [a, b = b, (a+b) 동작]
        매 회전마다 a와 b가 한 칸씩 앞으로 이동:

        초기:   a=dp[1]=1, b=dp[2]=2
        1회전:  a=dp[2]=2, b=dp[3]=3  -> b = 이전 a+b = 1+2 = 3
        2회전:  a=dp[3]=3, b=dp[4]=5  -> b = 이전 a+b = 2+3 = 5
        3회전:  a=dp[4]=5, b=dp[5]=8  -> b = 이전 a+b = 3+5 = 8

        n=5 기준 3번 반복 후 b = dp[5] = 8 = 정답

    [range(n-2)인 이유]
        dp[1], dp[2]는 초기값으로 설정 완료
        dp[3] ~ dp[n] 계산 필요 -> (n-2)번 반복

        n=5: dp[3], dp[4], dp[5]    -> 3번 = 5-2
        n=4: dp[3], dp[4]           -> 2번 = 4-2
        n=2: 계산 불필요            -> 0번 = 2-2 -> 반복 없이 b=2 반환

    [주의: 파이썬 동시 대입]
        a, b = b, (a+b)     -> 우변을 먼저 계산 후 동시 대입
        a = b; b = a+b      -> 순서대로 하면 a가 먼저 바뀌어 결과가 달라짐
    """
    if n == 1:
        return 1

    a, b = 1, 2     # a = dp[1], b = dp[2]

    for _ in range(n - 2):
        # a: 두 단계 전 값, b: 한 단계 전 값
        # 매 회전: a -> b로, b -> a+b로 한 칸씩 전진
        a, b = b, (a + b) % 1234567

    return b        # 루프 종료 후 b = dp[n]


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증한다."""

    test_cases: List[Tuple[int, int]] = [
        # (n, 기댓값)
        (4, 5),  # 기본 예시 1
        (3, 3),  # 기본 예시 2
        (1, 1),  # 최솟값: [1] → 1가지
        (2, 2),  # [1,1], [2] → 2가지
        (5, 8),  # f(5) = f(4)+f(3) = 5+3 = 8
        (10, 89),  # f(10) 검증
        (2000, None),  # 최댓값 (기댓값은 Best로 계산)
    ]

    # 최댓값 기댓값을 Best로 계산
    test_cases[-1] = (2000, solution_best(2000))

    solutions = [
        ("Mine (조합 C(p,i))", solution_mine),
        ("Best (DP 배열)", solution_best),
        ("Sub  (DP 변수 2개)", solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 64)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()
