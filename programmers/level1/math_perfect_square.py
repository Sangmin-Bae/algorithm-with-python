"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 정수 제곱근 판별
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12934
    풀이일자   : 2025-05-29
================================================================================
[문제 요약]
    n이 양의 정수 x의 제곱이면 (x+1)²을 반환
    아니면 -1 반환

    제약 조건
        - n: 1 이상 50,000,000,000,000 이하 (5×10¹³)
================================================================================
[입출력 예시]
    n   | return
    ----|-------
    121 | 144    (√121=11, (11+1)²=144)
    3   | -1     (3은 완전제곱수 아님)
================================================================================
[세 풀이의 핵심 차이 — 완전제곱수 판별 방식]
    Mine_one  : n**0.5 % 1 == 0              float, 부동소수점 위험
    Mine_two  : math.sqrt(n).is_integer()    float, 부동소수점 위험
    Mine/Best : math.isqrt(n)**2 == n        int,   부동소수점 없음

    n ≤ 5×10¹³ (실측에서 오류 없음 확인):
        float 유효 자릿수 약 15~17자리
        5×10¹³ = 14자리 → 경계에 걸침 → 이론적 위험 존재
        isqrt 방식 → 정수 연산으로 위험 원천 차단
================================================================================
[반환값 int() 변환 필요성]
    Mine_one/two:
        root = float → (root+1)**2 = float → int() 변환 필요
        없으면 144.0 반환 (문제에서 정수 요구)

    Mine(세번째)/Best:
        root = int (math.isqrt 반환값)
        (root+1)**2 = 정수 연산 → int 자동 반환
        int() 불필요 (일관성 목적으로 유지 가능)
================================================================================
[is_integer() 메서드]
    float 타입의 메서드로 소수점 이하가 0인지 판별
    (4.0).is_integer()  → True
    (3.7).is_integer()  → False
    % 1 == 0 방식보다 의도가 명확하고 파이써닉
================================================================================
[복잡도 분석]
    모든 풀이 - 시간: O(1) | 공간: O(1) — 제곱근 계산 1회 + 비교 1회
    복잡도 관점 차이 없음, 안전성 관점에서만 차이 존재
================================================================================
"""

import math
import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one — n**0.5 + % 1 방식
# ==============================================================================
def solution_mine_one(n: int) -> int:
    """
    n**0.5로 제곱근을 구하고 % 1로 정수 여부를 판별하는 초기 풀이

    주의:
        n**0.5: float 반환 → 부동소수점 오류 잠재 위험
        % 1 == 0: 소수점 이하가 0인지 확인
        int(): float 결과를 정수로 변환 필요
    """
    root = n ** 0.5
    return int((root + 1) ** 2) if root % 1 == 0 else -1


# ==============================================================================
# Mine solution two — math.sqrt + is_integer() 방식
# ==============================================================================
def solution_mine_two(n: int) -> int:
    """
    math.sqrt()로 제곱근을 구하고 is_integer()로 정수 여부를 판별하는 풀이

    Mine_one 대비:
        n**0.5와 math.sqrt()는 내부적으로 동일한 float 연산
        is_integer(): % 1 == 0 보다 의도가 명확한 float 메서드
        부동소수점 위험은 동일하게 존재
    """
    root = math.sqrt(n)
    return int((root + 1) ** 2) if root.is_integer() else -1


# ==============================================================================
# Mine solution (세번째) — math.isqrt + 정수 비교
# ==============================================================================
def solution_mine(n: int) -> int:
    """
    math.isqrt()로 정수 제곱근을 구하고 root**2 == n으로 판별하는 풀이

    핵심:
        math.isqrt(n): √n 이하 최대 정수, float 없이 정수 연산
        root**2 == n: 정수 비교 → 부동소수점 오류 원천 차단
        (root+1)**2: 정수 연산 → int 자동 반환
    """
    root = math.isqrt(n)
    return int((root + 1) ** 2) if root ** 2 == n else -1


# ==============================================================================
# Best solution — Mine(세번째) 개선 (if-else 분리)
# ==============================================================================
def solution_best(n: int) -> int:
    """
    정수 연산만으로 완전제곱수를 판별하는 최적 풀이

    Mine(세번째) 대비 개선:
        삼항 표현식 → if-else 분리로 가독성 향상
        (root+1)**2: isqrt 반환값이 int이므로 결과도 int 자동 보장

    안전성:
        float 연산 전혀 없음 → 부동소수점 오류 위험 없음
        n ≤ 5×10¹³에서도 정확하게 동작 보장
    """
    root = math.isqrt(n)            # √n 이하 최대 정수 (정수 연산)
    if root ** 2 == n:              # 완전제곱수 판별: root² = n
        return (root + 1) ** 2      # (x+1)² 반환 (정수 연산, int 자동)
    return -1


# ==============================================================================
# Sub solution — Mine_two 개선 (is_integer, if-else 분리)
# ==============================================================================
def solution_sub(n: int) -> int:
    """
    math.sqrt + is_integer()를 if-else로 분리한 풀이

    Best 대비 특징:
        float 연산 사용 → 부동소수점 위험 존재
        is_integer(): % 1 == 0 보다 의도 명확
        int() 변환 필요: float 결과를 정수로 변환
    """
    root = math.sqrt(n)             # float 제곱근
    if root.is_integer():           # 소수점 이하 0 여부 판별
        return int((root + 1) ** 2) # float → int 변환 필요
    return -1


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, int]] = [
        # (n, 기댓값)
        (121,              144),             # 기본 예시 1: √121=11, (11+1)²=144
        (3,                 -1),             # 기본 예시 2: 완전제곱수 아님
        (1,                  4),             # 최솟값: √1=1, (1+1)²=4
        (4,                  9),             # √4=2, (2+1)²=9
        (9,                 16),             # √9=3, (3+1)²=16
        (49999988518489, 50000002660624),   # 최댓값 근방: 7071067²
        (50000000000000,    -1),             # 최댓값: 완전제곱수 아님
    ]

    solutions = [
        ("Mine_one  (n**0.5+%1)",       solution_mine_one),
        ("Mine_two  (sqrt+is_int)",     solution_mine_two),
        ("Mine      (isqrt+정수비교)",  solution_mine),
        ("Best      (isqrt+if분리)",    solution_best),
        ("Sub       (sqrt+is_int분리)", solution_sub),
    ]

    print("=" * 68)
    print(f"{'풀이':<28} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 68)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<28} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 68)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()