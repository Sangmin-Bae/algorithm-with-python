"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 2
    문제명     : 연속 부분 수열 합의 개수
    유형       : Sliding Window / Set
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/131701
    풀이일자   : 2025-06-04
================================================================================
[문제 요약]
    원형 수열에서 연속 부분 수열 합의 종류 개수 반환
    길이 1 이상 len(elements) 이하인 연속 부분 수열의 합을 중복 제거 후 개수 반환.

    제약 조건
        - elements 길이: 3 이상 1,000 이하
        - 원소: 1 이상 1,000 이하
================================================================================
[입출력 예시]
    elements   | result
    -----------|-------
    [7,9,1,1,4]| 18
    (길이1→{1,4,7,9} 4종, 길이2→{2,5,10,11,16} 5종,
        길이3→{6,11,12,17,20} 5종, 길이4→{13,15,18,21} 4종, 길이5→{22} 1종
        → 중복 제거 후 18가지)
================================================================================
[왜 순열/조합이 적합하지 않은가]
    핵심 조건: "연속하는" 부분 수열

    순열 P(n,k):
        순서 있는 모든 선택
        예) [9,7]: 원형에서 9→7은 연속이 아님 (7→9가 연속)
        → 연속되지 않은 조합도 포함 → 부적합

    조합 C(n,k):
        순서 없는 선택
        예) {7,1}: 원형에서 7과 1은 인접하지 않음
        [7,9]와 [9,7]을 같은 것으로 취급 → 방향성 무시
        → 연속성/순서 조건 모두 불만족 → 부적합

    연속 부분 수열의 정의:
        "시작점(i)과 길이(k)로 완전히 결정됨"
        → 직접 이중 for 루프로 인덱스 제어가 자연스러운 선택
================================================================================
[Mine 풀이 상세 분석 — sum(slice)의 중복 계산]
    double_elements = [7,9,1,1,4, 7,9,1,1,4]  ← 원형을 선형화

    i=1(시작=9)일 때 연산 과정:
        j=2: sum([9])        = 9   → 덧셈 1번
        j=3: sum([9,1])      = 10  → 덧셈 2번 (9를 또 더함)
        j=4: sum([9,1,1])    = 11  → 덧셈 3번 (9,1을 또 더함)
        j=5: sum([9,1,1,4])  = 15  → 덧셈 4번 (9,1,1을 또 더함)
        j=6: sum([9,1,1,4,7])= 22  → 덧셈 5번 (9,1,1,4를 또 더함)
        i=1 기준: 1+2+3+4+5 = 15번

    전체 연산 횟수: l × l(l+1)/2 → O(N³)
    l=1000: 약 500,500,000번
================================================================================
[Ref/Best 풀이 상세 분석 — 누적합으로 이전 합 재사용]
    i=1(시작=9)일 때 연산 과정:
        ssum = 9                          → 1번
        j=2: ssum += elements[2%5=2]=1   ssum=10  (9 재사용)
        j=3: ssum += elements[3%5=3]=1   ssum=11  (10 재사용)
        j=4: ssum += elements[4%5=4]=4   ssum=15  (11 재사용)
        j=5: ssum += elements[5%5=0]=7   ssum=22  (15 재사용, 원형!)
        i=1 기준: 5번 (항상 이전 합 + 원소 1개)

    j%ll 의 역할:
        j가 ll을 초과하면 % 연산으로 처음으로 돌아감
        double_elements 없이 원형 수열 표현
        예) ll=5, i=4: j=5→elements[0]=7, j=6→elements[1]=9

    전체 연산 횟수: l × l → O(N²)
    l=1000: 약 1,000,000번

[두 방식 연산 횟수 비교 (l=1000)]
    Mine: l × l(l+1)/2 = 500,500,000번
    Best: l × l         =   1,000,000번
    → 이론 500배, 실측 21배 (sum이 C 레벨이라 상수 작음)
================================================================================
[핵심 아이디어]
    원형 수열 처리: elements*2(Mine/Sub) 또는 j%n(Best/Ref)
    중복 제거: set 자료형
    합산 최적화: sum(slice) O(N) → 누적합 += O(1)
================================================================================
[내 초기 풀이 — double_elements 방식]
    접근 과정:
        순열/조합 → 연속성 조건 불만족 확인
        원형 수열 처리: elements * 2로 2배 확장
        [i:j] 슬라이싱으로 연속 부분 수열 추출
        sum()으로 합산 후 set에 추가

    2배 확장만으로 충분한 이유:
        시작 인덱스 0~l-1, 길이 1~l
        최대 끝 인덱스 = (l-1)+l = 2l-1 < 2l → 2배면 충분

[개선 포인트]
    sum(double_elements[i:j]):
        슬라이싱 O(N) → 새 리스트 생성
        sum() O(N) → 처음부터 재합산
        이전 계산 버리고 매번 재계산 → O(N³) 원인
        → 누적합 += 원소 O(1)로 교체 → O(N²)
================================================================================
[복잡도 분석]
    N = len(elements) (최대 1,000)

    Mine - 시간: O(N³) | 공간: O(N²) — sum(slice) 재합산
    Best - 시간: O(N²) | 공간: O(N²) — 누적합 O(1) + % 연산
    Sub  - 시간: O(N²) | 공간: O(N²) — double_elements + 누적합

    set 최대 크기: O(N²) — 시작점 N × 길이 N → 최대 N² 종류
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution — double_elements + sum() 슬라이싱
# ==============================================================================
def solution_mine(elements: List[int]) -> int:
    """
    elements를 2배 확장 후 슬라이싱으로 모든 연속 부분 수열 합을 구하는 초기 풀이

    핵심 발상:
        원형 수열 → elements * 2로 선형화
        [i:j] 슬라이싱으로 연속 부분 수열 추출
        set으로 중복 자동 제거

    개선 전 상태:
        sum(double_elements[i:j]): 슬라이싱 O(N) + 합산 O(N)
        이전 합을 버리고 매번 처음부터 재계산 → O(N³) 원인
    """
    answer = set()
    l = len(elements)
    double_elements = elements * 2

    for i in range(l):
        for j in range(i + 1, i + l + 1):
            answer.add(sum(double_elements[i:j]))   # 매번 처음부터 합산

    return len(answer)


# ==============================================================================
# Best solution — 누적합 + % 연산 (Ref 개선)
# ==============================================================================
def solution_best(elements: List[int]) -> int:
    """
    누적합으로 이전 계산을 재사용해 O(N²)으로 개선한 최적 풀이

    Mine 대비 핵심 개선:
        sum(slice) O(N) → cumsum += O(1)
        이전 합에 다음 원소만 추가 → 중복 계산 제거

    % 연산으로 원형 수열 처리:
        j % n: j가 n을 넘으면 처음으로 돌아감
        double_elements 불필요 → 추가 메모리 없음

    누적합 손 추적 (elements=[1,2,3,4], i=0):
        cumsum = 1         → add(1)
        cumsum += 2 = 3    → add(3)
        cumsum += 3 = 6    → add(6)
        cumsum += 4 = 10   → add(10)
        (매번 이전 합 + 원소 1개 = O(1))
    """
    n = len(elements)
    sums = set()

    for i in range(n):              # 시작 인덱스 0~n-1
        cumsum = elements[i]        # 길이 1 부분 수열의 합
        sums.add(cumsum)
        for j in range(i+1, i+n):  # 길이 2~n
            cumsum += elements[j % n]   # 이전 합에 다음 원소만 추가 O(1)
            sums.add(cumsum)

    return len(sums)


# ==============================================================================
# Sub solution — double_elements + 누적합 결합
# ==============================================================================
def solution_sub(elements: List[int]) -> int:
    """
    double_elements 방식을 유지하면서 누적합으로 개선한 절충안

    Mine 대비 개선:
        sum(slice) → 누적합 O(1)로 교체
        double_elements 발상을 유지하면서 성능 개선

    Best 대비 특징:
        % 연산 대신 double_elements 슬라이싱 사용
        메모리를 더 씀 (double_elements 생성)
        직관성: 원형 수열 선형화 발상이 코드에 드러남
    """
    n = len(elements)
    double_elements = elements * 2
    sums = set()

    for i in range(n):
        cumsum = double_elements[i]     # 길이 1 합
        sums.add(cumsum)
        for j in range(i+1, i+n):      # 길이 2~n
            cumsum += double_elements[j]    # 누적합 O(1)
            sums.add(cumsum)

    return len(sums)


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[int], int]] = [
        # (elements, 기댓값)
        # [7,9,1,1,4] 손 추적:
        #   길이1: 7,9,1,1,4 → {7,9,1,4}
        #   길이2: 16,10,2,5,11 → {16,10,2,5,11}
        #   길이3: 17,11,6,14,12 → {17,11,6,14,12}
        #   길이4: 18,12,15,13 → {18,12,15,13} (일부 중복 제거됨)
        #   길이5: 22 → {22}
        #   직접 계산: 18가지
        ([7, 9, 1, 1, 4],   18),
        # [1,1,1]: 길이1→{1}, 길이2→{2}, 길이3→{3} → 3가지
        ([1, 1, 1],          3),
        # [1]: 길이1→{1} → 1가지
        ([1],                1),
        # [1,2]: 길이1→{1,2}, 길이2→{3} → 3가지
        ([1, 2],             3),
        # [1,2,3]: 길이1→{1,2,3}, 길이2→{3,4,5}, 길이3→{6}
        #   합집합: {1,2,3,4,5,6} → 6가지
        ([1, 2, 3],          6),
    ]

    solutions = [
        ("Mine (sum+slice O(N³))", solution_mine),
        ("Best (누적합 O(N²))",    solution_best),
        ("Sub  (double+누적합)",   solution_sub),
    ]

    print("=" * 64)
    print(f"{'풀이':<26} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 64)

    for name, func in solutions:
        for idx, (elements, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(elements[:])
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<26} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 64)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()