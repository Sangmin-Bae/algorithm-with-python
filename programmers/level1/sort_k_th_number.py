"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : K번째수
    유형       : Sort
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/42748
    풀이일자   : 2026-06-11
===================================================================================
[문제 요약]
    array의 i번째부터 j번째까지 자르고 정렬했을 때 k번째 수를 구함
    commands의 모든 [i, j, k]에 대해 반복, 결과를 리스트로 반환

    제약 조건
        - array 길이: 1 이상 100 이하
        - array 원소: 1 이상 100 이하
        - commands 길이: 1 이상 50 이하
        - i, j, k: 1-indexed (순서 번호, 0-indexed 인덱스 아님)
===================================================================================
[입출력 예시]
    array           | commands                      | return
    ----------------|-------------------------------|---------
    [1,5,2,6,3,7,4] | [[2,5,3],[4,4,1],[1,7,3]]     | [5,6,3]

    입출력 예 설명:
        [2,5,3]: array[1:5]=[5,2,6,3] → sorted=[2,3,5,6] → [2]번째=5
        [4,4,1]: array[3:4]=[6]       → sorted=[6]       → [0]번째=6
        [1,7,3]: array[0:7]=[1,5,2,6,3,7,4] → sorted=[1,2,3,4,5,6,7] → [2]번째=3
===================================================================================
[내 초기 풀이]
    solution_mine: 리스트 컴프리헨션으로 한 줄 표현

    핵심 인덱스 변환:
        i, j, k는 1-indexed → 0-indexed 변환 필요
        슬라이싱: array[i-1:j]
            i-1: 시작 인덱스 (1-indexed → 0-indexed)
            j  : 끝 인덱스 (슬라이싱은 끝 인덱스 미포함 → j-1+1 = j)
                    array[i-1:j-1]로 하면 j번째 원소 누락
        k번째: sorted(...)[k-1]
            k-1: 1-indexed k를 0-indexed로 변환

    commands를 리스트 컴프리헨션으로 순회:
        별도 리스트 변수와 append 없이 결과를 바로 반환

[개선 포인트]
    solution_mine: 개선 필요 없음 - Best
                    이 문제는 슬라이싱 → 정렬 → 인덱스 접근이 필수 3단계
                    commands의 i, j가 매번 달라 전처리/캐싱으로 줄일 수 없음
                    → O(M × N log N)이 이 문제의 하한, 알고리즘 최적화 여지 없음
===================================================================================
[슬라이싱 끝 인덱스 처리 근거]
    1-indexed j번째까지 포함하는 슬라이싱:

    array = [1, 5, 2, 6, 3, 7, 4], i=2, j=5
        array[i-1:j]   = array[1:5] → [5, 2, 6, 3]  (2~5번째 원소) ✓
        array[i-1:j-1] = array[1:4] → [5, 2, 6]     (2~4번째 원소) ✗

    Python 슬라이싱 [a:b]는 b를 미포함
    → 1-indexed j번째 원소의 0-indexed = j-1
    → 슬라이싱 끝에 j-1+1 = j를 쓰면 j번째까지 포함
    → j를 그대로 쓰면 되는 이유
===================================================================================
[복잡도 분석]
    N = len(array) (최대 100)
    M = len(commands) (최대 50)

    Mine - 시간: O(M × N log N) | 공간: O(N) - 슬라이싱 O(N) + 정렬 O(N log N), M회 반복
    Best - 시간: O(M × N log N) | 공간: O(N) - Mine과 동일, 주석 보강
    Sub  - 시간: O(M × N log N) | 공간: O(N) - 명시적 for 루프, 복잡도 동일

    N=100, M=50 고정 → 최대 50 × 100 × log(100) ≈ 33,000번 연산, 사실상 O(1)
    알고리즘 최적화 여지 없음: commands의 i, j가 매번 달라 전처리/캐싱 불가
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - 리스트 컴프리헨션 한 줄 표현
# =================================================================================
def solution_mine(array: List[int], commands: List[List[int]]) -> List[int]:
    """
    리스트 컴프리헨션으로 commands를 순회하며 결과를 한 줄로 반환하는 초기 풀이

    핵심:
        array[i-1:j]: 1-indexed i~j를 0-indexed 슬라이싱으로 변환
        sorted(...)[k-1]: 정렬 후 1-indexed k를 0-indexed로 변환해 추출
        별도 리스트 변수 없이 컴프리헨션으로 바로 반환
    """
    return [sorted(array[i-1:j])[k-1] for i, j, k in commands]


# =================================================================================
# Best solution - Mine 주석 보강
# =================================================================================
def solution_best(array: List[int], commands: List[List[int]]) -> List[int]:
    """
    리스트 컴프리헨션으로 슬라이싱 → 정렬 → 인덱스 추출을 한 줄로 표현한 최적 풀이

    Mine과 동일한 로직, 근거 주석 보강:
        array[i-1:j]: 시작 i-1 (1→0-indexed), 끝 j (슬라이싱 미포함 성질로 j번째까지 포함)
        sorted(array[i-1:j]): 원본 array 보존, 슬라이싱 결과만 정렬
        [k-1]: 1-indexed k를 0-indexed로 변환

    이 문제의 최선인 이유:
        commands의 i, j 범위가 매번 달라 전처리/캐싱으로 정렬 횟수 줄일 수 없음
        → 슬라이싱 → 정렬 → 추출 3단계가 매 command마다 필수
        → O(M × N log N)이 하한, 알고리즘 최적화 여지 없음
    """
    return [sorted(array[i-1:j])[k-1] for i, j, k in commands]


# =================================================================================
# Sub solution - 명시적 for 루프
# =================================================================================
def solution_sub(array: List[int], commands: List[List[int]]) -> List[int]:
    """
    명시적 for 루프로 각 단계를 분리해서 표현한 서브 풀이

    Best 대비 특징:
        슬라이싱 → 정렬 → 추출 각 단계가 변수로 분리되어 가독성 우위
        중간값(sliced, sorted_arr) 확인 가능 → 디버깅 용이
        로직 흐름이 지문의 설명 순서와 1:1 대응
    """
    answer = []

    for i, j, k in commands:
        sliced = array[i-1:j]           # 1. i번째~j번째 슬라이싱
        sorted_arr = sorted(sliced)     # 2. 오름차순 정렬
        answer.append(sorted_arr[k-1])  # 3. k번째 원소 추출 (1-indexed → 0-indexed)

    return answer


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[int], List[List[int]], List[int]]] = [
        # (array, commands, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # [2,5,3]: array[1:5]=[5,2,6,3] → sorted=[2,3,5,6] → [2]=5
        # [4,4,1]: array[3:4]=[6]       → sorted=[6]       → [0]=6
        # [1,7,3]: array[0:7]=[1,5,2,6,3,7,4] → sorted=[1,2,3,4,5,6,7] → [2]=3
        ([1,5,2,6,3,7,4], [[2,5,3],[4,4,1],[1,7,3]], [5,6,3]),
        # 추가 케이스:
        # [1,1,1]: array[0:1]=[1] → sorted=[1] → [0]=1
        ([1,5,2,6,3,7,4], [[1,1,1]], [1]),
        # [1,7,1]: array[0:7]=[1,5,2,6,3,7,4] → sorted=[1,2,3,4,5,6,7] → [0]=1
        ([1,5,2,6,3,7,4], [[1,7,1]], [1]),
        # [1,7,7]: array[0:7] → sorted=[1,2,3,4,5,6,7] → [6]=7
        ([1,5,2,6,3,7,4], [[1,7,7]], [7]),
    ]

    solutions = [
        ("Mine (컴프리헨션)", solution_mine),
        ("Best (컴프리헨션)", solution_best),
        ("Sub  (for 루프)  ", solution_sub),
    ]

    print("=" * 62)
    print(f"{'풀이':<22} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (array, commands, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(array[:], [c[:] for c in commands])
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<22} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
