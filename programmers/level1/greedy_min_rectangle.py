"""
================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 최소직사각형
    유형       : Greedy / Sort
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/86491
    풀이일자   : 2026-05-27
================================================================================
[문제 요약]
    명함을 회전(가로↔세로 교체) 가능할 때
    모든 명함을 수납할 수 있는 최소 지갑 크기(넓이) 반환

    제약 조건
        - sizes 길이: 1 이상 10,000 이하
        - w, h: 1 이상 1,000 이하
================================================================================
[입출력 예시]
    sizes                                      | result
    -------------------------------------------|-------
    [[60,50],[30,70],[60,30],[80,40]]          | 4000
    [[10,7],[12,3],[8,15],[14,7],[5,15]]       | 120
    [[14,4],[19,6],[6,16],[18,7],[7,11]]       | 133
================================================================================
[핵심 아이디어 — 방향 통일]
    명함을 회전할 수 있으므로 가로/세로 고정 개념이 없음
    → 모든 명함을 "긴 쪽 = 가로, 짧은 쪽 = 세로"로 방향 통일
    → 지갑 가로 = max(모든 명함의 가로)
    → 지갑 세로 = max(모든 명함의 세로)
    → 최소 지갑 = 지갑 가로 × 지갑 세로
================================================================================
[Mine_one 실패 원인]
    가정: "모든 값을 하나로 모아 정렬 후 절반으로 나누면 가로/세로가 분리된다"
    실패 이유: 한 명함의 두 값이 절반 나누기 후 같은 쪽에 들어갈 수 있음
                → 가로/세로 쌍 관계가 무너짐

    반례: sizes = [[5,3], [4,6], [2,2]]
        모든 값 정렬: [6,5,4,3,2,2]
        w=[6,5,4], h=[3,2,2]  → max(w)*max(h) = 6*3 = 18  (오답)

    정답:
        [5,3] → 긴쪽=5, 짧은쪽=3
        [4,6] → 긴쪽=6, 짧은쪽=4  (회전)
        [2,2] → 긴쪽=2, 짧은쪽=2
        지갑 = max(5,6,2) × max(3,4,2) = 6*4 = 24

    [4,6]의 6이 w, 4가 h에 들어가야 하는데
    solution_one은 6을 w에, 3([5,3]의 짧은쪽)을 h에 배치
    → 쌍 관계 무너짐 → 오답
================================================================================
[solution_two, three, four의 공통 핵심]
    세 풀이 모두 동일한 아이디어를 구현 방식만 다르게 표현:
        긴 쪽 → 가로 통일, 짧은 쪽 → 세로 통일
        지갑 = max(가로들) × max(세로들)

    구현 차이:
        Mine_two  : 리스트 두 개에 담은 뒤 max()
        Mine_three: 변수 두 개로 순회하며 갱신
        Ref : 제너레이터 표현식으로 한 줄 (sizes 두 번 순회)
================================================================================
[Ref (다른 사람 풀이) 분석]
    max(max(x) for x in sizes) * max(min(x) for x in sizes)
        - 파이써닉하고 간결함
        - 단, sizes를 두 번 순회 (max, min 각각)
        - Best 대비 상수 2배 순회 (복잡도 등급은 동일 O(N))
        - "한 줄이 더 효율적"이라고 보기는 어려움
================================================================================
[복잡도 분석]
    N = len(sizes) (최대 10,000)

    Mine_one   - 시간: O(N log N) | 공간: O(N) — sort 포함, 오답
    Mine_two   - 시간: O(N)       | 공간: O(N) — 리스트 두 개
    Mine_three - 시간: O(N)       | 공간: O(1) — 변수 두 개, sort() 원본 수정
    Ref        - 시간: O(N)       | 공간: O(1) — 2N번 순회
    Best       - 시간: O(N)       | 공간: O(1) — N번 순회, 원본 보존
    Sub        - 시간: O(N)       | 공간: O(1) — 2N번 순회 (Ref와 동일)
================================================================================
"""

import time
from typing import List, Tuple


# ==============================================================================
# Mine solution one — 전체 값 모아 정렬 후 절반 분리 (오답)
# ==============================================================================
def solution_mine_one(sizes: List[List[int]]) -> int:
    """
    모든 가로/세로 값을 하나로 모아 정렬 후 절반으로 분리하는 초기 풀이

    실패 이유:
        한 명함의 두 값이 정렬 후 같은 쪽(w 또는 h)에 들어갈 수 있음
        → 가로/세로 쌍 관계가 무너져 오답 발생
        반례: [[5,3],[4,6],[2,2]] → 18 (정답 24)
    """
    s = []
    for x, y in sizes:
        s.append(x)
        s.append(y)

    s.sort(reverse=True)
    half = len(sizes)
    w = s[:half]
    h = s[half:]

    return max(w) * max(h)


# ==============================================================================
# Mine solution two — 리스트 두 개로 긴쪽/짧은쪽 분리
# ==============================================================================
def solution_mine_two(sizes: List[List[int]]) -> int:
    """
    각 명함의 긴 쪽을 w 리스트, 짧은 쪽을 h 리스트에 담아 max 곱 반환

    개선 가능:
        w, h 리스트 → 변수 두 개로 교체하면 공간 O(N) → O(1)
    """
    w, h = [], []

    for size in sizes:
        w.append(max(size))     # 긴 쪽 → 가로
        h.append(min(size))     # 짧은 쪽 → 세로

    return max(w) * max(h)


# ==============================================================================
# Mine solution three — 변수 두 개로 순회하며 갱신
# ==============================================================================
def solution_mine_three(sizes: List[List[int]]) -> int:
    """
    리스트 없이 변수 두 개로 max를 순회하며 갱신하는 풀이

    Mine_two 대비 개선:
        리스트 → 변수 두 개로 공간 O(N) → O(1)

    주의:
        size.sort(reverse=True): 원본 sizes 내부 리스트 직접 수정
        → 함수 외부에서 sizes 재사용 시 순서가 바뀜
        → if w < h: w, h = h, w 스왑으로 교체 가능
    """
    w_, h_ = 0, 0

    for size in sizes:
        size.sort(reverse=True)             # 원본 수정 주의
        w_ = max(w_, size[0])               # 긴 쪽 최댓값 갱신
        h_ = max(h_, size[1])               # 짧은 쪽 최댓값 갱신

    return w_ * h_


# ==============================================================================
# Ref solution — 다른 사람 풀이 — 제너레이터 한 줄
# ==============================================================================
def solution_ref(sizes: List[List[int]]) -> int:
    """
    제너레이터 표현식으로 한 줄에 표현한 다른 사람 풀이

    분석:
        max(max(x) for x in sizes): 각 명함 긴 쪽 중 최댓값 → 지갑 가로
        max(min(x) for x in sizes): 각 명함 짧은 쪽 중 최댓값 → 지갑 세로

    Best 대비:
        파이써닉하고 간결하나 sizes를 두 번 순회 (2N번)
        Best는 한 번 순회 (N번) → 상수 측면에서 Best가 효율적
        복잡도 등급은 동일 O(N)
    """
    return max(max(x) for x in sizes) * max(min(x) for x in sizes)


# ==============================================================================
# Best solution — 변수 두 개 + 스왑으로 원본 보존
# ==============================================================================
def solution_best(sizes: List[List[int]]) -> int:
    """
    긴 쪽/짧은 쪽을 스왑으로 통일하며 변수 두 개로 최댓값을 갱신하는 최적 풀이

    Mine_three 대비 개선:
        size.sort() → if w < h: w, h = h, w 스왑
        - 원본 sizes 수정 없음
        - sort() 함수 호출 비용 없음
        - 의도가 더 명확 ("짧은 쪽이 가로면 회전")

    N번 단일 순회 → Best의 핵심
    """
    max_w = max_h = 0

    for w, h in sizes:
        if w < h:
            w, h = h, w             # 긴 쪽이 가로가 되도록 회전
        max_w = max(max_w, w)       # 가로 최댓값 갱신
        max_h = max(max_h, h)       # 세로 최댓값 갱신

    return max_w * max_h


# ==============================================================================
# Sub solution — 제너레이터 한 줄 (Ref와 동일 로직, 주석 보강)
# ==============================================================================
def solution_sub(sizes: List[List[int]]) -> int:
    """
    제너레이터 표현식으로 한 줄에 표현한 풀이 (Ref와 동일)

    Best 대비:
        간결하나 sizes 두 번 순회 (2N번)
        "가장 파이써닉"하지만 "가장 효율적"이지는 않음
    """
    return max(max(x) for x in sizes) * max(min(x) for x in sizes)


# ==============================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# ==============================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[List[List[int]], int]] = [
        # (sizes, 기댓값)
        ([[60,50],[30,70],[60,30],[80,40]], 4000),   # 기본 예시 1
        ([[10,7],[12,3],[8,15],[14,7],[5,15]], 120), # 기본 예시 2
        ([[14,4],[19,6],[6,16],[18,7],[7,11]], 133), # 기본 예시 3
        ([[5,3],[4,6],[2,2]], 24),                   # Mine_one 반례
        ([[1,1]], 1),                                # 단일 명함
        ([[1000,1000]], 1000000),                    # 최대 원소값
    ]

    solutions = [
        ("Mine_one   (전체정렬+절반)",   solution_mine_one),
        ("Mine_two   (리스트분리)",      solution_mine_two),
        ("Mine_three (변수갱신+sort)",   solution_mine_three),
        ("Ref  (제너레이터한줄)",  solution_ref),
        ("Best       (스왑+변수갱신)",   solution_best),
        ("Sub        (제너레이터한줄)",  solution_sub),
    ]

    print("=" * 68)
    print(f"{'풀이':<30} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 68)

    for name, func in solutions:
        for idx, (sizes, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func([s[:] for s in sizes])  # 원본 보존
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<30} TC{idx:<5} {status:<8} {elapsed*1000:>8.4f}ms")
        print("-" * 68)


# ==============================================================================
# 실행 진입점
# ==============================================================================
if __name__ == "__main__":
    solution_comparison()