"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 수박수박수박수박수박수?
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12922
    풀이일자   : 2026-06-21
===================================================================================
[문제 요약]
    길이가 n이고 "수박수박수...." 패턴을 유지하는 문자열을 반환

    제약 조건
        - n: 1 이상 10,000 이하 자연수
        - 항상 "수"로 시작
===================================================================================
[입출력 예시]
    n | return
    --|--------
    3 | "수박수"
    4 | "수박수박"
===================================================================================
[내 초기 풀이]
    solution_mine_one: 명시적 변수 + if/else 분기
        pattern = "수박", repeat = n // 2
        홀수: pattern * repeat + '수'
        짝수: pattern * repeat

    solution_mine_two: 삼항 연산자로 한 줄 표현
        "수박" * (n // 2) + '수' if n % 2 else "수박" * (n // 2)
        연산자 우선순위: + 가 삼항 연산자보다 높아서 의도대로 파싱됨
        명확성을 위해 괄호 추가 권장

[개선 포인트]
    solution_mine_one: 개선 필요 없음, 명시적 구조로 가독성 우위
    solution_mine_two:
        괄호 없이도 동작하나 명확성을 위해 아래처럼 표현 권장
        ("수박" * (n // 2) + '수') if n % 2 else "수박" * (n // 2)
===================================================================================
[슬라이싱 통일 방식]
    ("수박" * (n // 2 + 1))[:n]
        홀짝 분기 없이 충분히 긴 문자열 생성 후 앞 n글자만 추출
        n // 2 + 1: 짝수/홀수 모두 커버하는 최소 반복 횟수
            n=3: n//2+1=2 → "수박수박"[:3] = "수박수" ✓
            n=4: n//2+1=2 → "수박수박"[:4] = "수박수박" ✓
            n=1: n//2+1=1 → "수박"[:1] = "수" ✓

    Best 대비 특징:
        홀짝 조건문/삼항 연산자 없이 슬라이싱 하나로 처리
        "수박수박수박수"처럼 항상 짝수 단위로 반복 후 n글자 취함
===================================================================================
[복잡도 분석]
    N = n (최대 10,000)

    Mine_one - 시간: O(N) | 공간: O(N) - 문자열 생성 O(N)
    Mine_two - 시간: O(N) | 공간: O(N) - 문자열 생성 O(N)
    Best     - 시간: O(N) | 공간: O(N) - Mine_two와 동일, 주석 보강
    Sub      - 시간: O(N) | 공간: O(N) - 슬라이싱 통일, 문자열 생성 O(N)

    문자열 생성이 지배 → 모두 O(N)
    N ≤ 10,000에서 문자열 곱셈이 실질 비용
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution one - 명시적 변수 + if/else 분기
# =================================================================================
def solution_mine_one(n: int) -> str:
    """
    명시적 변수와 if/else로 홀짝을 분기하는 초기 풀이

    핵심:
        repeat = n // 2: "수박" 반복 횟수
        n % 2:  홀수 True → "수박" * repeat + '수'
                짝수 False → "수박" * repeat
        홀수에서 n // 2 * 2 < n → 나머지 1글자 = '수'
    """
    pattern = "수박"
    repeat = n // 2

    if n % 2:
        return pattern * repeat + '수'   # 홀수: "수박"*repeat + '수'
    else:
        return pattern * repeat          # 짝수: "수박"*repeat


# =================================================================================
# Mine solution two - 삼항 연산자 한 줄 표현
# =================================================================================
def solution_mine_two(n: int) -> str:
    """
    삼항 연산자로 mine_one을 한 줄로 표현한 풀이

    mine_one 대비:
        명시적 변수 제거, 삼항 연산자로 압축
        연산자 우선순위: + 가 삼항 연산자보다 높아 의도대로 파싱
            "수박" * (n//2) + '수' if n%2 else ...
            → ("수박" * (n//2) + '수') if n%2 else ...  (동일)
        명확성 위해 앞 항에 괄호 추가 권장
    """
    return ("수박" * (n // 2) + '수') if n % 2 else "수박" * (n // 2)


# =================================================================================
# Best solution - Mine_two 주석 보강
# =================================================================================
def solution_best(n: int) -> str:
    """
    삼항 연산자로 홀짝을 분기하는 최적 풀이

    mine_two와 동일한 로직, 근거 주석 보강:
        n // 2: "수박" 반복 횟수 (짝수이면 정확, 홀수이면 1 부족)
        n % 2: 홀수이면 마지막 '수' 추가
        괄호로 삼항 연산자 앞 항의 범위를 명확히 표현
    """
    return ("수박" * (n // 2) + '수') if n % 2 else "수박" * (n // 2)


# =================================================================================
# Sub solution - 슬라이싱 통일 방식
# =================================================================================
def solution_sub(n: int) -> str:
    """
    홀짝 분기 없이 슬라이싱으로 통일하는 서브 풀이

    핵심 아이디어:
        n // 2 + 1번 반복 → 항상 n글자 이상의 "수박..." 패턴 생성
        [:n] 슬라이싱으로 앞 n글자만 추출
        홀수/짝수 모두 동일한 코드로 처리

    손 추적:
        n=3: "수박" * 2 = "수박수박", [:3] = "수박수" ✓
        n=4: "수박" * 3 = "수박수박수박", [:4] = "수박수박" ✓
        n=1: "수박" * 1 = "수박", [:1] = "수" ✓

    Best 대비:
        삼항 연산자/조건문 없이 한 표현식으로 처리
        n // 2 + 1번 반복으로 불필요한 문자를 생성 후 버림
        → 최악의 경우 "수박" 1회 더 생성 (상수 추가 비용)
    """
    return ("수박" * (n // 2 + 1))[:n]


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[int, str]] = [
        # (n, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # n=3: repeat=1, 홀수 → "수박" * 1 + '수' = "수박수"
        (3,  "수박수"),
        # n=4: repeat=2, 짝수 → "수박" * 2 = "수박수박"
        (4,  "수박수박"),
        # 추가 케이스:
        # n=1: repeat=0, 홀수 → "수박" * 0 + '수' = "수"
        (1,  "수"),
        # n=2: repeat=1, 짝수 → "수박" * 1 = "수박"
        (2,  "수박"),
        # n=5: repeat=2, 홀수 → "수박" * 2 + '수' = "수박수박수"
        (5,  "수박수박수"),
        # n=6: repeat=3, 짝수 → "수박" * 3 = "수박수박수박"
        (6,  "수박수박수박"),
    ]

    solutions = [
        ("Mine_one (명시적+if/else)", solution_mine_one),
        ("Mine_two (삼항연산자)    ", solution_mine_two),
        ("Best     (삼항연산자)    ", solution_best),
        ("Sub      (슬라이싱)      ", solution_sub),
    ]

    print("=" * 66)
    print(f"{'풀이':<28} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 66)

    for name, func in solutions:
        for idx, (n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<28} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 66)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
