"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 콜라 문제
    유형       : Math
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/132267
    풀이일자   : 2026-07-06
===================================================================================
[문제 요약]
    빈 병 a개를 가져다주면 콜라 b병을 주는 마트
    빈 병 n개로 받을 수 있는 콜라의 총 병 수 반환
    보유 빈 병이 a개 미만이면 거래 불가

    제약 조건
        - 1 ≤ b < a ≤ n ≤ 1,000,000
        - b < a 보장 → 거래마다 병이 반드시 줄어듦 (무한 루프 없음)
        - b < a ≤ n → n < b 케이스 없음
===================================================================================
[입출력 예시]
    a | b | n  | result
    --|---|----|---------
    2 | 1 | 20 | 19
    3 | 1 | 20 | 9
===================================================================================
[내 풀이 — 시뮬레이션]
    solution_mine: while loop + divmod로 매 회차 병 개수 갱신

    매 회차:
        q, r = divmod(bottle, a)  → q: 거래 횟수, r: 남은 병
        받은 콜라: q * b
        다음 병: q * b + r        (받은 콜라 빈병 + 거래 못한 병)
    bottle < a → 종료

    손 추적 (a=2, b=1, n=20):
        20 // 2 = 10, r=0  → +10, bottle=10+0=10
        10 // 2 = 5,  r=0  → +5,  bottle=5+0=5
        5  // 2 = 2,  r=1  → +2,  bottle=2+1=3
        3  // 2 = 1,  r=1  → +1,  bottle=1+1=2
        2  // 2 = 1,  r=0  → +1,  bottle=1+0=1
        1 < 2 → 종료, 총합 = 19 ✓

[ref 풀이 — 수식 O(1)]
    (n - b) // (a - b) * b

    수식 유도:
        핵심 관찰: 거래 1회마다 병이 (a - b)개씩 순 감소
            내는 병: a개, 돌려받는 빈병: b개 → 순 감소: a - b

        거래 횟수 계산:
            마지막 거래에 쓸 a개를 미리 제외 → 나머지 (n - a)개가 줄어드는 동안 거래
            (n - a) // (a - b)번 거래 후 마지막 1회 추가
            총 거래 횟수 = (n - a) // (a - b) + 1

        수식 변환:
            ((n - a) // (a - b) + 1) * b
            = ((n - a) + (a - b)) // (a - b) * b   [+1회를 분자에 합침]
            = (n - b) // (a - b) * b                [n - a + a - b = n - b]

        max(n - b, 0): n < b 방어 코드 (제약상 불발이나 범용성)

    손 추적 (a=2, b=1, n=20):
        (20 - 1) // (2 - 1) * 1 = 19 // 1 * 1 = 19 ✓

    손 추적 (a=3, b=1, n=20):
        (20 - 1) // (3 - 1) * 1 = 19 // 2 * 1 = 9 ✓

[시뮬레이션 vs 수식 비교]
    시뮬레이션:
        직관적, 문제 동작 원리가 코드에 그대로 드러남
        O(log n): bottle이 매 회차 감소, 최대 log_{a/(a-b)}(n)번 반복
        n=1,000,000, a=2, b=1: 최대 약 20번 반복

    수식:
        O(1): 수식 계산 한 번으로 종료
        수식 유도에 수학적 통찰 필요
        조건 변형 문제에 즉시 적용 가능
===================================================================================
[복잡도 분석]
    N = n (최대 1,000,000)

    Mine  - 시간: O(log N) | 공간: O(1) - bottle이 매 회차 (b/a)배로 감소
    Best  - 시간: O(1)     | 공간: O(1) - 수식 계산 1회
    Sub   - 시간: O(log N) | 공간: O(1) - Mine과 동일, 주석 보강

    시뮬레이션 반복 횟수: bottle이 (b/a)배씩 줄어들므로 log_{a/b}(n)에 수렴
    n=1,000,000: 최대 수십 번 반복 → 사실상 O(1)에 가까움
    두 풀이 모두 제약 내에서 충분히 빠름
"""

import time


# =================================================================================
# Mine solution - 시뮬레이션 (while + divmod)
# =================================================================================
def solution_mine(a: int, b: int, n: int) -> int:
    """
    매 회차 병 개수를 갱신하며 받은 콜라를 누적하는 시뮬레이션 풀이

    핵심:
        divmod(bottle, a): 거래 횟수(q)와 남은 병(r) 동시 계산
        q * b: 이번 회차에 받은 콜라 수
        q * b + r: 다음 회차 병 수 (받은 콜라 빈병 + 거래 못한 병)
        bottle < a: 거래 불가 → 종료

    b < a 보장으로 무한 루프 없음:
        매 회차 bottle = q*b + r
        q*b = (bottle // a) * b < bottle (∵ b < a)
        r = bottle % a < a
        → bottle이 단조 감소 → 종료 보장
    """
    answer = 0
    bottle = n

    while bottle >= a:
        q, r = divmod(bottle, a)
        answer += q * b             # 이번 회차 받은 콜라 누적
        bottle = q * b + r          # 다음 회차 병 수 갱신

    return answer


# =================================================================================
# Best solution - 수식 O(1)
# =================================================================================
def solution_best(a: int, b: int, n: int) -> int:
    """
    거래 횟수를 수식으로 직접 계산하는 O(1) 최적 풀이

    수식 유도:
        거래 1회 순 감소: a - b (내는 a개 - 돌려받는 b개)
        총 거래 횟수: (n - a) // (a - b) + 1
            n - a: 마지막 거래에 쓸 a개 미리 제외한 감소 가능량
            // (a-b): 감소량을 1회 순 감소량으로 나눔
            + 1: 마지막 거래 포함

        횟수를 분자로 정리:
            ((n - a) // (a - b) + 1) * b
            = (n - a + (a - b)) // (a - b) * b
            = (n - b) // (a - b) * b

    max(n - b, 0): n < b 방어 코드 (제약상 b < a ≤ n이므로 불발)
    """
    return max(n - b, 0) // (a - b) * b


# =================================================================================
# Sub solution - 시뮬레이션 (mine 주석 보강)
# =================================================================================
def solution_sub(a: int, b: int, n: int) -> int:
    """
    시뮬레이션으로 콜라 거래를 직접 재현하는 서브 풀이

    Best 대비 특징:
        수식 유도 없이 문제 동작 원리를 코드에 직접 표현
        각 회차의 거래와 병 개수 변화가 명시적으로 드러남
        O(log N)이나 n=1,000,000에서도 수십 번 반복으로 빠름
    """
    answer = 0
    bottle = n

    while bottle >= a:
        q, r = divmod(bottle, a)
        answer += q * b
        bottle = q * b + r

    return answer


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: list[tuple[int, int, int, int]] = [
        # (a, b, n, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # a=2, b=1, n=20: 시뮬레이션 5회 → 10+5+2+1+1=19
        (2, 1, 20, 19),
        # a=3, b=1, n=20: 시뮬레이션 3회 → 6+2+1=9
        (3, 1, 20, 9),
        # 추가 케이스:
        # a=2, b=1, n=2: 최소 케이스, 2개로 1회 거래 → 1병
        (2, 1, 2,  1),
        # a=3, b=2, n=9:
        #   9//3=3, r=0 → +6, bottle=6+0=6
        #   6//3=2, r=0 → +4, bottle=4+0=4
        #   4//3=1, r=1 → +2, bottle=2+1=3
        #   3//3=1, r=0 → +2, bottle=2+0=2
        #   2 < 3 → 종료, 총합 = 6+4+2+2 = 14
        (3, 2, 9,  14),
        # 대규모: a=2, b=1, n=1000000
        (2, 1, 1_000_000, 999_999),
    ]

    solutions = [
        ("Mine (시뮬레이션) ", solution_mine),
        ("Best (수식 O(1)) ", solution_best),
        ("Sub  (시뮬레이션) ", solution_sub),
    ]

    # 워밍업 스텝
    _a, _b, _n, _ = test_cases[0]
    for _, func in solutions:
        func(_a, _b, _n)

    print("=" * 62)
    print(f"{'풀이':<20} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (a, b, n, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(a, b, n)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<20} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
