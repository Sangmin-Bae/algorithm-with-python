"""
===================================================================================
[문제 정보]
    사이트     : Programmers
    레벨       : Level 1
    문제명     : 핸드폰 번호 가리기
    유형       : String
    링크       : https://school.programmers.co.kr/learn/courses/30/lessons/12948
    풀이일자   : 2026-06-17
===================================================================================
[문제 요약]
    전화번호 문자열 phone_number에서 뒷 4자리를 제외한 나머지를 '*'로 가린 문자열 반환

    제약 조건
        - phone_number 길이: 4 이상 20 이하
        - 길이 4일 때 phone_number[:-4] = '' → '*' * 0 = '' → 정상 동작
===================================================================================
[입출력 예시]
    phone_number  | return
    --------------|------------------
    "01033334444" | "***4444"    (앞 7자리 → '*' × 7)
    "027778888"   | "*****8888"  (앞 5자리 → '*' × 5)
===================================================================================
[내 초기 풀이]
    solution_mine: 음수 인덱스 슬라이싱 + 문자열 곱셈 + 문자열 덧셈

    phone_number[:-4]: 뒷 4자리를 제외한 앞 부분 슬라이싱
    len(phone_number[:-4]): 가릴 자리 수 계산
    '*' * len(...): 가릴 자리 수만큼 '*' 반복 생성
    + phone_number[-4:]: 끝 4자리 문자열 결합

[개선 포인트]
    solution_mine:
        len(phone_number[:-4]): 슬라이싱으로 중간 문자열 객체 생성 후 len() 계산
        → len(phone_number) - 4로 슬라이싱 없이 O(1) 길이 계산 가능
        → 중간 문자열 객체 생성 비용 절감
        기능은 동일, 미세한 공간 효율 차이
===================================================================================
[Python 문자열 연산 정리]
    음수 인덱스:
        phone_number[-4:]: 뒤에서 4번째부터 끝까지 (끝 4자리)
        phone_number[:-4]: 처음부터 뒤에서 4번째 전까지 (끝 4자리 제외)

    문자열 곱셈:
        '*' * n: '*'를 n번 반복한 문자열 생성
        '*' * 0: '' (빈 문자열) → 길이 4인 입력에서도 정상 동작

    문자열 덧셈:
        "abc" + "def": "abcdef" (이어붙이기)

    len() 연산:
        len(phone_number): 전체 길이 O(1)
        len(phone_number[:-4]): 슬라이싱 O(N) 후 len O(1) → 불필요한 객체 생성
        len(phone_number) - 4: 슬라이싱 없이 O(1) 직접 계산
===================================================================================
[복잡도 분석]
    N = len(phone_number) (최대 20, 사실상 상수)

    Mine - 시간: O(N) | 공간: O(N) - 슬라이싱 중간 객체 + 결과 문자열
    Best - 시간: O(N) | 공간: O(N) - Mine과 동일, 주석 보강
    Sub  - 시간: O(N) | 공간: O(N) - 슬라이싱 중간 객체 없음, 결과 문자열만

    N ≤ 20 고정 → 모든 풀이 실질적으로 O(1)에 수렴
    문자열 곱셈 '*' * k: 길이 k 문자열 생성 O(k) = O(N)
"""

import time
from typing import List, Tuple


# =================================================================================
# Mine solution - 음수 인덱스 슬라이싱 + 문자열 곱셈
# =================================================================================
def solution_mine(phone_number: str) -> str:
    """
    음수 인덱스 슬라이싱으로 앞뒤를 분리하고 문자열 연산으로 결합하는 초기 풀이

    핵심:
        phone_number[:-4]: 뒷 4자리 제외한 앞 부분 (길이 4이면 빈 문자열)
        len(phone_number[:-4]): 가릴 자리 수
        '*' * len(...): 가릴 자리만큼 '*' 생성
        + phone_number[-4:]: 끝 4자리 결합

    개선 가능:
        len(phone_number[:-4]) → len(phone_number) - 4
        슬라이싱 없이 길이 직접 계산 → 중간 문자열 객체 생성 불필요
    """
    return '*' * len(phone_number[:-4]) + phone_number[-4:]


# =================================================================================
# Best solution - Mine 주석 보강
# =================================================================================
def solution_best(phone_number: str) -> str:
    """
    음수 인덱스 슬라이싱으로 앞뒤를 분리하는 최적 풀이

    Mine과 동일한 로직, 근거 주석 보강:
        phone_number[:-4]: 끝 4자리 기준으로 분리하는 의도가 명확
        음수 인덱스 활용으로 전체 길이를 몰라도 뒷자리 기준 접근 가능
        길이 4인 최소 입력: phone_number[:-4]='' → '*'*0='' → 정상 동작
    """
    return '*' * len(phone_number[:-4]) + phone_number[-4:]  # 앞부분 '*' + 끝 4자리


# =================================================================================
# Sub solution - len() - 4 직접 계산
# =================================================================================
def solution_sub(phone_number: str) -> str:
    """
    슬라이싱 없이 길이 연산으로 가릴 자리 수를 계산하는 서브 풀이

    Best 대비 특징:
        len(phone_number) - 4: 슬라이싱 없이 O(1)로 가릴 자리 수 직접 계산
        phone_number[:-4] 중간 문자열 객체 생성 없음 → 미세한 공간 절감
        phone_number[-4:]: 끝 4자리는 동일하게 슬라이싱

    N ≤ 20 고정이라 실질적 성능 차이 없음
    의미: 슬라이싱 목적이 값이 아닌 길이만 필요할 때 len() 직접 계산이 더 적합
    """
    return '*' * (len(phone_number) - 4) + phone_number[-4:]


# =================================================================================
# 각 풀이 결과 비교 검증 + 성능 측정
# =================================================================================
def solution_comparison():
    """각 풀이의 정확성과 성능을 동시에 검증"""

    test_cases: List[Tuple[str, str]] = [
        # (phone_number, 기댓값)
        # 손 추적 (프로그래머스 공식 예시):
        # "01033334444": len=11, 앞 7자리 '*'×7 + "4444" = "*******4444"
        ("01033334444", "*******4444"),
        # "027778888": len=9, 앞 5자리 '*'×5 + "8888" = "*****8888"
        ("027778888",   "*****8888"),
        # 추가 케이스:
        # "1234": len=4, 앞 0자리 '*'×0='' + "1234" = "1234"
        #   길이 4 최소 입력 → phone_number[:-4]='' 경계 케이스
        ("1234",        "1234"),
        # "12345678901234567890": len=20 최대 입력
        #   앞 16자리 '*'×16 + "7890"
        ("12345678901234567890", "****************7890"),
    ]

    solutions = [
        ("Mine (슬라이싱+len)  ", solution_mine),
        ("Best (슬라이싱+len)  ", solution_best),
        ("Sub  (len-4 직접계산)", solution_sub),
    ]

    print("=" * 62)
    print(f"{'풀이':<24} {'케이스':<6} {'결과':<8} {'소요시간':>10}")
    print("=" * 62)

    for name, func in solutions:
        for idx, (phone_number, expected) in enumerate(test_cases, 1):
            start = time.perf_counter()
            output = func(phone_number)
            elapsed = time.perf_counter() - start

            status = "PASS" if output == expected else "FAIL"
            print(f"{name:<24} TC{idx:<5} {status:<8} {elapsed * 1000:>8.4f}ms")
        print("-" * 62)


# =================================================================================
# 실행 진입점
# =================================================================================
if __name__ == "__main__":
    solution_comparison()
